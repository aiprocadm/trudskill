import type { ReactElement } from 'react';

/**
 * `TXT-004`, правило продукта «экран не врёт» · раздел работает вполсилы.
 *
 * Есть экраны, которые выглядят готовыми, но серверной части у них нет: введённое живёт
 * в памяти страницы и пропадает при перезагрузке. Человек об этом не догадается — он
 * заполнил форму, увидел строку в таблице и ушёл, считая работу сделанной.
 *
 * Молчать здесь нельзя, а прятать раздел — не всегда правильно: по нему ходят по прямым
 * ссылкам, и решение «оставить как заглушку» уже принято (`ia-architecture`,
 * `HIDDEN_STUB_ROUTES`). Поэтому раздел честно говорит о себе сам, одинаковыми словами
 * на всех таких экранах.
 */
export const PreviewNotice = ({
  what,
  instead
}: {
  /** Что именно не сохраняется — своими словами: «шаблоны форм», «сделки». */
  what: string;
  /** Куда пойти за рабочим способом, если он есть. */
  instead?: string;
}): ReactElement => (
  <p className="ui-callout ui-callout--warning" role="status">
    <strong>Раздел готовится.</strong> {what} пока не сохраняются: они исчезнут при перезагрузке
    страницы.
    {instead ? ` ${instead}` : ''}
  </p>
);
