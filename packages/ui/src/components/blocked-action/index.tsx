import type { ReactElement } from 'react';

/**
 * Кнопка, выключенная ПО УСЛОВИЮ, обязана сказать, чего не хватает (ТЗ 5.8 / Э8).
 *
 * Разница между «занято» и «нельзя». Занятая кнопка — операция идёт, объяснять нечего:
 * человек сам только что нажал, и об этом говорит крутилка. Заблокированная — другое дело:
 * человек жмёт, ничего не происходит, и причина ему неизвестна. «Отправить на проверку» без
 * загруженного селфи, «Провести тест» без выбранного слушателя, «Назначить курс» без курса —
 * во всех трёх случаях экран молчал (журнал 465).
 *
 * Почему не только всплывающая подсказка. `title` показывается при наведении мышью —
 * то есть не показывается ни на телефоне, ни человеку, который ходит по странице с
 * клавиатуры. Поэтому причина стоит ещё и ВИДИМОЙ строкой рядом с кнопкой и связана с ней
 * через `aria-describedby`: читалка экрана прочитает её вместе с кнопкой.
 */

/** Идентификатор видимой строки-причины: он же уходит в `aria-describedby` кнопки. */
export const blockedHintId = (key: string): string => `ui-blocked-${key}`;

/**
 * Свойства кнопки, выключенной по условию. Причина задана — кнопка выключается И объясняет
 * себя; причина не задана — свойств нет вовсе, и кнопка живёт своей жизнью (в том числе может
 * быть выключена по занятости отдельно).
 */
export const blockedProps = (
  key: string,
  reason: string | undefined
): { disabled?: true; title?: string; 'aria-describedby'?: string } =>
  reason ? { disabled: true, title: reason, 'aria-describedby': blockedHintId(key) } : {};

/**
 * Видимая строка «чего не хватает» рядом с кнопкой. Ничего не рисуется, когда причины нет:
 * пустая строка сдвигала бы раскладку каждый раз, когда условие выполнено.
 */
export const BlockedHint = ({
  hintKey,
  reason
}: {
  hintKey: string;
  reason: string | undefined;
}): ReactElement | null =>
  reason === undefined ? null : (
    <p className="ui-hint ui-hint--blocked" id={blockedHintId(hintKey)} role="note">
      {reason}
    </p>
  );
