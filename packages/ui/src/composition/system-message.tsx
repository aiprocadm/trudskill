import type { ReactElement, ReactNode } from 'react';

/**
 * Страница-сообщение системы: отказ в доступе, «не найдено», сбой сервера, нет сети (ТЗ 2.1/Б3).
 *
 * Как было. Отказ в доступе показывал голое «403 / У вас недостаточно прав для просмотра этой
 * страницы / Вернуться на главную»: код вместо объяснения, ни следующего шага, ни адресата.
 * Человек упирался в стену и не понимал даже, к кому идти. Страница «нет сети» была свёрстана
 * встроенными стилями — мимо всех токенов оформления.
 *
 * ТЗ требует шаблон из трёх частей: **что случилось → что делать сейчас → к кому идти.** Он и
 * зашит в устройство компонента, а не оставлен на совесть каждой страницы: `what` и `next`
 * обязательны, `whom` — там, где адресат вообще есть (у «нет сети» его нет: связь чинится не
 * через администратора).
 *
 * Код ответа в заголовок НЕ выносится: «403» человеку не сообщает ничего (правило продукта №4).
 * Он живёт в `details` — под спойлером, для поддержки. Пустого спойлера не бывает: обещание
 * подробностей, за которым ничего нет, обманывает дважды.
 */
export const SystemMessage = ({
  title,
  what,
  next,
  whom,
  details,
  action
}: {
  /** Что случилось — человеческим языком, а не кодом. */
  title: string;
  what: string;
  /** Что делать прямо сейчас. */
  next: string;
  /** К кому идти, если своими силами не выходит. */
  whom?: string;
  /** Техническое: код ответа, номер запроса. Только под спойлер. */
  details?: string;
  /** Первичное действие: «Повторить», «Написать администратору». */
  action?: ReactNode;
}): ReactElement => (
  <section className="ui-system-message" role="status">
    <h1 className="ui-section-title">{title}</h1>
    <p className="ui-prose">{what}</p>
    <p className="ui-prose">{next}</p>
    {whom ? <p className="ui-prose-muted">{whom}</p> : null}
    {action ? <div className="ui-stack">{action}</div> : null}
    {details ? (
      <details>
        <summary>Подробности для поддержки</summary>
        <p className="ui-prose-muted">{details}</p>
      </details>
    ) : null}
  </section>
);
