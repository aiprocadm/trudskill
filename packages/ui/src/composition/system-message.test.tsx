import { describe, expect, it } from 'vitest';

import { SystemMessage } from './system-message.js';

/**
 * Страница-сообщение системы: что случилось → что делать → к кому идти (ТЗ 2.1 / Б3).
 *
 * Как было: отказ в доступе показывал голое «403 / У вас недостаточно прав для просмотра этой
 * страницы / Вернуться на главную». Ни объяснения, ни следующего шага, ни адресата. Человек
 * упирался в стену и не понимал даже, к кому идти.
 *
 * ТЗ требует шаблон из трёх частей. Здесь он и закреплён: без «что делать» и без адресата
 * компонент не собирается — это не украшение, а то, ради чего страница существует.
 */

/**
 * Весь показанный текст одной строкой.
 *
 * Компонент вызывается как обычная функция и возвращает дерево элементов — React Testing Library
 * в проекте нет (CLAUDE.md). Для этих проверок обход дерева не нужен: важно, что текст ЕСТЬ и
 * что запрещённого текста НЕТ, а не в каком именно узле он лежит.
 */
const text = (node: unknown): string => JSON.stringify(node);

describe('SystemMessage — страница-сообщение системы', () => {
  it('говорит, ЧТО случилось, — заголовком, а не кодом', () => {
    const shown = text(
      SystemMessage({
        title: 'Этот раздел вам недоступен',
        what: 'Раздел открыт администратору центра.',
        next: 'Вернитесь на главную или откройте другой раздел.',
        whom: 'Если раздел нужен вам в работе — напишите администратору центра.'
      })
    );

    expect(shown).toContain('Этот раздел вам недоступен');
    expect(shown, 'код ответа человеку ничего не сообщает — он не заголовок').not.toContain('403');
  });

  it('несёт все три части шаблона', () => {
    const shown = text(
      SystemMessage({
        title: 'Страница не найдена',
        what: 'Такой страницы нет.',
        next: 'Проверьте адрес или вернитесь на главную.',
        whom: 'Если пришли по ссылке из письма — попросите прислать новую.'
      })
    );

    expect(shown).toContain('Такой страницы нет.');
    expect(shown).toContain('Проверьте адрес');
    expect(shown).toContain('попросите прислать новую');
  });

  it('технический код прячется под спойлер, а не в лицо', () => {
    const shown = text(
      SystemMessage({
        title: 'Не удалось загрузить',
        what: 'Сервер не ответил.',
        next: 'Нажмите «Повторить».',
        whom: 'Если не помогает — сообщите администратору центра.',
        details: 'HTTP 503, запрос req_42'
      })
    );

    expect(shown, 'подробности нужны поддержке').toContain('req_42');
    expect(shown, 'и они обязаны быть спрятаны под спойлер').toContain('Подробности');
  });

  it('без подробностей спойлера нет — пустой спойлер обманывает', () => {
    const shown = text(
      SystemMessage({ title: 'Нет сети', what: 'Соединения нет.', next: 'Повторите позже.' })
    );
    expect(shown).not.toContain('Подробности');
  });

  it('действие показывается там, где его ищут глазом', () => {
    const shown = text(
      SystemMessage({
        title: 'Не удалось загрузить',
        what: 'Сервер не ответил.',
        next: 'Нажмите «Повторить».',
        action: { kind: 'element', marker: 'ДЕЙСТВИЕ' } as never
      })
    );
    expect(shown).toContain('ДЕЙСТВИЕ');
  });
});
