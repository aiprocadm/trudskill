import type { PropsWithChildren, ReactElement } from 'react';

/**
 * `GOAL-3` · «блоков на первом экране: 5 → ≤3».
 *
 * Цель говорит про **первый экран** — то, что человек видит, не прокручивая. До этой
 * обёртки граница «до сгиба / ниже сгиба» существовала только в комментарии внутри
 * разметки (`{/* Зона 3 — ниже сгиба *\/}`), а комментарий ничего не гарантирует:
 * следующая правка добавляет блок выше него, и цель тихо перестаёт выполняться.
 *
 * Обёртка делает границу данными. Сторож `home-screen-density.e2e.test.ts` считает
 * блоки домашнего экрана и требует, чтобы выше обёртки их было не больше трёх.
 *
 * Визуально она ничего не меняет — это разметочный контейнер, наследующий сетку
 * страницы. Смысл — не в отступах, а в том, что решение «это подробности, их можно
 * не показывать сразу» записано в коде и проверяется.
 */
export const BelowFold = ({ children }: PropsWithChildren): ReactElement => (
  <div className="ui-below-fold" data-fold="below">
    {children}
  </div>
);
