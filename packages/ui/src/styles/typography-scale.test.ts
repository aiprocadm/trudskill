import { describe, expect, it } from 'vitest';

import { uiGlobalStyles } from './index.js';
import { baseVars } from '../tokens/index.js';

/**
 * `UI-011`, `UI-012`, `UI-013`, `UI-017` — типографическая шкала и ширина строки.
 *
 * Зачем шкала. Когда размеры букв берутся «на глаз», на соседних экранах одно и то же по
 * смыслу выглядит по-разному, а разницу в один пиксель никто не замечает при правке — она
 * копится. Здесь так и вышло: около полусотни мест задавали размер сами, причём в разных
 * единицах и вразнобой — `13px`, `14px`, `0.95rem`, `0.97rem`, `1.05rem`, `1.15rem`.
 * Отличить `0.95rem` от `0.97rem` глазом невозможно, а смысл у них разный.
 *
 * Зачем ширина строки (`--ui-measure`). Строка во всю ширину широкого экрана читается
 * плохо: глаз теряет начало следующей строки. Типографская норма — 60–75 знаков; для
 * пояснений и подсказок это не украшение, а разница между «прочитал» и «пробежал глазами».
 *
 * Зачем верхние ступени (`2xl`, `3xl`). Заголовок героя набирался `clamp()` до 33 пикселей,
 * тогда как потолок шкалы был 22 — то есть самый крупный текст продукта жил ВНЕ шкалы и
 * менялся отдельно от всего остального.
 */

/** Размеры, объявленные прямо в стилях (мимо токенов). */
const literalFontSizes = (): string[] =>
  (uiGlobalStyles.match(/font-size:\s*[^;}]+/g) ?? [])
    .map((d) => d.replace(/font-size:\s*/, '').trim())
    .filter((value) => !value.startsWith('var(--ui-font-size'))
    // clamp() у заголовка героя разбирается отдельной проверкой: он обязан опираться на токен.
    .filter((value) => !value.startsWith('clamp('))
    .filter((value) => value !== 'inherit')
    /*
     * `em` — законное исключение: это размер ОТНОСИТЕЛЬНО родителя, а не своя величина.
     * Так набрана стрелка в кнопке героя: она на 15% крупнее текста кнопки и обязана расти
     * вместе с ним. Подставить туда ступень шкалы — значит зафиксировать стрелку и рассогласовать
     * её с текстом при любом изменении размера кнопки.
     *
     * Проверка ловит `px` и `rem` — то есть абсолютные величины, заданные мимо шкалы.
     */
    .filter((value) => !/^\d*\.?\d+em$/.test(value));

describe('UI-011: шкала размеров', () => {
  it('шкала доходит до крупных ступеней', () => {
    expect(baseVars['--ui-font-size-2xl'], 'нет ступени 2xl').toBe('28px');
    expect(baseVars['--ui-font-size-3xl'], 'нет ступени 3xl').toBe('34px');
  });

  it('ступени возрастают и не повторяются', () => {
    // Ключ собирается из строки, поэтому словарь читаем как словарь: без этого
    // индекс по вычисленному ключу молча становится `any`.
    const vars = baseVars as Record<string, string | undefined>;
    const steps = ['xs', 'sm', 'md', 'lg', 'xl', '2xl', '3xl'].map((key) =>
      Number.parseInt(vars[`--ui-font-size-${key}`] ?? '0', 10)
    );
    for (let i = 1; i < steps.length; i += 1) {
      expect(steps[i]!, `ступень ${i} не больше предыдущей`).toBeGreaterThan(steps[i - 1]!);
    }
  });

  /*
   * Ключевая проверка. Размер, записанный числом, — это выход из шкалы: он не меняется
   * вместе с ней и не виден при сравнении экранов.
   */
  it('в стилях нет размеров мимо шкалы', () => {
    expect(
      literalFontSizes(),
      'Размер шрифта задан числом вместо ступени шкалы. Так на соседних экранах одно и ' +
        'то же по смыслу выглядит по-разному, а разницу в пиксель никто не замечает. ' +
        'Используйте var(--ui-font-size-*).'
    ).toEqual([]);
  });
});

describe('UI-012/UI-017: ширина строки и полосы содержимого', () => {
  it('токены ширины объявлены', () => {
    expect(baseVars['--ui-measure'], 'нет --ui-measure (ширина строки текста)').toBeDefined();
    expect(baseVars['--ui-measure-narrow'], 'нет --ui-measure-narrow').toBeDefined();
    expect(baseVars['--ui-content-max'], 'нет --ui-content-max').toBe('1280px');
    expect(baseVars['--ui-form-max'], 'нет --ui-form-max').toBe('720px');
  });

  /*
   * Норма чтения — 60–75 знаков в строке. Значение задаётся в `ch`, потому что это ширина
   * символа текущего шрифта: при смене шрифта норма сохранится сама.
   */
  it('ширина строки задана в знаках и лежит в норме чтения', () => {
    const measure = String(baseVars['--ui-measure']);
    expect(measure).toMatch(/^\d+ch$/);
    const value = Number.parseInt(measure, 10);
    expect(value).toBeGreaterThanOrEqual(60);
    expect(value).toBeLessThanOrEqual(75);
  });

  it('длинный текст ограничен по ширине', () => {
    expect(
      uiGlobalStyles,
      'Токен ширины строки объявлен, но нигде не применён — значит пояснения по-прежнему ' +
        'растягиваются во всю ширину экрана и читаются плохо.'
    ).toContain('var(--ui-measure)');
  });
});

describe('UI-013: заголовок героя опирается на шкалу', () => {
  it('размер заголовка героя растёт до верхней ступени шкалы', () => {
    const hero = uiGlobalStyles.match(/\.ui-hero__title\s*\{[^}]*\}/)?.[0] ?? '';
    expect(hero, 'правило .ui-hero__title не найдено').not.toBe('');
    expect(
      hero,
      'Заголовок героя набирается размером вне шкалы: самый крупный текст продукта ' +
        'меняется отдельно от всего остального.'
    ).toContain('var(--ui-font-size-3xl)');
  });
});
