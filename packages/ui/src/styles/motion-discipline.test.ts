import { describe, expect, it } from 'vitest';

import { uiGlobalStyles } from './index.js';

/**
 * `UI-028`, `UI-029`, `UI-030` — дисциплина движения.
 *
 * Зачем это нужно словами. Плавные переходы приятны большинству, но части людей движение
 * на экране мешает по-настоящему: при вестибулярных нарушениях, склонности к укачиванию и
 * мигрени оно вызывает тошноту и головокружение. Поэтому в системах есть настройка
 * «поменьше движения», и браузер сообщает о ней странице. Уважать её — не любезность,
 * а требование доступности.
 *
 * Что было не так. Плавное появление блоков страницы завёрнуто правильно, а вот
 * `prefers-reduced-motion: reduce` отключал РОВНО ОДИН переход — шеврон в боковом меню.
 * Остальные пятнадцать (кнопки, поля, панели, полоса прогресса) продолжали двигаться, и
 * человек, попросивший систему не двигать картинку, всё равно получал движение.
 *
 * Второе: длительности были записаны числами прямо в стилях, вразнобой — `.15s`, `0.15s`,
 * `.18s`, `0.2s`, `.4s`. Разнобой не даёт ни менять скорость разом, ни проверить её.
 */

/** Все объявления переходов и анимаций в слоях стилей. */
const declarations = (property: 'transition' | 'animation'): string[] =>
  (uiGlobalStyles.match(new RegExp(`${property}[^:;{}]*:[^;}]+`, 'g')) ?? []).map((d) => d.trim());

describe('UI-028: длительность и плавность задаются токенами', () => {
  it('токены движения объявлены', () => {
    for (const token of ['--ui-duration-fast', '--ui-duration-base', '--ui-ease']) {
      expect(uiGlobalStyles, `нет токена ${token}`).toContain(token);
    }
  });

  /*
   * Ключевая проверка. Число секунд прямо в стиле — это и разнобой, и невозможность
   * поменять скорость разом. Исключение — `0s`: так переход именно ОТКЛЮЧАЮТ.
   */
  it('в переходах нет захардкоженных длительностей', () => {
    const hardcoded = declarations('transition').filter((d) =>
      /(?:^|[\s,:])0?\.\d+s|(?:^|[\s,:])[1-9]\d*(?:\.\d+)?s/.test(d)
    );
    expect(
      hardcoded,
      'Длительность записана числом вместо токена: поменять скорость разом уже нельзя, ' +
        'а разнобой (.15s против 0.15s) не виден глазом. Используйте var(--ui-duration-*).'
    ).toEqual([]);
  });

  it('в анимациях нет захардкоженных длительностей', () => {
    const hardcoded = declarations('animation').filter(
      (d) => !d.includes('animation-delay') && /(?:^|[\s,:])0?\.\d+s/.test(d)
    );
    expect(hardcoded).toEqual([]);
  });
});

describe('UI-030: настройка «меньше движения» уважается везде', () => {
  it('есть общий блок, отключающий движение', () => {
    expect(
      uiGlobalStyles,
      'Нет правила для prefers-reduced-motion: reduce — человек, попросивший систему ' +
        'не двигать картинку, всё равно получит движение.'
    ).toMatch(/@media\s*\(\s*prefers-reduced-motion:\s*reduce\s*\)/);
  });

  /*
   * Проверяем не наличие блока, а его ОХВАТ: раньше он был, но гасил один-единственный
   * элемент. Правило обязано действовать на всё, а не на избранное.
   */
  it('блок гасит движение у всех элементов, а не у одного', () => {
    const block = uiGlobalStyles.match(
      /@media\s*\(\s*prefers-reduced-motion:\s*reduce\s*\)\s*\{([\s\S]*?)\n\}/
    );
    expect(block, 'блок reduced-motion не найден').not.toBeNull();
    const body = block![1]!;
    expect(
      body,
      'Правило написано под конкретный класс. Так гасится один элемент, а остальные ' +
        'продолжают двигаться — именно этим и была беда до UI-030.'
    ).toMatch(/\*\s*,|\*\s*\{|\*,\s*\*::/);
    expect(body).toContain('transition-duration');
    expect(body).toContain('animation-duration');
  });

  /*
   * Плавное появление блоков страницы обязано остаться под `no-preference`: включать его
   * и тут же гасить — значит полагаться на порядок правил, а он легко ломается.
   */
  it('появление блоков страницы включается только при отсутствии запрета', () => {
    expect(uiGlobalStyles).toMatch(/@media\s*\(\s*prefers-reduced-motion:\s*no-preference\s*\)/);
  });
});

describe('UI-029: движение не подменяет данные', () => {
  /*
   * Требование: анимация допустима для появления, наведения, раскрытия и подсказки —
   * но НЕ для данных и не для состояния загрузки. Бесконечно крутящийся индикатор поверх
   * таблицы и «пульсирующие» строки мешают читать и сбивают тех, кому движение противопоказано.
   */
  it('скелетон загрузки не мерцает', () => {
    expect(
      uiGlobalStyles,
      'Вернулась бегущая подсветка скелетона. Это анимация ДАННЫХ: она не заканчивается ' +
        'никогда и мешает тем, кому движение противопоказано, а смысл скелетона — ' +
        'показать форму будущего содержимого, а не мерцать.'
    ).not.toContain('ui-skeleton-shimmer');
  });

  /*
   * Бесконечное движение допустимо ровно в одном случае: когда оно объявлено ВНУТРИ блока
   * «движение разрешено». Тогда человек, отключивший анимацию, его просто не увидит.
   *
   * Первая редакция этой проверки запрещала `infinite` вообще и краснела на крутилке
   * кнопки — а крутилка там единственный признак того, что кнопка занята. Грубый запрет
   * пришлось бы отключить при первой правке, поэтому инвариант уточнён до точного.
   */
  it('бесконечная анимация живёт только там, где движение разрешено', () => {
    const guarded = uiGlobalStyles.match(
      /@media\s*\(\s*prefers-reduced-motion:\s*no-preference\s*\)\s*\{[\s\S]*?\n\}/g
    );
    const guardedText = (guarded ?? []).join('\n');
    const unguarded = declarations('animation')
      .filter((d) => d.includes('infinite'))
      .filter((d) => !guardedText.includes(d));

    expect(
      unguarded,
      'Бесконечная анимация объявлена вне блока «движение разрешено»: тот, кто просил ' +
        'систему не двигать картинку, всё равно её увидит. Заверните объявление в ' +
        '@media (prefers-reduced-motion: no-preference).'
    ).toEqual([]);
  });
});
