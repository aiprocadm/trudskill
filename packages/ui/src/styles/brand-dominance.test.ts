import { describe, expect, it } from 'vitest';

import { uiGlobalStyles } from './index.js';
import { darkThemeVars, lightThemeVars } from '../tokens/index.js';

/**
 * Индиго — доминанта, коралл — редкий акцент (ТЗ «Стабилизация, UX и развитие», 7.4 / В4).
 *
 * **Что было.** Кораллом красилась КАЖДАЯ первичная кнопка на каждом экране — в формах, в
 * диалогах, в пустых состояниях, в модальных окнах. Акцент, который стоит везде, акцентом
 * быть перестаёт: глаз к нему привыкает и больше не отличает главное от обычного. Заодно у
 * коралла было ДВЕ дороги — `--ui-accent-*` и `--ui-hero-cta-*` с теми же значениями, которые
 * приходилось держать в согласии вручную (журнал 566).
 *
 * **Что закреплено.** Первичная кнопка — фирменный индиго. Коралл остался ровно за одним
 * местом: призывом к действию в блоке «Следующий шаг», то есть за главным делом дня.
 *
 * **Почему сторожем, а не разовой правкой.** Кораллу свойственно расползаться: он яркий, и
 * каждому новому экрану хочется «выделить свою кнопку». Через полгода без сторожа он снова
 * окажется на всех кнопках подряд.
 */

/** Правила, где цвет стоит ФОНОМ (а не рамкой, полосой прокрутки или тенью). */
const backgroundRules = (token: string): string[] =>
  (uiGlobalStyles.match(/[^{}]+{[^}]*}/g) ?? []).filter((rule) =>
    new RegExp(`background(?:-color)?:\\s*var\\(${token}\\)`).test(rule)
  );

describe('коралл — редкий акцент (ТЗ 7.4)', () => {
  it('коралл стоит фоном ровно в одном месте', () => {
    /*
     * Считаем фон, а не любое упоминание: рамка и подчёркивание того же цвета — это не
     * «кнопка кричит», а деталь. Кричит именно заливка.
     */
    const rules = backgroundRules('--ui-accent-600');
    expect(
      rules.map((rule) => rule.split('{')[0]?.trim()),
      'коралл снова расползся по кнопкам — акцент, который везде, уже не акцент'
    ).toHaveLength(1);
    expect(rules[0]).toContain('ui-hero__cta');
  });

  it('первичная кнопка красится фирменным цветом, а не кораллом', () => {
    /*
     * Берём правило, посвящённое ИМЕННО первичной кнопке: селектор начинается с неё. Общее
     * правило всех кнопок тоже перечисляет `.ui-button--primary` в списке, и по одному
     * вхождению класса сторож брал не тот блок — поймано на себе.
     */
    const selectorOf = (rule: string): string => {
      /* Перед селектором может стоять комментарий — берём последнюю строку до скобки. */
      const head = (rule.split('{')[0] ?? '').trim().split('\n');
      return (head[head.length - 1] ?? '').trim();
    };
    const primary = (uiGlobalStyles.match(/[^{}]+{[^}]*}/g) ?? []).find((rule) => {
      const selector = selectorOf(rule);
      return selector.startsWith('.ui-button--primary') && !selector.includes(':hover');
    });
    expect(primary, 'правило первичной кнопки не найдено').toBeDefined();
    expect(primary).toMatch(/background:\s*var\(--ui-brand-600\)/);
    expect(primary, 'текст считается по фирменному цвету центра').toMatch(
      /color:\s*var\(--ui-on-brand\)/
    );
  });

  it('у коралла одна дорога, а не две', () => {
    /*
     * Отдельные `--ui-hero-cta-*` повторяли значения акцента. Два места для одного цвета — это
     * место, где цвет однажды разойдётся сам с собой: центр перекрашивает акцент, а кнопка
     * «Следующий шаг» остаётся прежней.
     */
    for (const vars of [lightThemeVars, darkThemeVars]) {
      expect(
        Object.keys(vars).filter((key) => key.startsWith('--ui-hero-cta')),
        'вернулся дублирующий набор токенов кнопки героя'
      ).toEqual([]);
    }
  });
});

describe('текст на цветном фоне считается, а не назначается (ТЗ 7.4)', () => {
  it('ни одного белого хардкодом на смысловом фоне', () => {
    /*
     * Именно так и получалось нечитаемо: `color: #fff` рядом с `background: var(--ui-...)`.
     * В тёмной теме смысловые цвета светлые, и белый на них давал 1.97–3.67:1 при пороге
     * 4.5:1 (журнал 565). Ищем постройку «цветной фон + белый текст», а не слово `#fff`:
     * белый на тёмной подложке бокового меню законен.
     */
    const offenders = (uiGlobalStyles.match(/[^{}]+{[^}]*}/g) ?? []).filter(
      (rule) =>
        /background(?:-color)?:\s*var\(--ui-(?:brand|accent|success|danger|warning|info)-\d00\)/.test(
          rule
        ) && /color:\s*(#fff|#ffffff|white)\b/i.test(rule)
    );
    expect(
      offenders.map((rule) => rule.split('{')[0]?.trim()),
      'на смысловом фоне снова прибит белый текст'
    ).toEqual([]);
  });

  it('токены «текст на цвете» объявлены в обеих темах', () => {
    for (const vars of [lightThemeVars, darkThemeVars]) {
      expect(vars).toHaveProperty('--ui-on-brand');
      expect(vars).toHaveProperty('--ui-on-color');
    }
  });

  it('в тёмной теме текст на цвете ТЁМНЫЙ, а в светлой — светлый', () => {
    /*
     * Не вкус, а следствие: в тёмной теме смысловые цвета осветляют, чтобы они читались на
     * тёмном фоне, — а значит текст поверх них обязан потемнеть. Ошибиться здесь легко:
     * «тёмная тема → всё светлое» звучит логично и приводит ровно к тому провалу, что был.
     */
    expect(lightThemeVars['--ui-on-color']).toBe('#ffffff');
    expect(darkThemeVars['--ui-on-color']).toBe('#0f172a');
    expect(lightThemeVars['--ui-on-brand']).toBe('#ffffff');
    expect(darkThemeVars['--ui-on-brand']).toBe('#0f172a');
  });
});
