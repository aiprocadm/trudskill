import { describe, expect, it } from 'vitest';

import { uiGlobalStyles } from './index.js';

/**
 * ФТ-H4/H5 (Фаза 5): тач-зоны кабинета слушателя.
 *
 * Критерий, согласованный с владельцем: элемент, по которому слушатель попадает
 * пальцем, — не меньше 44px. Реальные слушатели проходят обучение с телефонов, и
 * промах по соседнему варианту ответа в экзамене стоит балла.
 */
describe('тач-зоны (ФТ-H4/H5)', () => {
  it('вариант ответа не ниже 44px', () => {
    // Отступы дают «почти 44» и меняются при любой правке шрифта — поэтому размер
    // задан явно, а не выведен из padding.
    expect(uiGlobalStyles).toMatch(/\.ui-option\s*\{[^}]*min-height:\s*44px/);
  });

  it('кнопки не ниже 40px — нижняя граница для навигации по тесту', () => {
    expect(uiGlobalStyles).toMatch(/button[^{]*\{[^}]*height:\s*4[0-9]px/);
  });
});
