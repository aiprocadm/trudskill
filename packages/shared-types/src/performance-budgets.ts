/**
 * Бюджеты производительности (ТЗ «Стабилизация, UX и развитие», 15.3, **решение владельца Р16**).
 *
 * **Зачем они записаны числами в одном месте.** Бюджет, который живёт в тексте документа, не
 * проверяет никто: он превращается в пожелание и тихо перестаёт выполняться. Здесь он —
 * значение, на которое можно сослаться из проверки и из кода, и разойтись им уже не с чем.
 *
 * **Почему пакет общих типов, а не фронт и не бэкенд.** Размер страницы списка нужен обоим:
 * бэкенд его применяет, фронт от него зависит. Держать это число в двух местах — верный способ
 * получить «сервер отдаёт пятьдесят, экран просит двадцать» и долго искать, почему пролистывание
 * ведёт себя странно.
 */

/** Числа Р16. Менять можно только решением владельца: это не настройка центра. */
export const PERFORMANCE_BUDGETS = {
  /**
   * Начальный JavaScript страницы, в килобайтах после сжатия.
   *
   * Слушатель открывает курс с телефона на мобильном интернете: каждые лишние сто килобайт —
   * это ещё секунда до того, как он увидит хоть что-то.
   */
  initialJsKb: 300,

  /**
   * Появление основного содержимого, в секундах (эмуляция 4G).
   *
   * 2,5 с — общепринятый порог «быстро». Дольше — человек успевает решить, что зависло.
   */
  lcpSeconds: 2.5,

  /**
   * Ответ основных ручек, 95-й процентиль, в миллисекундах.
   *
   * Полсекунды — граница, за которой задержка в таблице становится заметной: человек
   * перестаёт связывать своё нажатие с тем, что происходит на экране.
   */
  apiP95Ms: 500,

  /**
   * Сколько записей на странице списка по умолчанию.
   *
   * Пятьдесят — компромисс: меньше означает постоянное пролистывание, больше — заметную
   * задержку отрисовки на слабом телефоне.
   */
  listPageSize: 50,

  /**
   * Потолок размера страницы для запросов «с проволоки».
   *
   * Без него один запрос отдавал всю таблицу слушателей со СНИЛС — это и нагрузка, и утечка
   * разом.
   */
  listPageSizeMax: 200,

  /**
   * Сохранение ответа на экзамене, 95-й процентиль, в миллисекундах.
   *
   * Триста — порог, за которым надпись «Сохранено» начинает раздражать: человек уже нажал
   * следующий вопрос, а предыдущий всё сохраняется.
   */
  examAnswerSaveP95Ms: 300,

  /**
   * С какой длины таблица обязана рисоваться частями.
   *
   * Двести строк — примерно та длина, после которой браузер на слабом телефоне заметно
   * задумывается при каждом пролистывании.
   */
  virtualizeRowsFrom: 200
} as const;

export type PerformanceBudget = keyof typeof PERFORMANCE_BUDGETS;
