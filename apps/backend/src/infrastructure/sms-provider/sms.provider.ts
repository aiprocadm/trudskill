/**
 * Шов СМС-провайдера (ФТ-C1.3 / ФТ-F2, Фаза 3 Task 5) — по форме `VideoProvider` (`0063`)
 * и `WebinarProvider` (`0055`): активный провайдер выбирается ПЕР ТЕНАНТ, потому что
 * учебные центры покупают СМС у разных операторов и платят за них сами.
 *
 * `noop` — безопасный дефолт: он ничего не отправляет и честно отвечает `null` вместо
 * того, чтобы падать. Это важнее, чем кажется: СМС здесь — ВТОРОЙ канал доставки того же
 * одноразового токена, а первый (письмо) обязан работать независимо. Спящий или
 * сломавшийся оператор не имеет права помешать слушателю получить доступ к экзамену.
 *
 * Конкретный оператор подключается в реестр отдельно (ветка B плана / Фаза 4 вместе с
 * биллингом) — от открытого вопроса №4 зависит ТОЛЬКО адаптер, а весь остальной код
 * пишется против этого шва. Правило шва: секреты (API-ключи) живут в env/секрет-хранилище,
 * в БД лежит только несекретная конфигурация (код провайдера, имя отправителя, флаг).
 */
/** Перечень кодов — один источник и для типа, и для проверки тела запроса (как у платежей). */
export const SMS_PROVIDER_CODES = ['noop', 'fake', 'smsc', 'smsru', 'mts'] as const;
export type SmsProviderCode = (typeof SMS_PROVIDER_CODES)[number];

export interface SendSmsInput {
  tenantId: string;
  /** Номер в формате E.164 (`+79991234567`). Нормализация — до вызова провайдера. */
  to: string;
  text: string;
  /**
   * Имя отправителя, зарегистрированное тенантом у оператора. У большинства российских
   * операторов незарегистрированное имя — это отказ на стороне оператора, а не наш.
   */
  senderName?: string;
}

export interface SmsSendResult {
  /** Идентификатор сообщения у оператора — по нему потом ищут доставку в его ЛК. */
  providerMessageId?: string;
  /** Сколько сегментов насчитал оператор (кириллица дробит СМС уже на 70 символах). */
  segments?: number;
}

export interface SmsProvider {
  readonly code: SmsProviderCode;
  /**
   * `null` = провайдер спит, не настроен или отказал. Никогда не бросает: вызывающий код
   * обязан продолжить работу без СМС. Успешная отправка ≠ доставка — операторы отвечают
   * «принято в очередь», и это максимум, что мы можем утверждать.
   */
  send(input: SendSmsInput): Promise<SmsSendResult | null>;
}

/** DI-токен реестра всех вкомпилированных провайдеров (Map<code, provider>). */
export const SMS_PROVIDER_REGISTRY = Symbol('SMS_PROVIDER_REGISTRY');
export type SmsProviderRegistry = Map<SmsProviderCode, SmsProvider>;

export class NoopSmsProvider implements SmsProvider {
  readonly code = 'noop' as const;
  async send(): Promise<SmsSendResult | null> {
    return null;
  }
}
