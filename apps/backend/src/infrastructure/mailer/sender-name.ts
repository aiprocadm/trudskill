/**
 * Имя отправителя письма — название учебного центра (ТЗ «Стабилизация, UX и развитие», 13.3,
 * решение владельца Р14).
 *
 * **Что просит Р14 базово, всем тарифам:** «поддомен вида `центр.trudskill.ru`, логотип, цвета
 * с автоматической проверкой контраста, **название центра в интерфейсе и в имени отправителя
 * писем**, реквизиты и подпись в документах».
 *
 * **Как было.** Транспорт отправлял ВСЕ письма от одного платформенного адреса (`SMTP_FROM`).
 * Слушатель получал письмо от платформы, а не от своего учебного центра: письмо приходило как
 * реклама незнакомого сервиса, и его открывали хуже — а для письма со ссылкой на вход это
 * прямо мешает работе (журнал 556).
 *
 * **Что меняется, а что нет.** Меняется только ВИДИМОЕ имя. Сам адрес остаётся платформенным:
 * свой домен и свой SMTP — возможность СТАРШЕГО тарифа по тому же Р14, и подменять адрес без
 * них нельзя — письмо от чужого домена уходит в спам (SPF/DKIM подписаны платформой).
 */

/** Символы, ломающие заголовок письма: перевод строки — способ подставить лишние заголовки. */
const UNSAFE = /[\r\n<>"]/g;

/**
 * Имя центра, пригодное для заголовка письма.
 *
 * Пустое название, пробелы и опасные символы означают одно и то же — имени нет, и подставлять
 * нечего. Длина ограничена: заголовок с именем на две строки почтовые программы обрезают, и
 * человек видит обрывок вместо названия.
 */
export const safeSenderName = (tenantName: string | undefined): string | null => {
  const cleaned = (tenantName ?? '').replace(UNSAFE, ' ').replace(/\s+/g, ' ').trim();
  if (cleaned.length === 0) return null;
  return cleaned.length > 78 ? `${cleaned.slice(0, 77).trimEnd()}…` : cleaned;
};

/**
 * Заголовок `From` письма: имя центра плюс платформенный адрес.
 *
 * Без названия центра возвращается исходная настройка как есть — письмо уйдёт от платформы, как
 * и раньше. Молчаливая подстановка пустого имени дала бы заголовок вида `<> <noreply@…>`,
 * который часть почтовых серверов отвергает.
 *
 * Если настройка уже содержит имя (`Платформа <noreply@…>`), берётся только адрес: два имени в
 * одном заголовке — ошибка формата, а не удвоенная вежливость.
 */
export const senderFrom = (smtpFrom: string, tenantName: string | undefined): string => {
  const name = safeSenderName(tenantName);
  if (!name) return smtpFrom;

  const address = /<([^>]+)>/.exec(smtpFrom)?.[1]?.trim() ?? smtpFrom.trim();
  if (!address) return smtpFrom;

  return `${name} <${address}>`;
};
