/**
 * Обращение «Сообщить о проблеме» (ТЗ «Стабилизация, UX и развитие», 15.5).
 *
 * **Зачем это дешевле поддержки по телефону.** Человек, у которого что-то не работает, обычно
 * не может объяснить, что именно: «не открывается», «выдало ошибку», «всё пропало». Разговор
 * уходит на выяснение, где он был и что нажимал, и половина сведений теряется — человек уже
 * ушёл с той страницы.
 *
 * **Контекст подставляет СЕРВЕР, а не экран.** Роль, версию системы и номер запроса он знает
 * точно, а присланное клиентом можно подделать — и тогда контекст в обращении бесполезен
 * (журнал 583). От экрана приходит только описание и адрес страницы.
 *
 * **Чего в обращении намеренно НЕТ.** Ни снимка экрана, ни содержимого полей, ни списка
 * последних действий. На экранах этой системы почти всегда персональные данные слушателей:
 * ФИО, СНИЛС, паспортные фотографии. Обращение в поддержку не должно превращаться в канал их
 * утечки — а именно этим оборачивается «приложим побольше на всякий случай».
 */

export interface ProblemReportInput {
  text: string;
  page: string;
}

export interface ProblemReportRecord {
  /** Что написал человек. */
  text: string;
  /** Где он был. */
  page: string;
  /** Кем работает — чтобы понимать, что ему вообще доступно. */
  role: string;
  /** Версия системы: «у меня не работает» и «у меня старая версия» — разные разговоры. */
  release: string;
  /**
   * Номер запроса. Он же возвращается человеку: по нему дежурный находит ровно этот случай, а
   * не «что-то похожее примерно в то же время».
   */
  requestId: string;
}

/**
 * Адрес страницы без строки запроса и без хвоста после решётки.
 *
 * Чистится ПОВТОРНО на сервере, хотя экран уже почистил: адрес приходит от клиента, а клиенту
 * доверять нельзя. В строке запроса живут идентификаторы («?learner=l_8f3a…»), и попасть в
 * обращение они не должны — по правилам продукта идентификатор не то, что показывают и
 * пересылают.
 */
export const safePage = (url: string | undefined): string => {
  if (!url) return 'неизвестно';
  const withoutHash = url.split('#')[0] ?? '';
  const withoutQuery = withoutHash.split('?')[0] ?? '';
  const trimmed = withoutQuery.trim();
  if (trimmed.length === 0) return '/';
  /* Обрезаем длинное: адрес в несколько килобайт — это не адрес, а попытка забить журнал. */
  return trimmed.slice(0, 200);
};

/**
 * Собрать запись обращения.
 *
 * Отдельной функцией, потому что у неё есть свойство, которое легко потерять при правке
 * контроллера: она НЕ добавляет ничего сверх перечисленного и НЕ доверяет клиенту ни в одном
 * поле, кроме самого описания.
 */
export const buildProblemReport = (
  input: ProblemReportInput,
  actor: { roles?: string[]; requestId: string },
  release: string
): ProblemReportRecord => ({
  text: input.text.trim(),
  page: safePage(input.page),
  role: actor.roles?.[0] ?? 'неизвестно',
  release: release.length > 0 ? release : 'неизвестно',
  requestId: actor.requestId
});
