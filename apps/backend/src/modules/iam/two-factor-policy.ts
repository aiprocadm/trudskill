/**
 * Политика двухфакторной защиты (ТЗ «Стабилизация, UX и развитие», 9.2, решение владельца Р7).
 *
 * **Что решено владельцем и не переоткрывается.** Двухфакторная защита обязательна для ролей
 * «Администратор платформы» и «Администратор центра», и вводится она в три шага:
 *
 * 1. **Сейчас:** защита доступна и ПРЕДЛАГАЕТСЯ баннером в профиле.
 * 2. **Через 30 дней после выпуска фазы 17:** при входе администратор видит экран «Подключите
 *    двухфакторную защиту» с возможностью отложить не более трёх раз.
 * 3. **Дальше:** вход без неё для этих ролей невозможен.
 *
 * Остальным ролям защита остаётся добровольной; слушателю она не навязывается никогда — он
 * заходит раз в несколько месяцев сдать экзамен, и требовать от него приложение-генератор
 * кодов значит потерять его на входе.
 *
 * **Почему шаг — настройка, а не «раскомментируйте через месяц».** Переход с шага на шаг это
 * срок, а всё, что выглядит как срок, в этом проекте делается настройкой со значением по
 * умолчанию. Иначе второй шаг наступает выкладкой кода — то есть тогда, когда про него
 * вспомнят, а не тогда, когда положено.
 *
 * **Чего здесь намеренно НЕТ.** Issuer TOTP не меняется ни на одном шаге — это прямое
 * предупреждение ТЗ: у тех, кто уже подключил защиту, привязанные приложения перестали бы
 * давать верные коды, и люди остались бы заперты снаружи.
 */

/** На каком шаге находится ввод обязательной защиты. */
export type TwoFactorStage =
  /** Шаг 1: предлагаем. */
  | 'offer'
  /** Шаг 2: просим при входе, позволяя отложить. */
  | 'nudge'
  /** Шаг 3: без неё не пускаем. */
  | 'required';

/** Значение по умолчанию — первый шаг: сейчас защита именно предлагается. */
export const DEFAULT_TWO_FACTOR_STAGE: TwoFactorStage = 'offer';

/** Сколько раз можно отложить на втором шаге (Р7 называет три). */
export const TWO_FACTOR_MAX_POSTPONES = 3;

export const resolveTwoFactorStage = (raw: unknown): TwoFactorStage =>
  raw === 'nudge' || raw === 'required' ? raw : DEFAULT_TWO_FACTOR_STAGE;

export interface TotpStatusLike {
  enabled: boolean;
  pending: boolean;
  /** Роль, которой защита положена по Р7. */
  eligible: boolean;
}

/**
 * Что показать человеку.
 *
 * `null` означает «ничего не показывать»: защита уже включена, либо роль не та. Молчание здесь
 * правильнее вежливой надписи «всё в порядке» — она занимала бы место на экране и ничего не
 * добавляла.
 */
export interface TwoFactorPrompt {
  /** Насколько настойчиво: подсказка или предупреждение. */
  tone: 'info' | 'warning';
  title: string;
  /** Почему это важно — человеческими словами, без слов «политика безопасности». */
  text: string;
  /** Что нажать. Кнопка называет результат, а не действие над системой. */
  actionLabel: string;
}

export const twoFactorPrompt = (
  status: TotpStatusLike,
  stage: TwoFactorStage = DEFAULT_TWO_FACTOR_STAGE
): TwoFactorPrompt | null => {
  if (!status.eligible) return null;
  if (status.enabled) return null;

  /*
   * Начатая, но не завершённая настройка — отдельный случай. Человек уже отсканировал код и
   * бросил на полпути; ему нужно не уговаривать, а напомнить, что осталось одно действие.
   */
  if (status.pending) {
    return {
      tone: 'warning',
      title: 'Двухфакторная защита настроена не до конца',
      text: 'Приложение уже связано с вашей учётной записью, но подтверждения не было. Пока вы не введёте код из приложения, защита не работает.',
      actionLabel: 'Завершить настройку'
    };
  }

  if (stage === 'required') {
    return {
      tone: 'warning',
      title: 'Подключите двухфакторную защиту',
      text: 'Для администраторов вход без неё больше невозможен. Подключение занимает минуту: приложение на телефоне покажет код, который нужно ввести после пароля.',
      actionLabel: 'Подключить защиту'
    };
  }

  if (stage === 'nudge') {
    return {
      tone: 'warning',
      title: 'Подключите двухфакторную защиту',
      text: 'Скоро вход администраторов без неё станет невозможен. Подключите сейчас, чтобы это не застало вас в неудобный момент — например, перед выдачей документов.',
      actionLabel: 'Подключить защиту'
    };
  }

  return {
    tone: 'info',
    title: 'Защитите вход вторым шагом',
    text: 'Ваша учётная запись открывает доступ к персональным данным слушателей: ФИО, СНИЛС, паспортным фотографиям. Если пароль попадёт в чужие руки, второй шаг не даст войти. Подключение занимает минуту.',
    actionLabel: 'Подключить защиту'
  };
};
