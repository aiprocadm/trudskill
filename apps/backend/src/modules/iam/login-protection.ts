/**
 * Защита входа от подбора пароля (ТЗ «Стабилизация, UX и развитие», 17.1).
 *
 * **Что было.** Частота запросов ограничивалась по адресу отправителя: двадцать пять попыток в
 * минуту с одного адреса. От перебора это не спасает по двум причинам. Во-первых, ограничение
 * общее на весь вход: двадцать пять попыток в минуту, распределённые по разным учётным записям,
 * его не трогают вовсе. Во-вторых, адрес меняется — у подбирающего их обычно много, а у центра
 * за общим выходом в интернет наоборот один на всех, и честные сотрудники мешают друг другу.
 *
 * **Что стало.** Считаются неудачи ПО УЧЁТНОЙ ЗАПИСИ. После серии неудач вход в неё временно
 * закрывается, и подбор упирается не в скорость запросов, а в само число попыток (журнал 573).
 *
 * **Чего эта защита не делает и почему.** Она не блокирует запись навсегда и не требует
 * вмешательства администратора: иначе подбирающий мог бы закрыть вход любому человеку, просто
 * назвав его логин десять раз подряд. Блокировка временная и снимается сама — это защита от
 * перебора, а не наказание.
 */

/** Настройки, которые центр может поменять. Значения по умолчанию — здесь. */
export interface LoginProtectionSettings {
  /**
   * Сколько неудач подряд допускается.
   *
   * Десять — это заметно больше, чем ошибается живой человек (обычно одна-две опечатки), и
   * несопоставимо меньше, чем нужно для перебора даже слабого пароля.
   */
  maxFailures: number;
  /**
   * За какое окно они считаются, в минутах.
   *
   * Пятнадцать: неудачи «на прошлой неделе» к сегодняшней попытке отношения не имеют, иначе
   * счётчик накапливался бы годами и однажды закрыл вход человеку на ровном месте.
   */
  windowMinutes: number;
  /**
   * На сколько минут закрывается вход.
   *
   * Пятнадцать — достаточно, чтобы перебор стал бессмысленным (десять попыток в четверть часа),
   * и достаточно мало, чтобы человек, который просто забыл пароль, не остался без работы на
   * день.
   */
  lockMinutes: number;
}

export const DEFAULT_LOGIN_PROTECTION: LoginProtectionSettings = {
  maxFailures: 10,
  windowMinutes: 15,
  lockMinutes: 15
};

/** Ключ счётчика: центр + логин. Логин приводится к нижнему регистру — это один и тот же человек. */
export const loginFailureKey = (tenantId: string, login: string): string =>
  `iam:login-failures:${tenantId}:${login.trim().toLowerCase()}`;

/** Ключ блокировки — отдельный: счётчик и запрет живут разное время. */
export const loginLockKey = (tenantId: string, login: string): string =>
  `iam:login-lock:${tenantId}:${login.trim().toLowerCase()}`;

/**
 * Настройки центра поверх умолчаний.
 *
 * Непонятное значение отбрасывается молча и заменяется умолчанием: настройка, введённая с
 * ошибкой, не должна ни открывать вход настежь, ни запирать его навсегда.
 */
export const resolveLoginProtection = (raw: unknown): LoginProtectionSettings => {
  const source = (raw ?? {}) as Partial<Record<keyof LoginProtectionSettings, unknown>>;
  const pick = (key: keyof LoginProtectionSettings, min: number, max: number): number => {
    const value = source[key];
    if (typeof value !== 'number' || !Number.isFinite(value)) return DEFAULT_LOGIN_PROTECTION[key];
    const rounded = Math.round(value);
    if (rounded < min || rounded > max) return DEFAULT_LOGIN_PROTECTION[key];
    return rounded;
  };
  return {
    /*
     * Границы не дают настройкой отменить защиту. Меньше трёх попыток — это блокировка на
     * опечатке; больше сотни — перебор снова становится возможным.
     */
    maxFailures: pick('maxFailures', 3, 100),
    windowMinutes: pick('windowMinutes', 1, 1440),
    lockMinutes: pick('lockMinutes', 1, 1440)
  };
};

/** Пора ли закрывать вход после очередной неудачи. */
export const shouldLock = (failures: number, settings: LoginProtectionSettings): boolean =>
  failures >= settings.maxFailures;

/**
 * Что сказать человеку, когда вход временно закрыт.
 *
 * Правило продукта: ошибка говорит, ЧТО произошло и ЧТО делать. «Слишком много попыток» без
 * срока оставляет человека гадать, сколько ждать, — и он продолжает нажимать, продлевая себе
 * блокировку.
 */
export const lockedMessage = (minutesLeft: number): string => {
  const minutes = Math.max(1, Math.ceil(minutesLeft));
  return (
    `Вход временно закрыт: слишком много неудачных попыток. ` +
    `Попробуйте через ${minutes} ${minutesWord(minutes)} или восстановите пароль.`
  );
};

/**
 * Склонение слова «минута» по числу.
 *
 * Пишется руками, потому что «через 2 минут» читается как машинный перевод и подрывает доверие
 * к остальному тексту. Правило русского счёта: 1, 21, 31 — «минуту»; 2–4, 22–24 — «минуты»;
 * всё прочее, включая 11–14, — «минут».
 */
export const minutesWord = (minutes: number): string => {
  const tail = minutes % 100;
  if (tail >= 11 && tail <= 14) return 'минут';
  const last = minutes % 10;
  if (last === 1) return 'минуту';
  if (last >= 2 && last <= 4) return 'минуты';
  return 'минут';
};
