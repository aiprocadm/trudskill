import { randomBytes } from 'node:crypto';

/**
 * Одноразовый тикет на подключение к живой трансляции (ТЗ «Стабилизация, UX и развитие», 9.1).
 *
 * **Что было.** Подключение к трансляции шло так:
 * `/realtime/stream/user%3Au_tenant_admin?since=...&access_token=eyJhbGci...` — то есть
 * ПОЛНОЦЕННЫЙ токен доступа ехал в адресе запроса.
 *
 * Почему это опасно, простыми словами: адрес запроса — не секрет. Он попадает в журналы
 * веб-сервера (их читают администраторы и системы сбора логов), в историю браузера (её видит
 * любой, кто сядет за компьютер) и в заголовок `Referer`, который браузер отправляет НА ЧУЖИЕ
 * САЙТЫ при переходе по внешней ссылке. Токен доступа оттуда можно взять и работать от имени
 * человека всё время, пока токен жив.
 *
 * **Что стало.** В адресе едет тикет: случайная строка, которая живёт секунды и сгорает при
 * первом использовании. Украсть её из журнала можно, но воспользоваться — уже нет.
 *
 * **Почему не просто короткий токен.** Короткий срок жизни спасает от старой записи в журнале,
 * но не от того, кто смотрит журнал прямо сейчас. Одноразовость закрывает и это: подключение
 * уже произошло, второго по тому же тикету не будет.
 */

/**
 * Сколько живёт невостребованный тикет.
 *
 * Тридцать секунд — это «человек нажал и браузер подключился», с запасом на медленную сеть.
 * Настройкой не сделано намеренно: это не деловое правило центра, а длина технической паузы
 * между двумя запросами одного и того же браузера; центру тут нечего решать.
 */
export const REALTIME_TICKET_TTL_SECONDS = 30;

/** Что тикет удостоверяет: кто именно и в каком центре подключается. */
export interface RealtimeTicketPayload {
  tenantId: string;
  userId: string;
  sessionId: string;
  roles: string[];
  /**
   * Комната, на которую тикет выдан. Тикет от одной комнаты не открывает другую: иначе
   * достаточно было бы попросить тикет на свой канал и подключиться к чужому.
   */
  room: string;
}

/**
 * Ключ в общем хранилище.
 *
 * Приставка нужна, чтобы тикеты нельзя было спутать с другими записями и чтобы их можно было
 * найти при разборе происшествия.
 */
export const realtimeTicketKey = (ticket: string): string => `realtime:ticket:${ticket}`;

/**
 * Сама случайная строка.
 *
 * 32 байта случайности — столько же, сколько у ключей сессий. Запись в шестнадцатеричном виде,
 * а не в base64: такая строка безопасно проходит через адрес запроса без экранирования, и в
 * журнале её не спутать с обрезанным токеном.
 */
export const newRealtimeTicket = (): string => randomBytes(32).toString('hex');

/** Тикет годен, только если он выдан на ту комнату, к которой подключаются. */
export const ticketMatchesRoom = (payload: RealtimeTicketPayload, room: string): boolean =>
  payload.room === room;

/**
 * Разбор того, что лежало в хранилище.
 *
 * Возвращает `null` на любой неожиданности вместо того, чтобы бросать исключение: на другом
 * конце это означает «подключение отклонено», и отличать «мусор в хранилище» от «тикет
 * просрочен» подключающемуся незачем — обе причины ведут к одному действию, запросить новый.
 */
export const parseRealtimeTicket = (
  raw: string | null | undefined
): RealtimeTicketPayload | null => {
  if (!raw) return null;
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    // Молчим намеренно: в хранилище чужой мусор — это тот же отказ, что и просроченный тикет.
    return null;
  }
  if (!parsed || typeof parsed !== 'object') return null;
  const value = parsed as Record<string, unknown>;
  const { tenantId, userId, sessionId, room } = value;
  if (
    typeof tenantId !== 'string' ||
    typeof userId !== 'string' ||
    typeof sessionId !== 'string' ||
    typeof room !== 'string'
  ) {
    return null;
  }
  const roles = Array.isArray(value.roles)
    ? value.roles.filter((role): role is string => typeof role === 'string')
    : [];
  return { tenantId, userId, sessionId, roles, room };
};
