import { IsString, Matches, MaxLength, MinLength } from 'class-validator';

/**
 * Запрос тикета на подключение к живой трансляции (ТЗ 9.1).
 *
 * Комната называется в запросе, а не подставляется потом: тикет выдаётся НА КОНКРЕТНУЮ комнату
 * и другую не открывает. Иначе достаточно было бы попросить тикет на свой канал и подключиться
 * к чужому — а комнаты здесь именуются по человеку и по центру.
 */
export class RealtimeTicketRequestDto {
  /**
   * Имя комнаты, как его понимает служба трансляций: `user:<id>` или `tenant:<id>`.
   *
   * Набор символов ограничен намеренно: имя уходит в адрес запроса и в ключ хранилища, и
   * посторонние символы там способны сломать и то и другое.
   */
  @IsString()
  @MinLength(3)
  @MaxLength(128)
  @Matches(/^[A-Za-z0-9:_-]+$/, {
    message: 'Имя канала содержит недопустимые символы'
  })
  room!: string;
}
