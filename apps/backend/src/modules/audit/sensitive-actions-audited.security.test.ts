import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

/**
 * Операции, которые обязаны оставлять след в журнале действий.
 *
 * Правило проекта — «каждая мутация пишет в аудит» — держалось на внимательности, и
 * ревизия 2026-08-26 нашла четыре места, где следа не было вовсе:
 *
 *  - правка карточки центра, включая подмену картинок подписи и печати, которые
 *    печатаются в выдаваемом удостоверении;
 *  - решение по переаттестации (отклонение не записывалось никак);
 *  - публикация текста согласия — юридического документа, под которым подписываются;
 *  - политика подтверждения личности, решающая, кого пускать к экзамену.
 *
 * Сторож намеренно НЕ пытается обойти все 259 мутирующих ручек: разбор «ручка → сервис →
 * метод» получается хрупким и уже соврал один раз, объявив без аудита `esign.service.ts`,
 * который его пишет. Вместо этого — короткий именной список того, что задевает юридическую
 * силу документов, деньги и доступ. Он ловит регресс «аудит убрали при рефакторинге» и
 * растёт по мере того, как находятся новые такие места.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const MODULES = resolve(HERE, '..');

/** Файл сервиса → что именно в нём нельзя делать бесследно. */
const MUST_AUDIT: Record<string, string> = {
  'tenant/tenant.service.ts':
    'юридическое название, ИНН, картинки подписи и печати — всё это печатается в удостоверении',
  'mvp/recertification/recertification.service.ts':
    'решение о допуске к переаттестации, включая отказ',
  'mvp/consents/consent.service.ts': 'публикация текста согласия — юридического документа',
  'mvp/identity/identity-policy.service.ts': 'кого пускать к экзамену и нужно ли фото',
  'esign/esign.service.ts': 'подписание документов простой электронной подписью',
  'org/licenses.service.ts': 'лицензии центра — сколько людей он вправе учить',
  'iam/services/auth.service.ts': 'вход, сессии, второй шаг проверки'
};

/*
 * Ищем именно ВЫЗОВ, а не наличие поля. Первая версия совпадала со строкой
 * `private readonly auditService` — и оставалась зелёной, когда вызов из кода убирали.
 * Сторож, который не краснеет на мутации, хуже отсутствующего: он создаёт уверенность.
 */
const AUDIT_CALL =
  /audit(?:Service)?\??\.(?:write|writeCritical)\(|this\.audit(?:Decision|Policy)?\(/;

describe('чувствительные операции оставляют след в журнале действий', () => {
  it('все перечисленные файлы существуют — иначе список молча устареет', () => {
    const missing = Object.keys(MUST_AUDIT).filter((rel) => !existsSync(join(MODULES, rel)));
    expect(missing, 'файл переехал или переименован — поправьте список').toEqual([]);
  });

  it('каждый из них пишет в журнал', () => {
    const silent = Object.keys(MUST_AUDIT)
      .filter((rel) => existsSync(join(MODULES, rel)))
      .filter((rel) => !AUDIT_CALL.test(readFileSync(join(MODULES, rel), 'utf8')))
      .sort();
    expect(
      silent,
      'сервис перестал писать в журнал действий: операция, которая задевает документы с ' +
        'юридической силой, деньги или доступ, не должна проходить бесследно'
    ).toEqual([]);
  });

  it('у каждой записи сказано, что именно нельзя делать бесследно', () => {
    const vague = Object.entries(MUST_AUDIT)
      .filter(([, why]) => why.trim().length < 20)
      .map(([rel]) => rel);
    expect(vague).toEqual([]);
  });
});
