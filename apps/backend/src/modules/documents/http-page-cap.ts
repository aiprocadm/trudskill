import type { BaseFilter } from './documents.dto.js';

/**
 * Ревизия 2026-08-27 (порция 34, журнал 283) — потолок размера страницы НА ГРАНИЦЕ HTTP.
 *
 * Порция 24 починила арифметику пагинации документов (параметры приходят строками, и
 * сложение склеивало их), но потолок туда ставить было нельзя: тот же помощник зовут
 * внутренние пути, которые законно просят огромные страницы — например, портал заказчика
 * фильтрует по контрагенту ДО пагинации и потому берёт всё сразу. Ограничение принадлежит
 * границе: снаружи `?page_size=1000000` не должен выносить весь реестр документов центра
 * одним ответом, внутри — должен работать как работал.
 */
export const DOCUMENTS_HTTP_MAX_PAGE_SIZE = 200;

/** Копия запроса с размером страницы не больше потолка. Прочие поля не трогаются. */
export function capHttpPageSize<T extends BaseFilter>(query: T): T {
  const raw = Number(query?.pageSize);
  if (!Number.isFinite(raw) || raw <= DOCUMENTS_HTTP_MAX_PAGE_SIZE) return query;
  return { ...query, pageSize: DOCUMENTS_HTTP_MAX_PAGE_SIZE };
}
