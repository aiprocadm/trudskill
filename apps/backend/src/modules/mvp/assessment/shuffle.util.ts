/**
 * Честное перемешивание (ФТ-E2, Фаза 2 Task 12).
 *
 * **Что здесь было не так.** Рандомизация вопросов делалась через
 * `array.sort(() => Math.random() - 0.5)`. Это классическая ошибка: компаратор обязан
 * быть согласованным (если a<b и b<c, то a<c), а случайный — не является. Результат
 * зависит от внутреннего алгоритма сортировки движка и НЕ является равновероятной
 * перестановкой: в V8 элементы массово остаются вблизи исходных позиций. То есть
 * «рандомизация» в правилах теста была включена, но фактически почти не работала —
 * два слушателя рядом получали похожий порядок вопросов.
 *
 * Здесь — Фишер–Йетс: каждая перестановка равновероятна, доказывается тестом.
 */

/** Источник случайности в [0,1). Вынесен параметром — иначе тест недоказуем. */
export type RandomFn = () => number;

/**
 * Перемешивание Фишера–Йетса. Возвращает НОВЫЙ массив: вызывающий код обычно
 * работает со снимком вопросов попытки, и порча исходного массива там недопустима.
 */
export function shuffle<T>(items: readonly T[], random: RandomFn = Math.random): T[] {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    // Защита от источника, вернувшего 1 или NaN: выход за границы молча испортил бы массив.
    const safeJ = Number.isFinite(j) ? Math.min(Math.max(j, 0), i) : i;
    [result[i], result[safeJ]] = [result[safeJ]!, result[i]!];
  }
  return result;
}
