/**
 * ФТ-G2 — предел частоты для кода допуска к экзамену.
 *
 * Числа лежат отдельно от контроллера по той же причине, по какой их вообще стоит
 * называть: их проверяет сторож. Записанные прямо в декораторе, они расходятся с
 * тестом молча — тест продолжает утверждать «10», когда в коде уже «100».
 *
 * **Проверка кода (`VERIFY`) — 10 в минуту.** Человек вводит код из письма: с опечаткой
 * это две-три попытки, десять — с большим запасом. Дальше это уже не ввод, а подбор.
 * Сам код длинный и случайный, угадать его практически невозможно, но без предела
 * подбор ничего не стоит и, что важнее, **не оставляет следа**: нет ни отказа, ни
 * сигнала. Предел превращает тихий перебор в заметный.
 *
 * **Запрос кода (`REQUEST`) — 5 в минуту.** Каждый запрос отправляет письмо: без предела
 * чужой почтовый ящик заваливается письмами с нашего адреса, и страдает репутация
 * отправителя — не только терпение слушателя.
 */
export const PRE_EXAM_VERIFY_RATE_LIMIT = { limit: 10, ttl: 60_000 } as const;

export const PRE_EXAM_REQUEST_RATE_LIMIT = { limit: 5, ttl: 60_000 } as const;
