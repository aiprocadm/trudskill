import { createHash } from 'node:crypto';

import type { Readable } from 'node:stream';

/**
 * Отпечаток удаляемого снимка (ТЗ «Стабилизация, UX и развитие», 17.2, решение владельца Р17).
 *
 * **Зачем.** Р17 требует: снимки удаляются через 90 дней, а ПРОТОКОЛ верификации остаётся —
 * «кто, когда и с каким результатом проверил, **плюс хеш файла**». Хеша в системе не было, и
 * протокол оставался недоказуемым: через год, когда файлов давно нет, подтвердить, что
 * модератор смотрел именно тот документ, нечем. Слушатель говорит «я присылал другое» — и
 * возразить невозможно (журнал 578).
 *
 * **Почему отпечаток безопасно хранить вечно.** Он не содержит изображения, и восстановить по
 * нему ни лицо, ни номер паспорта нельзя: это короткая строка, одинаковая у одинаковых файлов
 * и разная у разных. Именно этим он и полезен — сличить можно, увидеть нельзя.
 *
 * **Почему он снимается в момент удаления, а не при загрузке.** При загрузке файл проходит
 * через антивирус, и добавлять туда второе чтение значило бы замедлить приём документов у всех
 * ради того, что понадобится через три месяца и только части записей. При удалении файл читают
 * в любом случае — последний раз.
 */

/** Сколько байт читаем, прежде чем сдаться. */
const MAX_FINGERPRINT_BYTES = 64 * 1024 * 1024;

/**
 * Посчитать отпечаток по потоку.
 *
 * Возвращает `null` на любой неудаче вместо исключения — и это главное свойство функции.
 * Удаление персональных данных не имеет права остановиться из-за того, что не удалось снять
 * отпечаток: лучше протокол без отпечатка, чем паспортный скан, который остался лежать, потому
 * что хранилище моргнуло.
 */
export const fingerprintStream = async (stream: Readable): Promise<string | null> => {
  try {
    const hash = createHash('sha256');
    let seen = 0;
    for await (const chunk of stream) {
      const buffer = chunk as Buffer;
      seen += buffer.length;
      if (seen > MAX_FINGERPRINT_BYTES) {
        /*
         * Снимок паспорта весит мегабайты, а не десятки. Файл такого размера — это или
         * ошибка, или чужой файл, и вычитывать его целиком незачем.
         */
        return null;
      }
      hash.update(buffer);
    }
    return `sha256:${hash.digest('hex')}`;
  } catch {
    // Молчим намеренно: причина описана выше — отпечаток не важнее удаления самих данных.
    return null;
  }
};

/**
 * Собрать поле отпечатков, пропуская те, что снять не удалось.
 *
 * Пустой объект не возвращается: поле, которое есть, но пустое, выглядит как «отпечатки были и
 * потерялись», а его отсутствие честно говорит «снять не удалось».
 */
export const collectFingerprints = (parts: {
  selfie?: string | null;
  passport?: string | null;
}): { selfie?: string; passport?: string } | undefined => {
  const result: { selfie?: string; passport?: string } = {};
  if (parts.selfie) result.selfie = parts.selfie;
  if (parts.passport) result.passport = parts.passport;
  return Object.keys(result).length > 0 ? result : undefined;
};
