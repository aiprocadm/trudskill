import { IsOptional, IsString, MaxLength, MinLength } from 'class-validator';

/**
 * Запрос на показ персональных данных целиком (ТЗ «Стабилизация, UX и развитие», 17.2).
 *
 * Причина не обязательна технически, но спрашивается всегда. Необходимость её назвать сама по
 * себе останавливает праздный просмотр «а что там у этого», и она же помогает разобраться
 * потом, когда вспомнить обстоятельства уже нельзя.
 *
 * **Обязательной причина не сделана намеренно.** В срочном обращении человек напишет «asdf»,
 * лишь бы система пропустила, — и журнал доступа наполнится мусором вместо пустых полей.
 * Пустое поле честнее выдуманного: по нему хотя бы видно, что причину не называли.
 */
export class RevealPiiRequestDto {
  @IsOptional()
  @IsString()
  @MinLength(3)
  @MaxLength(300)
  reason?: string;
}
