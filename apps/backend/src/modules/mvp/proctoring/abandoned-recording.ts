/**
 * Брошенная запись прокторинга (ревизия 2026-08-26).
 *
 * Что происходит. Запись заводится в статусе «идёт запись» и переводится в «завершена»
 * с экрана слушателя, когда тот сдаёт работу. Если вкладку закрыли, связь оборвалась или
 * завершение не дошло, запись остаётся в статусе «идёт запись» — навсегда.
 *
 * Почему это важно. По этим записям потом разбирают, кто сдавал экзамен. Администратор
 * смотрит очередь и не может отличить экзамен, который идёт прямо сейчас, от записи,
 * оборванной две недели назад: обе выглядят одинаково. А это ровно тот вопрос, который
 * задают при разборе — «шла запись или нет».
 *
 * Что делаем. Признак вычисляется, а данные не трогаются: менять статус задним числом
 * значило бы утверждать «запись прервалась» там, где мы этого не знаем — может, человек
 * прямо сейчас пишет вторую часть. Экран показывает «связь потеряна», а не «прервана».
 *
 * Почему не ночной процесс. Он потребовал бы блокировки, расписания и наблюдения за
 * самим процессом — целый механизм ради признака, который считается из даты начала.
 * Механизм добавляют, когда надо ИЗМЕНИТЬ данные; здесь достаточно честно показать.
 */

/**
 * Порог: шесть часов. Любой экзамен короче — даже с перерывами и пересдачей внутри окна;
 * сутки были бы уже бесполезны (администратор смотрит очередь в тот же день).
 */
export const ABANDONED_AFTER_MS = 6 * 60 * 60 * 1000;

type RecordingLike = {
  recordingStatus: string;
  startedAt?: string | undefined;
  createdAt?: string | undefined;
};

/**
 * «Похоже, запись брошена»: начата давно и всё ещё числится идущей.
 *
 * `nowIso` — аргумент, а не системные часы: иначе проверку границы пришлось бы ждать
 * шесть часов.
 */
export const isAbandonedRecording = (
  recording: RecordingLike,
  nowIso: string,
  thresholdMs: number = ABANDONED_AFTER_MS
): boolean => {
  if (recording.recordingStatus !== 'recording') return false;

  const startedRaw = recording.startedAt ?? recording.createdAt;
  if (!startedRaw) return false;

  const started = Date.parse(startedRaw);
  const now = Date.parse(nowIso);
  if (Number.isNaN(started) || Number.isNaN(now)) return false;

  return now - started >= thresholdMs;
};
