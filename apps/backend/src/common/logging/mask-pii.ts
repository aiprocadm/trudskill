/**
 * Маскирование персональных данных для журналов (ревизия 2026-08-26).
 *
 * Тот же довод, что и у секретов: журналы читают шире, чем базу. То, что попало в лог,
 * попадает в выгрузку для расследования, в систему сбора логов и в тикет, к которому эту
 * выгрузку приложили. База при этом может быть зашифрована идеально.
 *
 * Адрес электронной почты — персональные данные (152-ФЗ), и писать его целиком в журнал
 * доставки писем не нужно: поддержке достаточно узнать письмо среди прочих и сопоставить
 * с обращением. Полный запрет был бы вреден — «письмо не дошло» разбирают именно по
 * журналу, — поэтому адрес не убирается, а маскируется.
 *
 * Маска сохраняет ровно столько, сколько нужно для узнавания: первый знак имени, домен
 * целиком (по нему видно корпоративную почту центра) и длину скрытой части не выдаёт.
 */

/** `ivanov@example.com` → `i***@example.com`. Не почта — возвращается как есть, но усечённо. */
export const maskEmail = (value: string | undefined | null): string => {
  if (!value) return '—';
  const at = value.lastIndexOf('@');
  if (at <= 0) {
    /*
     * Не адрес: строку всё равно не печатаем целиком — вдруг туда попало что-то ещё.
     * Три знака достаточно, чтобы отличить «пусто» от «мусор пришёл».
     */
    return `${value.slice(0, 3)}***`;
  }
  const name = value.slice(0, at);
  const domain = value.slice(at);
  return `${name.slice(0, 1)}***${domain}`;
};

/** `123-456-789 00` → `***-***-*** 00`: последние две цифры помогают отличить записи. */
export const maskSnils = (value: string | undefined | null): string => {
  if (!value) return '—';
  const digits = value.replace(/\D/g, '');
  if (digits.length < 4) return '***';
  return `***-***-*** ${digits.slice(-2)}`;
};

/**
 * `Иванов Иван Иванович` → `Иванов И. И.`
 *
 * Фамилия остаётся: без неё запись в журнале бесполезна для разбора обращения, а сама по
 * себе фамилия не опознаёт человека так, как полное ФИО рядом со СНИЛС и датой рождения.
 */
export const maskFullName = (value: string | undefined | null): string => {
  if (!value) return '—';
  const parts = value.trim().split(/\s+/);
  const [lastName, ...rest] = parts;
  if (!lastName) return '—';
  const initials = rest
    .filter(Boolean)
    .map((part) => `${part.slice(0, 1)}.`)
    .join(' ');
  return initials ? `${lastName} ${initials}` : lastName;
};
