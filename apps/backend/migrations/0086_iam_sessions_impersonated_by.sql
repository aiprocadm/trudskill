-- Ревизия 2026-08-27 (порция 33, журнал 270): признак «эта сессия выдана поддержкой
-- от имени пользователя».
--
-- Зачем в СЕССИИ, а не в токене: токен живёт минуты и обновляется, и признак,
-- живущий только в нём, исчез бы при первом обновлении — а доступ остался бы. В сессии
-- он живёт столько же, сколько сам вход «от имени», и переносится при ротации.
--
-- Хранится идентификатор ТОГО, КТО вошёл: по журналу нужно ответить не только «это была
-- поддержка», но и «кто именно из поддержки».
alter table iam.sessions
  add column if not exists impersonated_by text;

comment on column iam.sessions.impersonated_by is
  'Идентификатор сотрудника платформы, вошедшего «от имени» владельца сессии (NULL — обычный вход)';
