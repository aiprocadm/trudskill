-- Программа 272: номер выпущенного документа физически не может повториться.
--
-- Уникальный индекс на номера в базе ЕСТЬ с миграции 0005
-- (`uq_documents_reservation_number` на `documents.number_reservations`), но боевой путь
-- в ту таблицу НЕ ПИШЕТ ВООБЩЕ: рабочая модель чтения — снимок JSONB, двойная запись
-- выключена по умолчанию. То есть индекс не защищает ничего, а уникальность номера
-- держится на проверке в памяти процесса — и гонка двух выпусков может дать два
-- удостоверения с одним номером. Для регулируемой нумерации это худший из возможных
-- дефектов: у проверяющего два разных документа с одинаковым номером.
--
-- Почему не переиспользуем `documents.number_reservations`: у неё внешние ключи на
-- `documents.numbering_rules` и `documents.generated_documents`, а боевой путь эти таблицы
-- не заполняет — вставка упала бы на FK. Заводить нормализованную модель ради одного
-- индекса — отдельная большая работа. Заявке нужны только номер и его владелец.
--
-- Таблица работает как последняя линия обороны: заявка ставится в той же транзакции, что и
-- запись снимка. Заявлен номер другим резервированием — транзакция падает, документ не
-- выпускается. Резервирования не удаляются никогда, а освобождённый номер переиспользуется
-- ТЕМ ЖЕ резервированием, поэтому пара «номер → резервирование» стабильна.

create table if not exists documents.issued_number_claims (
  tenant_id text not null references core.tenants(id),
  reserved_number text not null,
  reservation_id text not null,
  claimed_at timestamptz not null default now(),
  constraint documents_issued_number_claims_pk primary key (tenant_id, reserved_number)
);

comment on table documents.issued_number_claims is
  'Заявка на номер документа: последняя линия обороны от дубля номера при нескольких экземплярах приложения (журнал 272). Пара «арендатор + номер» уникальна ключом таблицы.';

comment on column documents.issued_number_claims.reservation_id is
  'Резервирование, которому принадлежит номер. Совпало — та же заявка, значит повтор законен; не совпало — дубль, и запись не проходит.';
