-- ЗАЧЕМ. Приглашение сотрудника из интерфейса спрашивает должность (ФИО, почта, роль,
-- должность — §7.6 ТЗ), а у учётной записи сотрудника (`iam.users`) такого поля не было:
-- «должность» жила только у слушателей и контактов контрагентов. Аддитивно, без NOT NULL —
-- у старых учёток пусто.

ALTER TABLE iam.users
  ADD COLUMN IF NOT EXISTS position text;
