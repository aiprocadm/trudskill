-- Программа 272+292: чужая запись состояния арендатора больше не затирается молча.
--
-- Состояние центра хранится СНИМКОМ: коллекция целиком лежит строками JSONB, а сохранение
-- делает «удалить коллекцию — вставить заново». Порядок «прочитать → изменить → записать»
-- сериализован замком арендатора, но замок держит очередь В ПАМЯТИ ПРОЦЕССА. Второй
-- экземпляр за прокси не защищён ничем: оба читают одно состояние, оба пишут коллекцию
-- целиком, и «последний писатель побеждает» стирает чужие изменения ЦЕЛИКОМ и молча.
--
-- Версия — дешёвая замена сквозной блокировке: загрузка запоминает её, сохранение
-- увеличивает УСЛОВНО («если она всё ещё та, что прочитали»). Ноль изменённых строк
-- означает, что между чтением и записью состояние поменял кто-то другой; транзакция
-- откатывается, запрос отвечает 409. Соединение при этом никто не держит.
--
-- Внутри одного процесса проверка не срабатывает: там чтение и запись уже сериализованы,
-- и версия к моменту записи всегда та же.
--
-- `scope` разделяет два независимых снимка: `mvp` (learning.mvp_runtime_documents) и
-- `documents` (documents.runtime_documents). У них разные транзакции записи, поэтому и
-- версии разные — общая давала бы конфликты на ровном месте.

create table if not exists core.tenant_state_versions (
  tenant_id text not null references core.tenants(id),
  scope text not null,
  version bigint not null default 0,
  updated_at timestamptz not null default now(),
  constraint tenant_state_versions_pk primary key (tenant_id, scope),
  constraint tenant_state_versions_scope_known check (scope in ('mvp', 'documents'))
);

comment on table core.tenant_state_versions is
  'Версия снимка состояния арендатора. Растёт на каждую запись; сверяется с версией на момент чтения, чтобы параллельная запись из другого экземпляра не затёрла чужие изменения молча (журнал 272/292).';

comment on column core.tenant_state_versions.scope is
  'Какой снимок: mvp (learning.mvp_runtime_documents) или documents (documents.runtime_documents).';
