-- 0095_learning_material_text_and_link.sql
-- ТЗ «Стабилизация, UX и развитие» 2.5.a (Б7), решение Р8 — курс физически нельзя пройти.
--
-- Из трёх базовых видов материала хранить было нечем ДВА:
--   * text          — текста материала негде было держать. Экран слушателя честно печатал ему
--                     «Текстовый материал станет доступен после расширения backend полем
--                     textBody» — служебную фразу вместо учебного материала;
--   * external_url  — адреса ссылки негде было держать. Просмотрщик ссылки в коде есть, но
--                     получал жёстко переданный `null` и говорил «ссылка пока не задана
--                     администратором» — неправда: задать её было НЕКУДА.
--
-- Видео (`video_asset_id`, 0063), файл (`file_id`) и SCORM (`scorm_package_id`, 0052) уже имели
-- своё хранение. Здесь достраиваются недостающие два поля — по тому же образцу: типизированная
-- колонка как контракт схемы, снимок MVP-состояния её зеркалит (правило 0016).
--
-- Почему колонки, а не отдельные таблицы (в отличие от видео и SCORM): у текста и ссылки НЕТ
-- своего жизненного цикла — нечего обрабатывать, нечего ждать, нечего пересобирать. Это два
-- значения материала, и отдельная таблица добавила бы соединение без единой выгоды.
--
-- Additive + idempotent.

BEGIN;

ALTER TABLE learning.materials
  ADD COLUMN IF NOT EXISTS text_body text;

ALTER TABLE learning.materials
  ADD COLUMN IF NOT EXISTS external_url text;

-- В COMMENT ON допустим только ЦЕЛЬНЫЙ текстовый литерал: склейка через || здесь не работает
-- (поймано прогоном цепочки миграций на живой базе). Поэтому строки длинные, но единые.
COMMENT ON COLUMN learning.materials.text_body IS
  'ТЗ 2.5.a: тело текстового материала (material_type=text). Простой текст, без разметки: редактор административной части сохраняет абзацы как есть. MVP JSON store mirrors this field.';

COMMENT ON COLUMN learning.materials.external_url IS
  'ТЗ 2.5.a: адрес внешнего материала (material_type=external_url), например запись вебинара. Допускаются только http/https — проверка на стороне приложения. MVP JSON store mirrors this field.';

COMMIT;
