-- Фаза 6 Task 8 (ФТ-I2): повторная отправка письма.
--
-- ЗАЧЕМ. Журнал писем есть, а починить «письмо не ушло» было нечем: ручки повторной
-- отправки не существовало вовсе. Администратор центра видел строку со статусом `failed`
-- и мог только позвонить разработчику.
--
-- ПОЧЕМУ НУЖНА КОЛОНКА `body`. В журнале хранилась только ТЕМА письма. Чтобы отправить
-- письмо повторно, нужно его тело — а собрать его заново нельзя: шаблон и данные с тех пор
-- могли измениться, и слушатель получил бы ДРУГОЕ письмо под видом повторной отправки
-- (другая дата, другой номер удостоверения, другая подпись центра). Поэтому храним ровно
-- то, что было отправлено, и повторяем именно его.
--
-- Старые строки останутся без тела — для них повторная отправка честно недоступна,
-- вместо тихой отправки чего-то другого.
--
-- `resent_from_id` связывает повтор с исходным письмом: в журнале видно, что это не
-- второе самостоятельное уведомление, а именно повтор.
--
-- Additive + idempotent.

BEGIN;

ALTER TABLE communication.email_deliveries
  ADD COLUMN IF NOT EXISTS body text NULL;

ALTER TABLE communication.email_deliveries
  ADD COLUMN IF NOT EXISTS resent_from_id text NULL;

-- Запрос экрана «Эксплуатация»: свежие неудачи центра сверху.
CREATE INDEX IF NOT EXISTS idx_email_deliveries_tenant_status
  ON communication.email_deliveries (tenant_id, status, created_at DESC);

COMMIT;
