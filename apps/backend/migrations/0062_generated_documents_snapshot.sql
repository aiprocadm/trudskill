-- 0062: снапшот подстановки выданного документа (ФТ-A1.4, Фаза 1 Task 3).
--
-- Зачем: ТЗ требует, чтобы повторный рендер выданного документа давал ИДЕНТИЧНЫЙ файл.
-- Для этого вместе с документом сохраняется полный словарь значений, подставленных в бланк
-- (номер, даты, ФИО, программа, состав комиссии), — перевыпуск берёт данные из снапшота,
-- а не пересобирает их заново из живых сущностей, которые могли измениться.
--
-- Где лежат данные на самом деле: рантайм пишет сущности JSONB-документами в
-- documents.runtime_documents (collection='generatedDocuments'), поэтому новое поле
-- variablesSnapshot уезжает туда автоматически и миграции данных не требует.
-- Эта колонка — для нормализованной схемы (read-model Фазы 4), как и предыдущие
-- аддитивные ALTER'ы 0033 (qr_token) и 0034 (revoke/reissue).
--
-- ПДн: содержимое снапшота шифруется приложением (AES-256-GCM, тот же keyring
-- INTEGRATION_CRYPTO_KEYS, что у СНИЛСа и TOTP-секретов) — в БД попадает строка 'enc:…'.
-- Публичная проверка по QR снапшот не отдаёт вовсе.
alter table documents.generated_documents
  add column if not exists variables_snapshot jsonb;
