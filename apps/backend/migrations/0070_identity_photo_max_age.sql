-- Фаза 3 (ФТ-C1.2): срок годности подтверждения личности с фотографией.
--
-- **Ответ владельца от 2026-07-29** на открытый вопрос №8 («что значит „непосредственно
-- перед экзаменом“»): срок годности — 24 часа, снимок ОДИН на слушателя (не на каждую
-- попытку), сам срок настраивается администратором.
--
-- Колонка добавляется рядом с `require_photo_before_exam` (0066), потому что это свойство
-- ТОГО ЖЕ требования: «нужно фото» и «насколько свежее» бессмысленны по отдельности.
-- Настройка живёт на уровне политики, а не тенанта: у разных программ требования к
-- строгости разные, и площадка обязана уметь их различать.
--
-- NULL = «срок не задан», работает умолчание 24 часа. Отдельного значения «бессрочно»
-- нет намеренно: требование ТЗ — «непосредственно перед экзаменом», и возможность
-- выключить его совсем противоречила бы самому требованию.

BEGIN;

ALTER TABLE learning.identity_policies
  ADD COLUMN IF NOT EXISTS photo_max_age_hours integer NULL;

COMMENT ON COLUMN learning.identity_policies.photo_max_age_hours IS
  'ФТ-C1.2: сколько часов подтверждение с фото считается действительным. NULL = умолчание 24 ч.';

-- Границы: минимум час (меньше — человек физически не успеет пройти проверку модератором),
-- максимум 720 часов = 30 суток (дальше «непосредственно перед экзаменом» перестаёт быть
-- правдой). Проверка в БД, а не только в коде: настройку правят и напрямую.
ALTER TABLE learning.identity_policies
  DROP CONSTRAINT IF EXISTS identity_policies_photo_max_age_chk;
ALTER TABLE learning.identity_policies
  ADD CONSTRAINT identity_policies_photo_max_age_chk
  CHECK (photo_max_age_hours IS NULL OR (photo_max_age_hours >= 1 AND photo_max_age_hours <= 720));

COMMIT;
