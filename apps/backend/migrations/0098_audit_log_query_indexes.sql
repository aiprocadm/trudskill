-- ТЗ «Стабилизация, UX и развитие», 15.4: запросы к базе.
--
-- ЧТО БЫЛО. Журнал действий — самая большая таблица в системе: в неё пишется каждое действие
-- каждого человека. При этом самый частый запрос к ней (открыть журнал: свежие записи без
-- служебных) опирался ровно на один индекс — (tenant_id, created_at). Отбор «кроме служебных»
-- и сортировка по второму полю в нём не покрыты.
--
-- ПОЧЕМУ ЭТО ВАЖНО ИМЕННО ЗДЕСЬ. ТЗ 15.4 называет журнал первым кандидатом на проблему с
-- объёмом, и причина понятна: продление сеанса пишется у каждого работающего человека каждые
-- несколько минут. Чем дольше живёт центр, тем больше доля служебных записей — и тем больше
-- строк база вынуждена прочитать и выбросить, чтобы набрать одну страницу полезных. Это тот
-- случай, когда запрос не «медленный», а медленнее с каждым месяцем (журнал 589).
--
-- ЧТО ДЕЛАЕМ. Два индекса. Оба добавляются, ничего не меняется и не удаляется — миграция
-- аддитивная, как требует регламент проекта.
--
-- ПОЧЕМУ ЧАСТИЧНЫЙ ИНДЕКС, А НЕ ОБЫЧНЫЙ. Служебные записи в него просто не попадают: индекс
-- получается меньше самой таблицы во столько раз, во сколько служебных записей больше
-- полезных, и сортировка по нему уже готова. Обычный индекс по (tenant_id, created_at, action)
-- пришлось бы читать целиком и отбрасывать служебное на ходу.
--
-- ⚠️ СПИСОК СЛУЖЕБНЫХ ДЕЙСТВИЙ ПОВТОРЁН ЗДЕСЬ ИЗ КОДА (`SERVICE_ACTIONS` в audit.service.ts).
-- Расхождение не сломает выдачу — запрос останется верным, — но индекс перестанет применяться,
-- и всё станет медленным МОЛЧА. Поэтому совпадение двух списков стережёт тест.

-- 1. Самый частый запрос: открыть журнал действий (свежие сверху, служебные скрыты).
CREATE INDEX IF NOT EXISTS audit_log_tenant_visible_created_idx
  ON audit.audit_log (tenant_id, created_at DESC, id DESC)
  WHERE action <> 'auth.refresh';

-- 2. Журнал входов человека (ТЗ 17.1): свои входы и свои неудачные попытки.
--
-- Отбор идёт по паре «человек + действие», а имеющийся индекс (tenant_id, actor_id, created_at)
-- знает только про человека: чтобы найти четыре вида входа, база читает ВСЕ действия этого
-- человека за всё время. У администратора, который работает в системе год, это десятки тысяч
-- строк ради двадцати строк на экране профиля.
CREATE INDEX IF NOT EXISTS audit_log_tenant_actor_action_created_idx
  ON audit.audit_log (tenant_id, actor_id, action, created_at DESC);
