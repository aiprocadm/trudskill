'use client';

/**
 * Падение САМОЙ корневой раскладки (журнал 395, ТЗ 1.1.4).
 *
 * `app/error.tsx` перехватывает ошибки страниц, но не ошибки раскладки, которая эти страницы
 * рисует. Такого файла в проекте не было вовсе: падение раскладки показывало человеку
 * служебный экран браузера — без оформления, без объяснения и без единого действия.
 *
 * Здесь всё своё и без зависимостей от оболочки: раскладка уже упала, полагаться на неё
 * нельзя. Поэтому даже теги `html` и `body` пишутся заново — так требует App Router.
 */
export default function GlobalError({
  error,
  reset
}: {
  error: Error & { digest?: string };
  reset: () => void;
}) {
  return (
    <html lang="ru">
      <body>
        <main className="ui-centered-page">
          <div className="ui-centered-stack">
            <h1>Страница не открылась</h1>
            <p>
              Сбой произошёл до того, как система успела нарисовать экран. Данные не потеряны: всё,
              что было сохранено, осталось на месте.
            </p>
            <p>Нажмите «Повторить». Если не помогает — обновите страницу или войдите заново.</p>
            <button type="button" className="ui-button" onClick={() => reset()}>
              Повторить
            </button>
            {error.digest ? (
              <details>
                <summary>Подробности для поддержки</summary>
                <p>
                  Номер случая: <code>{error.digest}</code>. Назовите его, если будете писать в
                  поддержку, — по нему найдут запись в журнале.
                </p>
              </details>
            ) : null}
          </div>
        </main>
      </body>
    </html>
  );
}
