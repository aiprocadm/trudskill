'use client';

import { SystemMessage, buildThemeVars, uiGlobalStyles } from '@trudskill/ui';

/**
 * Падение САМОЙ корневой раскладки (журнал 395, ТЗ 1.1.4, оформление — ТЗ 2.1).
 *
 * `app/error.tsx` перехватывает ошибки страниц, но не ошибки раскладки, которая эти страницы
 * рисует. Такого файла в проекте не было вовсе: падение раскладки показывало человеку
 * служебный экран браузера — без оформления, без объяснения и без единого действия.
 *
 * Здесь всё своё: раскладка уже упала, полагаться на неё нельзя. Поэтому теги `html` и `body`
 * пишутся заново (так требует App Router) — **и оформление тоже**. Это было упущено: страница
 * ставила классы `ui-*`, но стили пакета вставляет ThemeProvider из раскладки, которой здесь
 * нет, — то есть классы не значили ничего, и человек видел голый текст браузера. Теперь строка
 * стилей и переменные оформления подставляются прямо здесь, без провайдеров и без хранилища:
 * чем меньше машинерии на странице падения, тем выше шанс, что она сама не упадёт.
 *
 * Светлая тема взята жёстко и намеренно: выбор темы человека лежит в хранилище браузера, читать
 * которое на странице падения — лишний риск ради оттенка фона.
 */
export default function GlobalError({
  error,
  reset
}: {
  error: Error & { digest?: string };
  reset: () => void;
}) {
  const details = [
    error.digest ? `номер случая: ${error.digest}` : null,
    error.message.trim() ? `сбой: ${error.message.trim()}` : null
  ]
    .filter((part): part is string => part !== null)
    .join(' · ');

  return (
    <html lang="ru">
      <body style={{ margin: 0 }}>
        <div data-ui-theme="light" style={buildThemeVars('light')}>
          <style>{uiGlobalStyles}</style>
          <main className="ui-centered-page">
            <SystemMessage
              title="Страница не открылась"
              what="Сбой произошёл до того, как система успела нарисовать экран. Данные не потеряны: всё, что было сохранено, осталось на месте."
              next="Нажмите «Повторить». Если не помогает — обновите страницу или войдите заново."
              whom="Если сбой повторяется, сообщите администратору учебного центра и назовите номер случая из подробностей."
              action={
                <button type="button" className="ui-button" onClick={() => reset()}>
                  Повторить
                </button>
              }
              {...(details ? { details } : {})}
            />
          </main>
        </div>
      </body>
    </html>
  );
}
