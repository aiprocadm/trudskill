'use client';

import { SystemMessage } from '@trudskill/ui';
import Link from 'next/link';

import { AppShell } from '../../src/widgets/shell/app-shell';

/**
 * Отказ в доступе (ТЗ 2.1 / Б3).
 *
 * Как было: голое «403 / У вас недостаточно прав для просмотра этой страницы / Вернуться на
 * главную» — вне оболочки, без меню и без выхода. Человек выпадал из системы: единственная
 * ссылка вела на главную, а что делать дальше — не сказано.
 *
 * Стало: страница внутри оболочки — меню, шапка и выход на месте, человек остаётся внутри. Текст
 * по шаблону ТЗ: что случилось → что делать → к кому идти. Кнопка ведёт в чат.
 *
 * Тему обращения НЕ подставляем: экран чата параметров адреса не читает (проверено), и
 * подставленная тема была бы обещанием, которого никто не исполняет, — ровно тот класс дефектов,
 * который в этом репозитории ловят журналом расхождений.
 */
export default function ForbiddenPage() {
  return (
    <AppShell>
      <SystemMessage
        title="Этот раздел вам недоступен"
        what="Раздел открыт другим ролям — например, администратору учебного центра."
        next="Вернитесь на главную или откройте раздел из меню слева: там показано только то, что доступно вам."
        whom="Если раздел нужен вам в работе, напишите администратору центра — права выдаёт он."
        action={
          <>
            <Link href="/chat" className="ui-button">
              Написать администратору
            </Link>
            <Link href="/" className="ui-link">
              На главную
            </Link>
          </>
        }
      />
    </AppShell>
  );
}
