import { SystemMessage } from '@trudskill/ui';

import { privacyPolicyMissing } from '../../../src/features/legal/privacy-link';

/**
 * Политика обработки персональных данных (ТЗ «Стабилизация, UX и развитие», 17.3).
 *
 * **Зачем страница нужна.** Человек ставит галочку «Даю согласие на обработку персональных
 * данных (152-ФЗ)» — и до этой страницы прочитать было нечего. Согласие по закону должно быть
 * ИНФОРМИРОВАННЫМ: галочка без доступного текста юридически стоит столько же, сколько подпись
 * под пустым листом (журнал 579).
 *
 * **Почему страница ПУБЛИЧНАЯ.** Политику читают до входа в систему и вообще без учётной
 * записи: слушатель переходит по ссылке из письма-приглашения, работодатель проверяет, кому
 * отдаёт данные сотрудников. Требовать вход, чтобы прочитать, на что соглашаешься, — то же
 * самое, что не показывать текст вовсе.
 *
 * **Почему текста здесь нет, а есть объяснение.** Оператор персональных данных — учебный
 * центр, а не платформа: он отвечает перед человеком и перед надзором, и политику пишет он.
 * Выдумать её за центр система не может и не должна — подставленный «типовой текст» выглядел бы
 * как настоящая политика и вводил бы в заблуждение и слушателя, и сам центр. Поэтому страница
 * честно говорит: документа пока нет, вот что с этим делать.
 *
 * Когда центр загрузит документ, страница покажет его; пока не загрузил — объясняет ситуацию.
 */
export default function PrivacyPolicyPage() {
  /*
   * Кто перед нами, страница не знает: она публичная и открывается без входа. Поэтому текст
   * взят «для слушателя» — он мягче и никому не даёт задач, которые тот не может выполнить.
   * Сотрудник увидит подсказку для себя в настройках центра, где он и может что-то сделать.
   */
  const missing = privacyPolicyMissing('learner');

  return (
    <main className="ui-centered-page">
      <SystemMessage
        title={missing.title}
        what="Здесь должен быть документ учебного центра: какие данные он собирает, зачем, сколько хранит и как их удалить по вашему требованию."
        next={missing.hint}
        whom="Учебный центр, в который вы записались, — его название указано в письме-приглашении."
        details="Обработка ваших данных в любом случае ограничена законом 152-ФЗ: данные собираются только для обучения и выдачи документов, а вы вправе потребовать их выгрузку и прекращение обработки."
      />
    </main>
  );
}
