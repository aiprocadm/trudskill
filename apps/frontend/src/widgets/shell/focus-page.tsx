'use client';

import { ProtectedRoute } from '../../features/auth/guards';

import type { PropsWithChildren } from 'react';

/**
 * Страница без оболочки — для экрана, где всё лишнее мешает (ТЗ 6.2 / С2).
 *
 * `ProtectedPage` даёт общую оболочку: меню слева, поиск сверху, «Уведомления»,
 * переключатель темы и кнопку «Выйти». На экзамене это не помощь, а помеха: «Выйти»
 * стоит прямо над вопросами, и одно нажатие посреди попытки — потерянная попытка
 * (журнал 495). Здесь остаётся только проверка сессии.
 *
 * **Чего тут намеренно нет.**
 *
 * - Меню и поиска — уводить человека с экзамена некуда.
 * - «Выйти» из системы — выход из режима экзамена экран рисует сам и спрашивает
 *   подтверждение.
 * - Хлебных крошек — их рисует оболочка, а без неё крошке негде стоять.
 * - Гейта соглашения (`AgreementGate`): до попытки человек проходит обычные экраны, где
 *   гейт и срабатывает. Здесь он мог бы запереть человека в экзамене без выхода — ровно то,
 *   чего сам гейт велит избегать.
 */
export const FocusPage = ({ children }: PropsWithChildren) => (
  <ProtectedRoute>
    <div className="ui-focus">{children}</div>
  </ProtectedRoute>
);
