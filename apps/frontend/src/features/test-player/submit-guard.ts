/**
 * Ревизия 2026-08-27 (порция 27, журнал 280) — правило «не сдавать без последнего ответа».
 *
 * Перед сдачей плеер досохраняет черновик текущего вопроса. Если сохранение не удалось
 * (связь пропала, сервер ответил ошибкой), пометка «несохранён» возвращается на место —
 * но сдача шла дальше, и попытка финализировалась на сервере БЕЗ последнего ответа.
 * Человек видел «Тест завершён», не зная, что ответ не дошёл.
 *
 * Для сдачи по кнопке правильный ответ — не сдавать и дать нажать ещё раз. Для автосдачи
 * по нулю таймера выбора нет: время вышло, и несданная попытка всё равно закроется
 * просроченной — сдать с потерей последнего ответа лучше, чем не сдать вовсе.
 */
export interface SubmitGuardInput {
  /** Сдача запущена таймером, а не человеком. */
  auto: boolean;
  /** Черновик текущего вопроса остался несохранённым после попытки досохранить. */
  currentAnswerUnsaved: boolean;
}

export const UNSAVED_ANSWER_SUBMIT_MESSAGE =
  'Последний ответ не сохранился — проверьте связь и нажмите «Завершить тест» ещё раз.';

/** `true` — сдачу нужно остановить и показать `UNSAVED_ANSWER_SUBMIT_MESSAGE`. */
export function shouldBlockSubmit({ auto, currentAnswerUnsaved }: SubmitGuardInput): boolean {
  if (auto) return false;
  return currentAnswerUnsaved;
}
