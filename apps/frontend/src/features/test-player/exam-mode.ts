import type { AnswerDraft, AnswerDraftMap, AttemptQuestion } from './types';
import type { ConfirmRequest } from '@trudskill/ui';

/**
 * Экзамен — отдельный режим (ТЗ «Стабилизация, UX и развитие», 6.2 / С2 и 6.3 / С3).
 *
 * **Как было.** Тест шёл в обычной оболочке: слева меню, сверху поиск, «Уведомления»,
 * переключатель темы и кнопка **«Выйти»** прямо над вопросами. Нажать «Выйти» посреди
 * экзамена, где попытка одна, — потерять её; кнопка стояла там же, где всегда, и ничем
 * не предупреждала (журнал 495).
 *
 * **Как стало.** Экран экзамена рисуется без оболочки. Всё, что на нём есть, относится к
 * попытке: название теста, таймер, «Вопрос N из M», карта вопросов с отметками
 * «отвечен / пропущен», ответ и переходы. Выйти можно, но только через явное подтверждение.
 *
 * Правила собраны здесь чистыми функциями, потому что во фронте нет React Testing Library
 * (`RISK-002`): проверяются их ЗНАЧЕНИЯ, а не текст разметки.
 */

/** Ответ считается данным, если выбран хотя бы один вариант или введён непустой текст. */
export const isAnswered = (draft: AnswerDraft | undefined): boolean =>
  (draft?.selectedOptionIds?.length ?? 0) > 0 || (draft?.textAnswer ?? '') !== '';

export interface QuestionMark {
  id: string;
  /** Номер для человека — позиция в попытке, считая с единицы. */
  number: number;
  answered: boolean;
  current: boolean;
  /** Готовая подпись для подсказки и для читалки с экрана. */
  label: string;
}

/**
 * Карта вопросов попытки: что отвечено, что пропущено, где человек сейчас.
 *
 * Отметки берутся из тех же черновиков, по которым считается «без ответа» в диалоге
 * завершения, — иначе карта и диалог однажды разойдутся в числах.
 */
export const questionMarks = (
  questions: readonly AttemptQuestion[],
  drafts: AnswerDraftMap,
  currentIndex: number
): QuestionMark[] =>
  questions.map((question, index) => {
    const answered = isAnswered(drafts[question.id]);
    return {
      id: question.id,
      number: index + 1,
      answered,
      current: index === currentIndex,
      label: `Вопрос ${index + 1} — ${answered ? 'отвечен' : 'пропущен'}`
    };
  });

/** Сколько вопросов попытки отвечено. Один источник счёта на экран и на диалог. */
export const answeredTotal = (
  questions: readonly AttemptQuestion[],
  drafts: AnswerDraftMap
): number => questions.filter((question) => isAnswered(drafts[question.id])).length;

/** Заголовок вопроса — ТОЛЬКО позиция в попытке (ТЗ 6.3). */
export const questionHeading = (index: number, total: number): string =>
  `Вопрос ${index + 1} из ${total}`;

/*
 * Номер, которым вопрос назван в банке: «Вопрос 3. Кто отвечает за инструктаж…», «Вопрос №3 —
 * …», «3) …». Банк хранит свою нумерацию, а попытка показывает вопросы в своём порядке, поэтому
 * эти числа расходятся: человек читал «Вопрос 3» под счётчиком «Вопрос 1 из 3» (журнал 496).
 */
const BANK_NUMBER_PREFIX = /^\s*(?:вопрос\s*)?№?\s*\d+\s*[.):\-–—]\s*|^\s*вопрос\s*№?\s*\d+\s*$/i;

/**
 * Текст вопроса без номера из банка.
 *
 * Если от названия после снятия номера ничего не остаётся (вопрос назван просто «Вопрос 3»),
 * возвращается пустая строка: показывать нечего, номер уже сказан счётчиком.
 */
export const questionStatement = (title: string): string => title.replace(BANK_NUMBER_PREFIX, '');

/**
 * Подтверждение выхода из режима экзамена (ТЗ 6.2: «выход — через явное подтверждение»).
 *
 * Последствие называется числом: сколько ответов уже дано и что попытка остаётся начатой.
 * Слово вводить не просим — на экзамене это было бы издевательством (правило из 5.3 / Э3).
 */
export const leaveExamRequest = (input: { answered: number; total: number }): ConfirmRequest => ({
  title: 'Выйти из теста',
  message:
    input.answered > 0
      ? `Отвечено ${input.answered} из ${input.total}. Попытка останется начатой, а время продолжит идти — вернуться и дописать можно, пока оно не вышло.`
      : `Попытка останется начатой, а время продолжит идти. Ответов пока нет: вернуться и начать отвечать можно, пока время не вышло.`,
  confirmLabel: 'Выйти из теста',
  cancelLabel: 'Остаться в тесте'
});
