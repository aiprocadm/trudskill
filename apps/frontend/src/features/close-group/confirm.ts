import type { ConfirmRequest } from '@trudskill/ui';

/**
 * Подтверждение закрытия группы (ТЗ «Стабилизация, UX и развитие», 5.3 / Э3).
 *
 * **Как было.** «Закрыть группу (12 чел.)» и запуск цепочки «экзамен → протокол → документы»
 * срабатывали с одного нажатия — без диалога. Это самое тяжёлое действие учебного центра:
 * слушателям выпускаются документы, состав группы после этого изменить нельзя.
 *
 * **Правило.** Диалог называет объект («Закрыть группу «Группа 360px»?»), называет последствие
 * и требует ввода названия группы — механика «Обезличивания» и отзыва лицензии (`CMP-005`):
 * ввод подтверждает и намерение, и что выбрана та самая группа.
 */
export const closeGroupRequest = (input: {
  groupName: string;
  learnersCount: number;
  mode: 'close' | 'chain';
}): ConfirmRequest => {
  const who =
    input.learnersCount > 0 ? `${input.learnersCount} чел.` : 'слушатели, которых отберёт сервер';
  const what =
    input.mode === 'chain'
      ? 'протокол на группу и удостоверение каждому сдавшему'
      : 'протокол и удостоверения выбранным';
  return {
    title: `Закрыть группу «${input.groupName}»?`,
    message: `Будут выпущены ${what} (${who}). После закрытия состав группы изменить будет нельзя, выпущенные документы получат номера.`,
    confirmLabel: 'Закрыть группу',
    tone: 'danger',
    requireTyping: {
      word: input.groupName,
      label: 'Введите название группы, чтобы подтвердить закрытие',
      hint: `Название группы: ${input.groupName}`
    }
  };
};
