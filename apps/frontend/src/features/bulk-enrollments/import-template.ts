import * as XLSX from 'xlsx';

import type { BulkOutcome } from '@trudskill/ui';

/**
 * Шаблон файла для импорта и отчёт об ошибках (ТЗ «Стабилизация, UX и развитие», 12.1).
 *
 * **Зачем шаблон.** Администратору присылают список из шестидесяти человек в произвольном виде.
 * Разбор принимает синонимы заголовков («ФИО», «фио», «fio»), но угадать, какие колонки система
 * вообще ждёт и что писать в СНИЛС, по пустому экрану нельзя. Скачанный файл превращает
 * «догадайся сам» в «заполни бланк» (журнал 516).
 *
 * **Зачем отчёт об ошибках.** Итог «Загружено 58, пропущено 2» без списка — это задача найти две
 * строки в файле на шестьдесят. Отчёт даёт номер строки, имя и причину; его можно отправить тому,
 * кто прислал список, не пересказывая своими словами (журнал 517).
 *
 * Чистые функции: собирают книгу или таблицу и отдают её, не трогая браузер. Сохранение —
 * отдельным шагом, чтобы правила можно было проверить значениями (`RISK-002`).
 */

/** Колонки шаблона — ровно те, что понимает разбор файла. */
export const TEMPLATE_COLUMNS = [
  { header: 'ФИО', hint: 'Фамилия Имя Отчество полностью, как в паспорте' },
  { header: 'Почта', hint: 'На неё придёт ссылка для входа. Без неё слушатель не сможет войти' },
  { header: 'СНИЛС', hint: '11 цифр. Можно с дефисами: 112-233-445 95' },
  { header: 'Должность', hint: 'Необязательно. Попадёт в документы об обучении' }
] as const;

/** Строка-пример: показывает формат, а не просто занимает место. */
export const TEMPLATE_EXAMPLE = [
  'Иванов Иван Иванович',
  'ivanov@example.ru',
  '112-233-445 95',
  'Электромонтёр'
] as const;

/**
 * Книга шаблона: лист с заголовками, строкой-примером и пояснением каждой колонки.
 *
 * Пояснения лежат ОТДЕЛЬНЫМ листом, а не строкой под заголовками: строка с пояснением попала бы
 * в разбор как данные, и человек получил бы «Строка 2: СНИЛС указан неверно» за подсказку,
 * которую мы сами и написали.
 */
export const buildTemplateWorkbook = (): XLSX.WorkBook => {
  const book = XLSX.utils.book_new();

  const sheet = XLSX.utils.aoa_to_sheet([
    TEMPLATE_COLUMNS.map((column) => column.header),
    [...TEMPLATE_EXAMPLE]
  ]);
  XLSX.utils.book_append_sheet(book, sheet, 'Слушатели');

  const help = XLSX.utils.aoa_to_sheet([
    ['Колонка', 'Что писать'],
    ...TEMPLATE_COLUMNS.map((column) => [column.header, column.hint]),
    [],
    ['Строку-пример удалите перед загрузкой — иначе Иванов попадёт в группу.'],
    ['Порядок колонок неважен, заголовки можно писать по-своему: «Фамилия Имя Отчество», «e-mail».']
  ]);
  XLSX.utils.book_append_sheet(book, help, 'Как заполнять');

  return book;
};

/** Имя файла шаблона — человеческое, а не «template.xlsx». */
export const TEMPLATE_FILE_NAME = 'Шаблон списка слушателей.xlsx';

/** Сохранить шаблон на диск пользователя. */
export const downloadTemplate = (): void => {
  XLSX.writeFile(buildTemplateWorkbook(), TEMPLATE_FILE_NAME);
};

/** Заголовки отчёта: подпись уже содержит имя и номер строки исходного файла. */
export const ERROR_REPORT_HEADERS = ['Кто', 'Почему не загружен'] as const;

/**
 * Отчёт об ошибках импорта — строками «кто» и «почему».
 *
 * Берётся из ТОГО ЖЕ итога, что показан на экране: иначе отчёт и экран однажды разойдутся в
 * числах, и человек не будет знать, какому верить.
 */
export const buildErrorReport = (outcome: BulkOutcome): string[][] =>
  outcome.failures.map((failure) => [failure.label, failure.reason]);

/** Имя файла отчёта: с датой, потому что таких файлов у администратора будет много. */
export const errorReportFileName = (today: string): string =>
  `Ошибки импорта ${today.slice(0, 10)}.csv`;
