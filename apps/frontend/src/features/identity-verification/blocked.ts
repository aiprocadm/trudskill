/**
 * Чего не хватает, чтобы отправить документы на проверку (ТЗ 5.8 / Э8).
 *
 * Чистая функция рядом с экраном: её значения проверяются тестом, а экран лишь показывает
 * строку. Раньше кнопка просто выключалась — человек жал по ней и не понимал, в чём дело
 * (журнал 465).
 *
 * Перечисление ПОИМЁННОЕ, а не «заполните всё»: «загрузите селфи и фото паспорта» говорит,
 * что делать, «форма заполнена не полностью» — не говорит ничего.
 */
export const identitySubmitBlockedReason = (input: {
  selfie: boolean;
  passport: boolean;
  personalDataGranted: boolean;
  photoGranted: boolean;
}): string | undefined => {
  /*
   * Согласия идут первыми: без них загружать файлы бессмысленно, а отказ от согласия на фото —
   * законное право слушателя, и он должен видеть последствие словами.
   */
  if (!input.personalDataGranted && !input.photoGranted) {
    return 'Дайте согласие на обработку персональных данных и на обработку фото.';
  }
  if (!input.personalDataGranted) return 'Дайте согласие на обработку персональных данных.';
  if (!input.photoGranted) return 'Дайте согласие на обработку фото.';

  const missing = [
    ...(input.selfie ? [] : ['селфи']),
    ...(input.passport ? [] : ['фото паспорта'])
  ];
  if (missing.length === 0) return undefined;
  return `Загрузите ${missing.join(' и ')}.`;
};
