/**
 * Открытая вкладка живёт в адресе страницы (ТЗ «Стабилизация, UX и развитие», 5.7 / Э7).
 *
 * Зачем. Вкладка, которой нет в адресе, не передаётся ссылкой: «посмотри счета аренды» —
 * и человек на той стороне открывает страницу на первой вкладке и ищет сам. Кнопка «назад»
 * тоже ведёт себя неожиданно — уводит со страницы целиком вместо возврата к прошлой вкладке.
 *
 * Чистая функция вынесена отдельно от хука: её можно проверить тестом без React и без
 * маршрутизатора, а сторож — прочитать глазами.
 */

/** Параметр адреса, в котором живёт открытая вкладка. Одно имя на всё приложение. */
export const TAB_PARAM = 'tab';

/**
 * Какая вкладка открыта. Незнакомое значение (опечатка в ссылке, вкладку переименовали)
 * возвращает к первой: пустая страница с сообщением «раздел не найден» здесь была бы
 * наказанием за чужую опечатку.
 */
export const activeTab = (
  raw: string | null | undefined,
  tabs: readonly string[],
  fallback?: string
): string => {
  const first = fallback ?? tabs[0] ?? '';
  if (!raw) return first;
  return tabs.includes(raw) ? raw : first;
};

/**
 * Адрес с открытой вкладкой. Остальные параметры отбора сохраняются: человек отфильтровал
 * список, переключил вкладку и вернулся — отбор на месте.
 */
export const tabHref = (pathname: string, search: string, id: string): string => {
  const params = new URLSearchParams(search);
  params.set(TAB_PARAM, id);
  return `${pathname}?${params.toString()}`;
};
