/**
 * Доля пройденного курса — ОДНО правило на экран и на сервер (режим ревизии, журнал 604).
 *
 * **Что было.** Одну и ту же величину считали в двух местах, и она расходилась дважды.
 *
 * 1. **Курс без материалов.** Сервер считал такой курс пройденным на 100% и ставил статус
 *    «завершён» — по нему выдаются документы. Экран показывал 0%. Слушатель видел ноль,
 *    система считала обучение законченным.
 * 2. **Округление.** Сервер хранит два знака после запятой, экран округлял до целого. При
 *    79,6% человек видел «80%» и не понимал, почему его не допускают до экзамена. Та же
 *    ловушка, что обходили в задаче 10.4, где процент округляется ВНИЗ.
 *
 * **Почему копия правила, а не общий пакет.** Ни одно из приложений не зависит от
 * `@trudskill/shared-types` напрямую, а контракты `packages/api-contracts` правятся только
 * решением владельца. Поэтому здесь применён приём, уже принятый в этом коде для разбора
 * тикета подключения: копия правила, РАСХОЖДЕНИЕ КОТОРОЙ СТЕРЕЖЁТ ТЕСТ. Копия без сторожа
 * была бы ровно тем, от чего эта правка избавляет.
 */

/**
 * Пустой курс — это 100%, а не 0.
 *
 * Правило сервера: делить не на что, значит пройдено всё, что было. Спорить с ним здесь
 * нельзя — по этому же правилу он ставит статус «завершён» и выдаёт документы. Показывать
 * другое число значит показывать неправду.
 */
export const courseCompletionPercent = (completedCount: number, totalCount: number): number => {
  if (totalCount <= 0) return 100;
  const raw = (completedCount / totalCount) * 100;
  /* Два знака после запятой и рамки 0…100 — ровно как `normalizePercent` на сервере. */
  return Math.min(100, Math.max(0, Math.round(raw * 100) / 100));
};

/**
 * Процент словами для подписи.
 *
 * Хвостовые нули не пишем: «80%» читается, «80.00%» выглядит машинным. Дробная часть
 * сохраняется — именно она отличает 79,6% от порога в 80%, и скрыть её значит вернуть ту же
 * путаницу.
 */
export const formatPercent = (value: number): string =>
  `${Number.isInteger(value) ? value : Number(value.toFixed(2))}%`;
