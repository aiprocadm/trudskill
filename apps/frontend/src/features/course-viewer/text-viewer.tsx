'use client';

import type { Material } from '../mvp/types';

interface Props {
  material: Material;
}

/**
 * Текстовый материал (ТЗ «Стабилизация, UX и развитие», 2.5.a / Б7).
 *
 * **Как было.** Здесь стояла заглушка, печатавшая слушателю: «Текстовый материал станет доступен
 * после расширения backend полем `textBody`». Человек, пришедший учиться, читал название поля
 * базы данных — и курс из одного текстового урока пройти было физически нельзя.
 *
 * Хранилище появилось миграцией 0095. Текст простой, без разметки: абзацы разделены пустой
 * строкой и так и показываются. Разметку сознательно не вводим — она потребовала бы
 * очистки от опасного содержимого, а это отдельная работа, и в объём Р8 она не входит.
 */
export const TextViewer = ({ material }: Props) => {
  const body = material.textBody?.trim() ?? '';

  if (!body) {
    /*
     * Пусто — говорим человеческим языком, что делать, и НЕ называем причину кодом.
     * Правило продукта №3: пустой экран объясняет, что это, зачем и что сделать первым.
     */
    return (
      <div className="course-player__placeholder" data-testid="text-empty">
        <strong>{material.title}</strong>
        <p>
          Материал ещё готовится — текста пока нет. Если он нужен вам сейчас, сообщите в учебный
          центр: остальные материалы курса при этом доступны.
        </p>
      </div>
    );
  }

  return (
    <article className="course-player__text" data-testid="text-viewer">
      <h2 className="ui-section-title">{material.title}</h2>
      {/*
        Ключ по номеру абзаца: абзацы не переставляются и не удаляются по одному — текст
        показывается целиком и меняется целиком. Своего идентификатора у абзаца нет и быть
        не должно: это простой текст, а не список записей.
      */}
      {body.split(/\n\s*\n/).map((paragraph, index) => (
        <p key={`${index}-${paragraph.slice(0, 24)}`} className="ui-prose">
          {paragraph}
        </p>
      ))}
    </article>
  );
};
