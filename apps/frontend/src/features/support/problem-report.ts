/**
 * «Сообщить о проблеме» (ТЗ «Стабилизация, UX и развитие», 15.5).
 *
 * **Зачем это дешевле поддержки по телефону.** Человек, у которого что-то не работает, обычно
 * не может объяснить, что именно: «не открывается», «выдало ошибку», «всё пропало». Разговор
 * уходит на выяснение, где он был и что нажимал, — и половина сведений теряется, потому что
 * человек уже ушёл с той страницы.
 *
 * Кнопка прикладывает контекст сама: адрес страницы, роль, номер запроса, версия сборки. То
 * есть ровно то, что дежурный по [runbook](../../../../docs/ops/runbook.md) спрашивает первым.
 *
 * **Чего здесь намеренно НЕТ.** Ни снимка экрана, ни содержимого полей, ни списка последних
 * действий. На экранах этой системы почти всегда персональные данные слушателей: ФИО, СНИЛС,
 * паспортные фотографии. Обращение в поддержку не должно превращаться в канал их утечки — а
 * именно этим оборачивается «приложим побольше на всякий случай» (журнал 583).
 */

/** Что уходит вместе с обращением. Список закрыт: новое поле — это решение, а не мелочь. */
export interface ProblemReportContext {
  /** Где человек был. Без строки запроса: в ней встречаются идентификаторы. */
  page: string;
  /** Кем он работает — чтобы понимать, что ему вообще доступно. */
  role: string;
  /**
   * Номер последнего запроса, если он известен. По нему дежурный находит ровно этот случай, а
   * не «что-то похожее примерно в то же время».
   */
  requestId?: string;
  /** Версия сборки: «у меня не работает» и «у меня старая версия» — разные разговоры. */
  release: string;
}

/**
 * Адрес страницы без строки запроса и без хвоста после решётки.
 *
 * В строке запроса живут идентификаторы («?learner=l_8f3a…»), а по правилам продукта
 * идентификатор — не то, что показывают и пересылают. Для понимания, где был человек, хватает
 * самого адреса.
 */
export const safePage = (url: string | undefined): string => {
  if (!url) return 'неизвестно';
  const withoutHash = url.split('#')[0] ?? '';
  const withoutQuery = withoutHash.split('?')[0] ?? '';
  return withoutQuery.length > 0 ? withoutQuery : '/';
};

/**
 * Собрать контекст обращения.
 *
 * Отдельной функцией, потому что у неё есть свойство, которое легко потерять при правке в
 * разметке: она НЕ добавляет ничего сверх перечисленного. Проверить это на функции можно, на
 * коде экрана — почти нет.
 */
export const problemReportContext = (input: {
  url?: string;
  role?: string;
  requestId?: string;
  release?: string;
}): ProblemReportContext => ({
  page: safePage(input.url),
  role: input.role && input.role.length > 0 ? input.role : 'неизвестно',
  ...(input.requestId ? { requestId: input.requestId } : {}),
  release: input.release && input.release.length > 0 ? input.release : 'неизвестно'
});

/** Сколько символов принимает описание. */
export const PROBLEM_REPORT_MIN = 10;
export const PROBLEM_REPORT_MAX = 2000;

/**
 * Что не так с описанием — словами, которые видит человек.
 *
 * `null` означает «всё в порядке». Нижняя граница не придирка: «не работает» без продолжения
 * не даёт дежурному ничего, и обращение всё равно вернётся вопросом «а что именно?» — только
 * через день.
 */
export const problemReportError = (text: string): string | null => {
  const trimmed = text.trim();
  if (trimmed.length === 0) return 'Опишите, что произошло: без описания обращение не поможет.';
  if (trimmed.length < PROBLEM_REPORT_MIN) {
    return 'Напишите чуть подробнее: что вы делали и что увидели вместо ожидаемого.';
  }
  if (trimmed.length > PROBLEM_REPORT_MAX) {
    return `Слишком длинно: уместите в ${PROBLEM_REPORT_MAX} символов, самое важное — в начало.`;
  }
  return null;
};

/** Подпись пункта меню. Называет действие человека, а не механизм системы. */
export const PROBLEM_REPORT_LABEL = 'Сообщить о проблеме';
