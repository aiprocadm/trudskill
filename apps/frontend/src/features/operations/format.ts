import { formatDateTime } from '../mvp/screen-helpers';

import type { QuarantinedJob } from './types';

/**
 * Дата и время по-русски. ТЗ 5.12.1: формат один на всё приложение — своя копия здесь и в
 * проверке работ печатали один и тот же момент по-разному (журнал 479).
 */
export { formatDateTime };

/**
 * «Кто и когда разобрал» — вторая строка под статусом разобранного сообщения (§5.431).
 *
 * Сервер хранил и присылал `resolvedBy`/`resolvedAt`, а экран их не показывал: вопрос «кто
 * отбросил упавший выпуск удостоверения» выяснялся только по базе. В карантин попадают
 * несостоявшиеся выпуски документов, и разбирают их вручную — значит, у разбора должен быть
 * автор, видимый там же, где виден результат.
 *
 * Имя подставляет СЕРВЕР (левое соединение с учётными записями): справочник имён на стороне
 * экрана врёт на удалённых и на неизвестных записях, а сырой идентификатор человеку
 * показывать нельзя (правило продукта №2). Если имени нет — так и говорим, вместо
 * правдоподобной неправды вроде «система».
 */
export const resolutionNote = (job: QuarantinedJob): string => {
  const who = job.resolvedByName ?? 'учётная запись удалена';
  const when = job.resolvedAt ? formatDateTime(job.resolvedAt) : 'время неизвестно';
  // Число возвращений говорит о том, что сообщение падало снова — это меняет решение
  // человека: возвращать ещё раз или всё-таки отбросить.
  const returns = job.republishCount > 1 ? `, возвращали ${job.republishCount} раза` : '';
  return `${who}, ${when}${returns}`;
};
