/**
 * Ссылка на политику обработки персональных данных (ТЗ «Стабилизация, UX и развитие», 17.3).
 *
 * **Что было.** Человек ставил галочку «Даю согласие на обработку персональных данных (152-ФЗ)»
 * — и не имел никакой возможности прочитать, на что соглашается. Ссылки на политику не было ни
 * рядом с галочкой, ни где-либо ещё в продукте (журнал 579).
 *
 * Это не придирка к оформлению. Согласие по закону должно быть ИНФОРМИРОВАННЫМ: человек
 * соглашается на конкретную обработку конкретных данных конкретным лицом. Галочка без текста —
 * это подпись под пустым листом, и юридически она стоит ровно столько же.
 *
 * **Что стало.** Рядом с каждой галочкой стоит ссылка на политику того центра, который эти
 * данные обрабатывает.
 *
 * **Почему политика центра, а не платформы.** Обрабатывает данные слушателя учебный центр — он
 * оператор, он же отвечает перед человеком и перед надзором. Платформа — обработчик по
 * поручению, и её собственная политика к согласию слушателя отношения не имеет.
 */

/** Куда ведёт ссылка. Один адрес на весь продукт: политика у центра одна. */
export const PRIVACY_POLICY_HREF = '/legal/privacy';

/** Подпись ссылки. Называет документ, а не действие: человек идёт читать, а не соглашаться. */
export const PRIVACY_POLICY_LABEL = 'Политика обработки персональных данных';

/**
 * Что показать, когда центр политику ещё не загрузил.
 *
 * Тексты разные для сотрудника и для слушателя, и это принципиально. Сотруднику нужно знать,
 * что делать, — это его задача. Слушателю задачу давать нельзя: он не может ни загрузить
 * политику, ни повлиять на это, и «обратитесь к администратору» здесь единственное честное
 * указание.
 */
export const privacyPolicyMissing = (viewer: 'staff' | 'learner') =>
  viewer === 'staff'
    ? {
        title: 'Политика обработки персональных данных не загружена',
        hint: 'Пока её нет, слушатели соглашаются на обработку данных, не видя текста, — а такое согласие юридически не считается информированным. Загрузите документ в настройках центра.',
        action: 'Перейти в настройки центра'
      }
    : {
        title: 'Политика обработки данных пока не опубликована',
        hint: 'Обратитесь в учебный центр: текст должен быть доступен вам до того, как вы даёте согласие.',
        action: undefined
      };
