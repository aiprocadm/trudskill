import { formatDate } from '../mvp/screen-helpers';

/**
 * «Когда собрана выгрузка и кем» — одной строкой в колонке «Дата» (§5.432).
 *
 * Выгрузка в государственный реестр — регулируемое действие: при проверке спрашивают, кто её
 * отправил. Сервер хранил автора (`generatedBy`) и присылал его экрану, а экран не показывал
 * вовсе — ответ был только в базе.
 *
 * Отдельной колонки не заводим: у таблицы выгрузок их шесть при бюджете семь (§13.2), а «кто»
 * читается вместе с «когда». Имя подставляет СЕРВЕР: сырой идентификатор человеку показывать
 * нельзя (правило продукта №2), а справочник имён на стороне экрана врёт на удалённых
 * записях. Нет имени — говорим прямо, вместо правдоподобной неправды вроде «система».
 */
export const exportedOn = (batch: {
  createdAt: string;
  generatedBy?: string;
  generatedByName?: string | null;
}): string => {
  const when = formatDate(batch.createdAt);
  if (!batch.generatedBy) return when;
  return `${when} · ${batch.generatedByName ?? 'учётная запись удалена'}`;
};
