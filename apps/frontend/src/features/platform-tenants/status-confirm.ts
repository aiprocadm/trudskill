import type { PlatformTenantDto, PlatformTenantStatus } from './types';
import type { ConfirmRequest } from '@trudskill/ui';

/**
 * Подтверждение смены статуса центра (ТЗ «Стабилизация, UX и развитие», 5.3 / Э3).
 *
 * **Как было.** «Приостановить центр» и «Перевести в архив» срабатывали с одного нажатия
 * в меню строки — без диалога вовсе; самая тяжёлая операция платформы стояла рядом со «Сменить
 * тариф».
 *
 * **Правило.** Диалог называет объект («центр «Ромб»»), называет последствие («сотрудники и
 * слушатели не смогут войти») и требует осознанного клика. Для самого тяжёлого — перевода в
 * архив — ввод кода центра: так подтверждается и намерение, и что выбран тот самый центр
 * (`CMP-005`, механика «Обезличивания» и отзыва лицензии).
 */
export const statusChangeRequest = (
  tenant: Pick<PlatformTenantDto, 'name' | 'code'>,
  status: PlatformTenantStatus
): ConfirmRequest => {
  switch (status) {
    case 'suspended':
      return {
        title: 'Приостановить центр',
        message: `Центр «${tenant.name}» перестанет работать: сотрудники и слушатели не смогут войти, пока центр приостановлен. Вернуть работу можно действием «Включить работу центра».`,
        confirmLabel: 'Приостановить центр',
        tone: 'danger'
      };
    case 'archived':
      return {
        title: 'Перевести центр в архив',
        message: `Центр «${tenant.name}» уйдёт в архив: работа остановится, вход закроется для всех его пользователей. Вернуть его из архива может только администратор платформы — через приостановку.`,
        confirmLabel: 'Перевести в архив',
        tone: 'danger',
        requireTyping: {
          word: tenant.code,
          label: 'Введите код центра, чтобы подтвердить перевод в архив',
          hint: `Код центра: ${tenant.code}`
        }
      };
    case 'trial':
      return {
        title: 'Перевести на пробный период',
        message: `Центр «${tenant.name}» снова заработает в пробном режиме: вход откроется для всех его пользователей.`,
        confirmLabel: 'Перевести на пробный период'
      };
    case 'active':
    default:
      return {
        title: 'Включить работу центра',
        message: `Центр «${tenant.name}» снова будет работать: вход откроется для всех его пользователей.`,
        confirmLabel: 'Включить работу центра'
      };
  }
};
