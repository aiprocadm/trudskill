/**
 * Разбор параметра `?next=` — куда вести человека после успешного входа.
 *
 * **Зачем.** `ProtectedRoute` уводит анонима на `/login?next=<куда он шёл>`, то есть
 * адрес назначения известен. Раньше его никто не читал, и вход всегда высаживал на «/»:
 * ссылки из писем и закладки не доводили до цели.
 *
 * **Почему отдельный чистый модуль.** Это единственное место, где чужая строка
 * превращается в адрес перехода, — классическая дыра «открытый редирект»: по ссылке
 * `/login?next=//evil.com` человек вводит пароль на нашем сайте, а оказывается на чужом,
 * похожем, и вводит его там ещё раз. Проверку удобнее держать отдельно от компонента:
 * её можно перечислить тестом на злые варианты, не поднимая React.
 *
 * **Принцип.** Разрешено только то, что заведомо ведёт на наш же сайт: путь, начинающийся
 * с одного «/». Всё остальное — запасной адрес.
 */

/**
 * Выдуманный домен-подставка. Настоящий адрес страницы нам не нужен и в тестах его нет:
 * важно лишь, останется ли разобранный адрес на ТОМ ЖЕ хосте, что и база. Зона `.invalid`
 * зарезервирована стандартом и никому не принадлежит, поэтому совпадение с реальным
 * сайтом исключено.
 */
const BASE_ORIGIN = 'https://next-target.invalid';

/**
 * Страницы, на которые нельзя приземляться после входа: форма входа сразу после
 * успешного входа выглядит как «вход не сработал», а `/logout` тут же выкинет обратно.
 */
const NON_LANDING_PATHS = ['/login', '/logout'];

/**
 * Убирает управляющие символы (табуляцию, перевод строки и прочие невидимки).
 *
 * Написано перебором кодов, а не регулярным выражением, намеренно: регулярка с такими
 * символами внутри превращает исходник в файл с невидимыми байтами, который потом никто
 * не может ни прочитать, ни отредактировать.
 */
const stripControlChars = (value: string): string =>
  Array.from(value)
    .filter((char) => {
      const code = char.codePointAt(0) ?? 0;
      return code > 0x1f && code !== 0x7f;
    })
    .join('');

const isNonLandingPath = (pathname: string): boolean =>
  NON_LANDING_PATHS.some((path) => pathname === path || pathname.startsWith(`${path}/`));

/**
 * Возвращает безопасный внутренний адрес или `null`, если строке доверять нельзя.
 *
 * Порядок проверок важен: сначала убираем то, что браузер убирает молча (иначе строка
 * «безопасная на вид» станет опасной уже после нашей проверки), и только потом смотрим
 * на начало и на итоговый хост.
 */
export const parseSafeNextTarget = (raw: string | null | undefined): string | null => {
  if (typeof raw !== 'string') return null;

  // Браузер выбрасывает управляющие символы из адреса сам и никого не спрашивает:
  // «/<таб>/evil.com» превращается в «//evil.com», то есть в чужой хост. Поэтому чистим
  // их ДО остальных проверок, иначе проверять будем не ту строку, по которой пойдёт переход.
  const cleaned = stripControlChars(raw).trim();
  if (!cleaned) return null;

  // Обратный слэш браузер считает тем же «/», значит «/\evil.com» — это «//evil.com».
  // В нормальном пути обратного слэша не бывает (в адресе он записывается как %5C),
  // поэтому запрещаем его целиком, а не пытаемся угадать безопасные случаи.
  if (cleaned.includes('\\') || cleaned.toLowerCase().includes('%5c')) return null;

  // Один «/» в начале — это путь на нашем сайте. Два — уже чужой хост
  // («//evil.com» равнозначно «https://evil.com»). Ни протоколов, ни относительных путей.
  if (!cleaned.startsWith('/') || cleaned.startsWith('//')) return null;

  let parsed: URL;
  try {
    parsed = new URL(cleaned, BASE_ORIGIN);
  } catch {
    return null;
  }

  // Последний рубеж: что бы ни осталось в строке, разбор обязан приземлиться на базовый
  // хост. Так же отсеиваются псевдопротоколы (`javascript:`, `data:`) — у них другой origin.
  if (parsed.origin !== BASE_ORIGIN) return null;

  /*
   * Проверять НАДО РЕЗУЛЬТАТ разбора, а не исходную строку.
   *
   * Разбор адреса схлопывает `..` и `.` уже ПОСЛЕ нашей проверки начала строки, поэтому
   * «/..//evil.com» выглядит безопасным (начинается с одного «/»), а превращается в
   * «//evil.com» — то есть в чужой хост. Проверка `origin` этого не ловит: хост-то у
   * разобранного адреса базовый, опасность появляется позже, когда полученную строку
   * отдают в переход. Так что смотрим именно на итоговый путь.
   */
  if (!parsed.pathname.startsWith('/') || parsed.pathname.startsWith('//')) return null;
  if (isNonLandingPath(parsed.pathname)) return null;

  const target = `${parsed.pathname}${parsed.search}${parsed.hash}`;
  // Пояс поверх подтяжек: строка, которую мы реально вернём, тоже обязана быть
  // одиночным «/…». Дешевле, чем ещё раз доказывать, что предыдущая проверка полна.
  if (!target.startsWith('/') || target.startsWith('//')) return null;

  return target;
};

/**
 * То же самое, но сразу с запасным адресом: небезопасный или отсутствующий `next`
 * не должен ломать вход — человек просто попадает туда, куда попадал раньше.
 */
export const resolveNextTarget = (raw: string | null | undefined, fallback: string): string =>
  parseSafeNextTarget(raw) ?? fallback;
