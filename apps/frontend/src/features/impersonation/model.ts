import { roleNameRu } from '../texts/roles.ru';

import type { UserSession } from '../../entities/session/model';

/**
 * Режим «Войти от имени» (ТЗ «Стабилизация, UX и развитие», 13.5).
 *
 * **Как было.** Механизм сделан правильно: администратор платформы входит в кабинет центра,
 * вход пишется в журнал, и признак живёт в сессии — каждое последующее действие попадает в
 * журнал с пометкой поддержки (порция 33, журнал 270). Но **в интерфейсе он невидим**:
 * `auth/me` признак не отдавал вовсе, поэтому экран о нём не знал. Человек из поддержки
 * работал в чужом кабинете и ничем не отличал это от собственного — а сотрудник центра потом
 * видел в журнале действия, которых не совершал (журнал 551).
 *
 * **Почему признак приходит с сервера, а не выводится по ролям.** В этом режиме роль ровно та
 * же, что у настоящего сотрудника центра: по ней режим неотличим. Единственный надёжный
 * источник — метка в подписанном токене, которую сервер и кладёт в сессию.
 */

export const isImpersonating = (session: UserSession | null): boolean =>
  Boolean(session?.user.impersonatedBy);

/**
 * Текст полосы: от имени какого центра и под какой ролью идёт работа.
 *
 * Название центра берётся из сессии, а не выдумывается: человек из поддержки ведёт несколько
 * центров сразу, и «вы в чужом кабинете» без имени центра не отвечает на вопрос «в чьём».
 * Роль называется словарём Р1 — тем же, что в шапке, а не кодом.
 */
export const impersonationBanner = (
  session: UserSession | null,
  tenantName?: string
): { text: string; exitLabel: string } | null => {
  if (!isImpersonating(session)) return null;

  const role = session!.roles[0];
  const roleName = role ? roleNameRu(role) : 'сотрудника центра';
  /*
   * Без названия центр НЕ называется кодом: сырой идентификатор человеку запрещён правилом
   * продукта, и сторож оболочки это ловит. Лучше сказать «вашего центра» — полоса всё равно
   * объясняет главное: вы не у себя, и след останется в журнале (журнал 551).
   */
  const where = tenantName?.trim() ? `«${tenantName.trim()}»` : 'учебного центра';

  return {
    text: `Вы работаете от имени центра ${where} под ролью «${roleName}». Всё, что вы сделаете, попадёт в журнал центра как действие поддержки.`,
    exitLabel: 'Выйти из режима'
  };
};

/**
 * Пометка в подтверждении опасного действия.
 *
 * ТЗ 13.5 разрешает выбор: либо запретить необратимые действия в этом режиме, либо потребовать
 * отдельное подтверждение с пометкой. Выбран второй путь: запрет сломал бы саму поддержку —
 * к ней и обращаются тогда, когда центр сам сделать не может. А вот молча выполнить
 * необратимое от чужого имени нельзя: человек должен видеть, ЧЬИМ именем он это делает.
 */
export const IMPERSONATION_CONFIRM_NOTE =
  'Вы действуете от имени центра: в журнале это останется как действие поддержки.';

export const impersonationConfirmNote = (session: UserSession | null): string | undefined =>
  isImpersonating(session) ? IMPERSONATION_CONFIRM_NOTE : undefined;
