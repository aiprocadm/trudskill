/**
 * Публичная страница состояния сервиса (ТЗ «Стабилизация, UX и развитие», 18.3).
 *
 * **Зачем.** Когда у центра «ничего не открывается», он должен знать, куда посмотреть. Иначе
 * первый же сбой превращается в десяток звонков с одним и тем же вопросом — и в ощущение, что
 * никто ничего не делает. Для арендной модели это часть договорных ожиданий.
 *
 * **Что страница НЕ показывает и почему.** Ни состояния базы, ни длины очередей, ни версий, ни
 * имён служб. Публичная страница состояния — это подсказка и посетителю, и тому, кто ищет, за
 * что дёрнуть: «очередь задач переполнена» сообщает атакующему, что система под нагрузкой и
 * чем её добить. Поэтому наружу уходит одно из трёх слов и время последней проверки
 * (журнал 586).
 */

/** Три состояния — больше человеку не нужно, а меньше не различает «медленно» и «лежит». */
export type ServiceState = 'ok' | 'degraded' | 'down';

export interface ServiceStatusView {
  state: ServiceState;
  /** Что показать крупно. */
  title: string;
  /** Что это значит для того, кто сейчас работает. */
  what: string;
  /** Что делать. У «работает» — тоже: иначе человек продолжит гадать. */
  next: string;
}

/**
 * Свести внутреннюю проверку готовности к одному из трёх слов.
 *
 * Внутрь приходит подробный ответ `health/ready`, наружу уходит слово. Правило простое: не
 * отвечает вовсе — «недоступна»; отвечает, но что-то из зависимостей нездорово — «работает с
 * перебоями»; всё зелёное — «работает».
 *
 * **Неизвестное считается неполадкой, а не нормой.** Если проверка вернула что-то непонятное,
 * честнее сказать «возможны перебои», чем «всё хорошо»: человек, которому сказали «всё хорошо»,
 * начнёт искать причину у себя — в своём интернете, браузере, руках.
 */
export const serviceStateOf = (probe: {
  reachable: boolean;
  allHealthy?: boolean;
}): ServiceState => {
  if (!probe.reachable) return 'down';
  if (probe.allHealthy === true) return 'ok';
  return 'degraded';
};

/**
 * Что человек прочитает.
 *
 * Тексты написаны для администратора учебного центра, а не для дежурного: ни «зависимостей», ни
 * «деградации», ни названий служб. Человеку нужно понять три вещи — работает ли, чем это грозит
 * его сегодняшним делам и что делать сейчас.
 */
export const serviceStatusView = (state: ServiceState): ServiceStatusView => {
  switch (state) {
    case 'ok':
      return {
        state,
        title: 'Система работает',
        what: 'Обучение, экзамены и выдача документов доступны.',
        next: 'Если у вас что-то не открывается — дело, скорее всего, в вашем интернете или в браузере: попробуйте обновить страницу.'
      };
    case 'degraded':
      return {
        state,
        title: 'Работает с перебоями',
        what: 'Часть действий может выполняться медленно или не с первого раза. Данные при этом не теряются: незавершённое действие можно повторить.',
        next: 'Повторите через несколько минут. Если вы в середине экзамена — не закрывайте вкладку, ответы сохранятся при восстановлении связи.'
      };
    default:
      return {
        state,
        title: 'Система недоступна',
        what: 'Мы уже знаем о неполадке и работаем над ней.',
        next: 'Зайдите позже. Экзамены, начатые до сбоя, не сгорают — попытка сохранится.'
      };
  }
};

/**
 * Текст о плановых работах.
 *
 * ТЗ просит «понятный текст о плановых работах». Он общий, а не про конкретную дату: конкретные
 * даты объявляет владелец, и хранить их в коде значило бы выкладывать релиз ради каждой.
 */
export const PLANNED_MAINTENANCE_NOTE =
  'Плановые работы проводятся ночью и заранее объявляются учебным центрам. Во время работ система может быть недоступна до часа; начатые экзамены при этом не сгорают.';
