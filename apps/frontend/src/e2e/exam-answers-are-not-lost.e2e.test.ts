import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { fromApp } from './app-root';
import { stripComments } from './backend-source';

/**
 * Обещание экрана экзамена исполняется (ТЗ «Стабилизация, UX и развитие», 10.1 / 10.2).
 *
 * **Что показала обязательная сверка по коду.** Подозрение ТЗ («ответы удерживаются на клиенте
 * до завершения теста») НЕ подтвердилось: автосохранение на сервер, досохранение перед сдачей,
 * блокировка сдачи при несохранённом ответе, предупреждение при уходе со страницы и
 * идемпотентность по паре «попытка + вопрос» уже были и работали. Срок попытки тоже живёт на
 * сервере, а брошенные попытки закрывает сканер.
 *
 * **Что было сломано.** Экран при пропаже связи обещает: «отправим, как только сеть вернётся».
 * Обработчик события `online` при этом менял только НАДПИСЬ — досылки не запускалось ни одной.
 * Автосохранение перезапускается сменой вопроса или правкой ответа, поэтому человек, ответивший
 * офлайн и оставшийся на том же вопросе, ждал досылки, которой не будет.
 *
 * Здесь закреплено: обещание и механизм связаны. Появится текст без досылки — сторож покраснеет.
 */

const SCREEN = fromApp('src', 'features', 'test-player', 'test-attempt-screen.tsx');
const CONNECTION = fromApp('src', 'features', 'test-player', 'connection.ts');

const codeOf = (file: string): string => stripComments(readFileSync(file, 'utf8'));

describe('ответы на экзамене не теряются (ТЗ 10.1)', () => {
  it('экран обещает досылку — значит, досылка существует', () => {
    const promise = codeOf(CONNECTION);
    expect(
      /отправим, как только сеть вернётся/.test(promise),
      'проверка привязана к тексту обещания: нет обещания — нечего и требовать'
    ).toBe(true);

    const screen = codeOf(SCREEN);
    expect(
      /shouldResend\(/.test(screen) && /pendingPayloads\(/.test(screen),
      'обещание досылки обязано быть подкреплено механизмом: раньше обработчик `online` менял ' +
        'только надпись, и ответ, данный офлайн, висел несохранённым до смены вопроса'
    ).toBe(true);
  });

  it('досылка повторяется по времени, а не по одному событию связи', () => {
    /* Связь возвращается рывками: первый запрос после неё часто ещё падает. */
    const screen = codeOf(SCREEN);
    const block = screen.slice(screen.indexOf('shouldResend('));
    expect(/setInterval\(resend, RESEND_POLICY\.intervalMs\)/.test(block)).toBe(true);
  });

  it('возвращение в начатую попытку не молчит', () => {
    const screen = codeOf(SCREEN);
    expect(
      /resumeNotice\(/.test(screen) && /attempt-resume-notice/.test(screen),
      'ответы подставлялись обратно молча: человек не знал, продолжает он попытку или начал ' +
        'заново — ТЗ требует сказать прямо'
    ).toBe(true);
  });

  it('отсчёт времени идёт по часам СЕРВЕРА, а не устройства (ТЗ 10.2)', () => {
    /*
     * Инвариант прошлой починки (порция 25): отстающие часы слушателя показывали лишние
     * минуты, автосдача уезжала за срок, и попытка обнулялась вместе со всеми ответами.
     * Часы устройства здесь появиться не должны никогда.
     */
    const screen = codeOf(SCREEN);
    expect(/serverNow\(\)/.test(screen), 'остаток считается по серверному времени').toBe(true);
    expect(
      /remainingMsFromExpiry\(attempt\.expiresAt, Date\.now\(\)\)/.test(screen),
      'часы устройства в отсчёте экзамена запрещены'
    ).toBe(false);
  });
});
