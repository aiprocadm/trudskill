import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { fromApp } from './app-root';
import { stripComments } from './backend-source';

/**
 * Первое, что видит человек, — не пустой белый лист (ТЗ 7.3 / В3).
 *
 * **Что было.** Пока едет сессия, `ProtectedRoute` показывал серый прямоугольник «Проверяем
 * сессию…» в левом верхнем углу пустой белой страницы. То же самое показывала корневая
 * загрузка Next.js. Человек видел это на КАЖДОМ входе и после каждого обновления вкладки, и
 * выглядело это не как «идёт загрузка», а как поломка. На медленной сети такой экран живёт
 * секундами — достаточно, чтобы решить, что система не работает, и нажать обновление ещё раз
 * (журнал 564).
 *
 * **Что закреплено.** Оба места показывают `BootSplash` — страницу целиком, с каркасом
 * будущего содержимого. Сам компонент проверяется своим сторожем в пакете `ui`; здесь
 * проверяется, что им ПОЛЬЗУЮТСЯ, а это разные вещи: готовый и не подключённый механизм —
 * самая частая находка в этом коде.
 */

const guards = stripComments(
  readFileSync(fromApp('src', 'features', 'auth', 'guards.tsx'), 'utf8')
);
const rootLoading = stripComments(readFileSync(fromApp('app', 'loading.tsx'), 'utf8'));

describe('экран загрузки подключён, а не просто написан (ТЗ 7.3)', () => {
  it('страж защищённой страницы показывает каркас приложения', () => {
    /* `frame` по умолчанию — «app»: человек уже внутри, каркас его и ждёт. */
    expect(guards).toMatch(/if \(loading\) return <BootSplash \/>;/);
  });

  it('страница входа каркаса приложения не обещает', () => {
    /* Меню на входе не появится; нарисовать его значило бы соврать о том, что будет дальше. */
    expect(guards).toMatch(/if \(loading\) return <BootSplash frame="plain"/);
  });

  it('корневая загрузка страницы — тоже каркас', () => {
    expect(rootLoading).toContain('BootSplash');
  });

  it('серый прямоугольник в углу не вернулся', () => {
    /*
     * Ищем постройку «показать LoadingState вместо экрана загрузки», а не слово: сам по себе
     * `LoadingState` остаётся законным внутри разделов, где грузится кусок уже открытой
     * страницы. Запрещено им подменять загрузку ВСЕГО приложения.
     */
    expect(guards, 'страж маршрута снова показывает надпись в углу').not.toMatch(
      /return <LoadingState|className="ui-loading"/
    );
    expect(rootLoading).not.toMatch(/GlobalLoading|LoadingState/);
  });

  it('подписи говорят, что происходит, а не техническим словом', () => {
    /* «Перенаправление...» ничего не сообщает администратору учебного центра. */
    expect(guards).not.toContain('Перенаправление');
    expect(guards).toContain('Открываем нужный раздел');
  });
});
