import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { fromApp } from './app-root';
import { stripComments } from './backend-source';
import { PRIVACY_POLICY_HREF, privacyPolicyMissing } from '../features/legal/privacy-link';

/**
 * Согласие даётся осознанно, а копии проверяются (ТЗ 17.3 и 17.4, решение владельца Р18).
 *
 * **Что было с согласием (журнал 579).** Человек ставил галочку «Даю согласие на обработку
 * персональных данных (152-ФЗ)» — и не имел никакой возможности прочитать, на что соглашается.
 * Ссылки на политику не было ни рядом с галочкой, ни где-либо ещё в продукте.
 *
 * Это не придирка к оформлению. Согласие по закону должно быть ИНФОРМИРОВАННЫМ: человек
 * соглашается на конкретную обработку конкретных данных конкретным лицом. Галочка без
 * доступного текста — подпись под пустым листом, и юридически она стоит ровно столько же.
 *
 * **Что было с копиями (журнал 580).** Регламент резервного копирования, заданный решением Р18,
 * не был записан НИГДЕ. Порядок восстановления, целевые показатели и правило ежемесячной
 * проверки жили в чьей-то голове — то есть в момент настоящей аварии их бы не было.
 */

const backup = readFileSync(fromApp('..', '..', 'docs', 'ops', 'backup.md'), 'utf8');
const proctoring = stripComments(
  readFileSync(fromApp('src', 'features', 'proctoring', 'screens.tsx'), 'utf8')
);
const identity = stripComments(
  readFileSync(fromApp('src', 'features', 'identity-verification', 'screens.tsx'), 'utf8')
);

describe('рядом с каждой галочкой согласия есть текст (ТЗ 17.3)', () => {
  it.each([
    ['видеозапись экзамена', proctoring],
    ['подтверждение личности', identity]
  ])('%s: ссылка на политику стоит рядом с галочкой', (_where, source) => {
    /*
     * Проверяем ПОСТРОЙКУ «в подписи галочки есть ссылка», а не наличие слова: упоминание
     * политики в комментарии ничего не даёт человеку, который смотрит на экран.
     */
    expect(source).toMatch(/PRIVACY_POLICY_HREF/);
    expect(source).toMatch(/согласие[\s\S]{0,400}PRIVACY_POLICY_LABEL/i);
  });

  it('страница политики существует и открывается без входа', () => {
    /*
     * Политику читают ДО входа и вообще без учётной записи: слушатель переходит по ссылке из
     * письма-приглашения, работодатель проверяет, кому отдаёт данные сотрудников. Требовать
     * вход, чтобы прочитать, на что соглашаешься, — то же самое, что не показывать текст.
     */
    const nav = readFileSync(fromApp('src', 'features', 'navigation', 'model.ts'), 'utf8');
    expect(nav).toMatch(/pattern: '\/legal\/privacy', meta: \{ public: true \}/);
    expect(PRIVACY_POLICY_HREF).toBe('/legal/privacy');
  });

  it('сотруднику и слушателю говорят разное, когда политики нет', () => {
    /*
     * Сотруднику нужно знать, что делать, — это его задача. Слушателю задачу давать нельзя: он
     * не может ни загрузить политику, ни повлиять на это, и «обратитесь в центр» здесь
     * единственное честное указание.
     */
    const staff = privacyPolicyMissing('staff');
    const learner = privacyPolicyMissing('learner');
    expect(staff.action, 'сотруднику не сказали, что делать').toBeTruthy();
    expect(learner.action, 'слушателю дали задачу, которую он не может выполнить').toBeUndefined();
    expect(learner.hint).toMatch(/обратитесь/i);
  });
});

describe('регламент резервного копирования записан (ТЗ 17.4, Р18)', () => {
  it('называет все числа, заданные решением владельца', () => {
    /*
     * Числа Р18 не переоткрываются, и регламент без них — это текст «про бэкапы вообще», по
     * которому в момент аварии ничего не решить.
     */
    for (const value of ['1 час', '4 часа', '30 дней', '12 месяцев']) {
      expect(backup, `в регламенте нет значения «${value}»`).toContain(value);
    }
    /*
     * Показатели проверяются ИМЕННО В ТАБЛИЦЕ, а не «где-нибудь в тексте». Испорченная
     * таблица при уцелевшем упоминании ниже — это противоречивый документ, и в момент аварии
     * читать будут таблицу: подсадкой поймано, что одного упоминания мало.
     */
    expect(backup, 'в таблице показателей испорчен RPO').toMatch(/\(RPO\)[^|]*\|\s*1 час\s*\|/);
    expect(backup, 'в таблице показателей испорчен RTO').toMatch(/\(RTO\)[^|]*\|\s*4 часа\s*\|/);
  });

  it('говорит, что копии лежат не на том же сервере', () => {
    /* Самая частая причина потери — отказ на самом сервере, и копия рядом гибнет вместе с ним. */
    expect(backup).toMatch(/не на том же сервере|не лежат на том же сервере/i);
  });

  it('содержит порядок восстановления по шагам', () => {
    expect(backup).toMatch(/## 4\. Как восстановить/);
    /* Первый шаг именно этот: иначе во время восстановления продолжат приходить новые данные. */
    expect(backup).toMatch(/1\. \*\*Остановить приём запросов/);
  });

  it('требует ежемесячной проверки и записи результата', () => {
    /*
     * Главное правило: непроверенная копия считается отсутствующей. Копия, которую ни разу не
     * разворачивали, — это не копия, а надежда.
     */
    /*
     * Правило объявлено во введении и повторено в разделе проверки — намеренно, это главное
     * правило документа. Проверяем ОБА места: потеря одного превращает регламент в такой,
     * где правило легко не заметить.
     */
    expect(
      backup.match(/непроверенная копия считается отсутствующей/gi)?.length ?? 0,
      'главное правило регламента должно стоять и во введении, и в разделе проверки'
    ).toBeGreaterThanOrEqual(2);
    expect(backup).toMatch(/раз в месяц/i);
    expect(backup, 'не сказано, что запись обязательна и при успехе').toMatch(
      /даже когда всё прошло гладко/i
    );
  });

  it('называет, кто принимает решение о восстановлении', () => {
    /*
     * Восстановление стирает данные, появившиеся после точки восстановления. Этот размен — не
     * техническое решение, и принимать его должен не тот, кто первым заметил проблему.
     */
    expect(backup).toMatch(/## 6\. Кто отвечает/);
    expect(backup).toMatch(/Владелец продукта/);
  });
});
