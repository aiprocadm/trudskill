import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { fromApp } from './app-root';
import { staticSecurityHeaders } from '../lib/security/csp';

/**
 * Базовая гигиена безопасности (ТЗ «Стабилизация, UX и развитие», 17.5).
 *
 * **Что уже было и переделывать не пришлось.** Политика безопасности содержимого с одноразовым
 * числом на каждый ответ, запрет угадывания типа файла, ограничение того, что уходит в
 * `Referer`, список разрешённых устройств, запрет открывать систему в чужой рамке, строгий HTTPS
 * в боевом контуре. Секреты живут в переменных окружения, и это стерегут отдельные проверки.
 *
 * **Чего не было (журнал 582).** Проверки зависимостей на известные уязвимости — ни команды, ни
 * упоминания. Первый же прогон нашёл **51 уязвимость, из них 2 критические**: обе в Next.js
 * версии 16.3.0 — удалённое выполнение кода БЕЗ ВХОДА в систему. Чинилось обновлением
 * патч-версии, то есть лежало на поверхности всё это время и просто некому было посмотреть.
 */

const rootPackageJson = JSON.parse(readFileSync(fromApp('..', '..', 'package.json'), 'utf8')) as {
  scripts?: Record<string, string>;
};

describe('заголовки безопасности на месте (ТЗ 17.5)', () => {
  const headers = staticSecurityHeaders(true);
  const byKey = new Map(headers.map((h) => [h.key, h.value]));

  it.each([
    [
      'X-Content-Type-Options',
      'браузер угадывал бы тип файла и мог выполнить загруженное как скрипт'
    ],
    ['Referrer-Policy', 'адреса с идентификаторами уходили бы на чужие сайты целиком'],
    [
      'Permissions-Policy',
      'страница могла бы без спроса просить камеру, микрофон и местоположение'
    ],
    ['Strict-Transport-Security', 'первый заход мог бы пройти без шифрования']
  ])('%s объявлен', (key) => {
    expect(byKey.has(key), `заголовок ${key} пропал`).toBe(true);
  });

  it('строгий HTTPS включается только в боевом контуре', () => {
    /*
     * На машине разработчика он сделал бы адрес недоступным по обычному протоколу на месяцы
     * вперёд — браузер запоминает это надолго и сбросить трудно.
     */
    const dev = staticSecurityHeaders(false).map((h) => h.key);
    expect(dev).not.toContain('Strict-Transport-Security');
  });

  it('систему нельзя открыть в чужой рамке', () => {
    /*
     * Иначе чужой сайт показывает наш экран внутри себя и подставляет поверх свои кнопки:
     * человек думает, что нажимает одно, а нажимает другое.
     */
    const csp = readFileSync(fromApp('src', 'lib', 'security', 'csp.ts'), 'utf8');
    expect(csp).toMatch(/frame-ancestors 'self'/);
  });
});

describe('зависимости проверяются на известные уязвимости (ТЗ 17.5)', () => {
  it('команда проверки объявлена', () => {
    /*
     * Чужой код составляет бо́льшую часть того, что мы запускаем, и уязвимости в нём находят
     * каждую неделю. Без команды проверять его некому и нечем — что и подтвердил первый
     * прогон: 51 уязвимость, две критические (журнал 582).
     */
    expect(rootPackageJson.scripts?.['audit:deps'], 'команда проверки исчезла').toBeTruthy();
  });

  it('проверка не отключена молча', () => {
    /*
     * Самый простой способ «починить» такую проверку — приписать к ней то, что всегда
     * возвращает успех. Тогда она остаётся в списке команд и ничего не значит.
     */
    const command = rootPackageJson.scripts?.['audit:deps'] ?? '';
    expect(command).toContain('pnpm audit');
    expect(command, 'проверка всегда сообщает об успехе').not.toMatch(/\|\|\s*true|;\s*exit 0/);
  });

  it('проверка смотрит на то, что уходит в бой', () => {
    /*
     * `--prod` — это зависимости работающей системы, а не инструменты разработки. Уязвимость в
     * сборщике неприятна, уязвимость в том, что крутится на сервере с персональными данными, —
     * совсем другой разговор, и путать их в одном отчёте значит утопить второе в первом.
     */
    expect(rootPackageJson.scripts?.['audit:deps'] ?? '').toContain('--prod');
  });

  it('порог не опущен ниже высокого', () => {
    /* Иначе проверка молчит про то, ради чего заводилась. */
    const command = rootPackageJson.scripts?.['audit:deps'] ?? '';
    expect(command).toMatch(/--audit-level (high|critical)/);
  });
});
