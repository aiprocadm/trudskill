import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { fromApp } from './app-root';
import { stripComments } from './backend-source';
import { lockCaption } from '../features/course-viewer/study-flow';

/**
 * Слушателю есть чем двинуться дальше (ТЗ 2.5.b / Б7).
 *
 * **Как было.** Кнопки «Материал изучен → Далее» не существовало вовсе: прогресс двигался
 * только счётчиком времени просмотра, и человек не понимал, засчиталось ли ему что-нибудь. У
 * замка стояла общая подпись «Закрыт: сначала пройдите предыдущие уроки» — какие именно, не
 * сказано, а в модуле из семи материалов это загадка, а не подсказка.
 *
 * **Что закреплено.** Три требования ТЗ, каждое проверяется на своём месте:
 *
 * 1. Кнопка есть и вызывает сохранение отметки — а не просто нарисована.
 * 2. Кнопка никогда не гаснет молча: рядом всегда показывается причина.
 * 3. У замка подпись строится по названию материала-виновника, а не общей фразой.
 *
 * Правила движения проверяются отдельно и по существу — `study-flow.test.ts` гоняет чистые
 * функции таблицей случаев. Здесь только то, что нельзя увидеть изнутри модуля: подключено ли
 * это к экрану вообще.
 */

const SCREEN = fromApp('src', 'features', 'course-viewer', 'course-viewer-screen.tsx');
const TOC = fromApp('src', 'features', 'course-viewer', 'table-of-contents.tsx');

const codeOf = (file: string): string => stripComments(readFileSync(file, 'utf8'));

describe('слушатель может двинуться дальше (ТЗ 2.5.b)', () => {
  it('кнопка «Материал изучен» есть и действительно сохраняет отметку', () => {
    const code = codeOf(SCREEN);

    expect(
      /Материал изучен/.test(code),
      'кнопки не было вовсе: прогресс двигался только счётчиком времени, и человек не понимал, ' +
        'засчиталось ли ему что-нибудь'
    ).toBe(true);

    /* Нарисованная кнопка без обработчика — обещание, которого экран не исполнит. */
    expect(
      /onClick=\{\(\) => void markStudied\(\)\}/.test(code),
      'кнопка обязана вызывать сохранение отметки'
    ).toBe(true);
    expect(
      /upsertProgress\(\{/.test(code.slice(code.indexOf('markStudied'))),
      'сохранение отметки обязано уходить на сервер'
    ).toBe(true);
  });

  it('кнопка не гаснет молча: причина показывается рядом', () => {
    const code = codeOf(SCREEN);
    const block = code.slice(code.indexOf('course-material-done'));

    expect(
      /study\.reason/.test(block),
      'погашенная кнопка без объяснения — тупик: человек жмёт и не понимает, почему не работает'
    ).toBe(true);
    expect(
      /disabled=\{!study\.enabled/.test(block),
      'доступность кнопки обязана считаться правилом, а не на месте'
    ).toBe(true);
  });

  it('подпись у замка называет материал-виновника', () => {
    const code = codeOf(TOC);

    /*
     * Замер переписан 18.09 (ТЗ 6.5, журнал 503). Прежняя редакция искала в оглавлении ВЫЗОВЫ
     * `blockingMaterialTitle(` и `lockCaption(` — то есть следила за МЕСТОМ сборки подписи.
     * Стоило перенести решение в общую `materialLockReason` (она учитывает второй замок —
     * ворота раздела), как сторож покраснел, хотя требование ТЗ соблюдено лучше прежнего.
     * Инвариант не ослаблен, а привязан к поведению: проверяются ЗНАЧЕНИЯ подписи.
     */
    expect(
      /materialLockReason\(/.test(code),
      'причина замка обязана считаться одним правилом, а не собираться на месте'
    ).toBe(true);
    expect(
      lockCaption('Текст инструктажа'),
      'ТЗ требует подпись «Откроется после изучения „…“» — с названием, а не общей фразой'
    ).toBe('Откроется после изучения «Текст инструктажа»');

    /* Общая фраза как ЕДИНСТВЕННЫЙ вариант — это и есть прежнее поведение. */
    expect(
      /сначала пройдите предыдущие уроки/.test(code),
      'прежняя общая подпись обязана исчезнуть: она ничего не подсказывает'
    ).toBe(false);

    expect(
      /course-toc__material-reason/.test(code),
      'причина обязана быть видна глазом, а не только читалке'
    ).toBe(true);
  });

  it('подпись у замка оформлена — класс без стилей ничего не значит', () => {
    /*
     * Урок журнала 400: класс в разметке — такая же ссылка, как импорт, но за ней не следит ни
     * проверка типов, ни один сторож. Проверяем существование правила в пакете оформления.
     */
    const styles = readFileSync(
      fromApp('..', '..', 'packages', 'ui', 'src', 'styles', 'course-viewer.ts'),
      'utf8'
    );
    expect(styles).toContain('.course-toc__material-reason');
  });
});
