import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { fromApp } from './app-root';
import { BACKEND_SRC, stripComments } from './backend-source';

/**
 * Экран государственных выгрузок не утверждает доставку, которой нет.
 *
 * «Мастер формирования пакета» на `/admin/gov-export` создаёт задачу выгрузки, и весь путь
 * заканчивается у адаптера провайдера. Ни один адаптер (`frdo`, `eisot`, `email`, `webinar`,
 * `proctoring`) не переопределяет `sendExportBatch`: все они — восьмистрочные наследники
 * `BaseAdapter`, объявляющие только свой код. Базовая реализация ничего никуда не передаёт —
 * она возвращает `status: 'completed'` и выдуманный номер партии.
 *
 * Цена лжи здесь выше обычной. Экран показывал человеку: «Реестр: ФИС ФРДО · Что выгружали:
 * Слушатели · Готово», а рядом журнал с колонками «Что отправляли», «Итог: Принято», «Ответ
 * сервиса: 200» и подписью «Здесь видно, что и когда ушло в реестр и как ведомство ответило».
 * Администратор учебного центра делает единственно возможный вывод: данные приняты
 * Рособрнадзором. На деле за 19 миллисекунд не прочитано ни одной записи слушателя и наружу
 * не ушло ни одного байта — проверено живьём на стенде (журнал 387).
 *
 * Настоящая подача в реестр в продукте ЕСТЬ и работает иначе: разделы ниже собирают ФАЙЛ
 * (XML/XLSX), который человек подаёт сам через личный кабинет ведомства. Соседство честного
 * файла и молчащей заглушки и делало заглушку убедительной.
 *
 * Сторож строит соответствие сам: он смотрит, появился ли у кого-то из адаптеров настоящий
 * `sendExportBatch`, и требует предупреждение ровно до тех пор, пока его нет. Когда появится
 * живая отправка — сторож покраснеет и потребует предупреждение снять. Так заметка не
 * переживёт причину, по которой её поставили.
 */

const ADAPTERS = join(BACKEND_SRC, 'modules', 'integrations', 'adapters');
const SCREEN = fromApp('src', 'features', 'gov-export', 'gov-export-screen.tsx');

/** Адаптеры провайдеров — без базового класса и объявления интерфейса. */
const providerAdapters = (): string[] =>
  readdirSync(ADAPTERS).filter(
    (entry) => entry.endsWith('.adapter.ts') && entry !== 'base.adapter.ts'
  );

/** Настоящая отправка = адаптер провайдера переопределил `sendExportBatch`. */
const adaptersThatSend = (): string[] =>
  providerAdapters().filter((entry) =>
    /\bsendExportBatch\s*\(/.test(readFileSync(join(ADAPTERS, entry), 'utf8'))
  );

/**
 * Формулировки, утверждающие ЧУЖОЕ действие: что данные ушли наружу и что ведомство их
 * приняло. Про собственную работу системы («пакет собран», «перед подачей сверьте») говорить
 * можно и нужно — запрещено только приписывать поступок ведомству.
 */
const DELIVERY_CLAIMS: Array<{ pattern: RegExp; why: string }> = [
  { pattern: /['"]Принято['"]/, why: 'подпись «Принято» — это ответ ведомства, которого не было' },
  { pattern: /ушло в реестр/, why: 'ничего в реестр не уходило' },
  { pattern: /ведомство ответило/, why: 'ведомство не отвечало — обмена не происходило' },
  { pattern: /Что отправляли/, why: 'не отправляли: пакет остался внутри системы' },
  { pattern: /Ответ сервиса/, why: 'сервиса на том конце нет, отвечать некому' }
];

describe('экран выгрузок не утверждает доставку, которой нет', () => {
  it('пока ни один адаптер не умеет отправлять — «Мастер» несёт предупреждение', () => {
    const sending = adaptersThatSend();
    if (sending.length > 0) {
      throw new Error(
        `Появилась настоящая отправка (${sending.join(', ')}). Предупреждение на экране ` +
          'государственных выгрузок больше не верно — снимите его и обновите этого сторожа.'
      );
    }

    const screen = readFileSync(SCREEN, 'utf8');
    expect(
      screen.includes('data-testid="export-wizard-delivery-notice"'),
      'блок «Мастер формирования пакета» обязан честно сказать, что пакет никуда не отправляется'
    ).toBe(true);
    expect(
      /не отправля|не уходит|не передаёт/.test(screen),
      'предупреждение обязано сказать это словами, а не намёком'
    ).toBe(true);
  });

  it('экран не приписывает ведомству получение и приём данных', () => {
    /*
     * Комментарии снимаются: человеку они не показываются, а объяснение «почему убрали
     * колонку „Что отправляли“» обязано называть её своим именем. Сторож, который считает
     * пояснение нарушением, вынуждает писать пояснения загадками.
     */
    const screen = stripComments(readFileSync(SCREEN, 'utf8'));
    const found = DELIVERY_CLAIMS.filter(({ pattern }) => pattern.test(screen)).map(
      ({ pattern, why }) => `${String(pattern)} — ${why}`
    );
    expect(found, `утверждения о доставке на экране выгрузок:\n${found.join('\n')}`).toEqual([]);
  });
});
