import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { fromApp } from './app-root';
import { stripComments } from './backend-source';
import { userMenuItems } from '../features/navigation/user-menu';
import {
  PROBLEM_REPORT_LABEL,
  PROBLEM_REPORT_MAX,
  problemReportError,
  safePage
} from '../features/support/problem-report';

/**
 * Дежурство и обращения (ТЗ «Стабилизация, UX и развитие», 15.2 и 15.5).
 *
 * **Что было с дежурством (журнал 584).** Проверка готовности, метрики и скрипт тревог в
 * проекте есть — а `docs/ops/runbook.md`, который ТЗ называет прямо, не было. То есть ответы на
 * «что делать при 503», «где логи», «как перезапустить», «как откатить релиз» жили в чьей-то
 * голове, и в час аварии дежурный выяснял бы их заново.
 *
 * **Что было с обращениями (журнал 583).** Кнопки «Сообщить о проблеме» не было вовсе. Человек,
 * у которого что-то не работает, обычно не может объяснить, что именно: «не открывается»,
 * «выдало ошибку», «всё пропало». Разговор уходит на выяснение, где он был и что нажимал, — и
 * половина сведений теряется, потому что человек уже ушёл с той страницы.
 */

const runbook = readFileSync(fromApp('..', '..', 'docs', 'ops', 'runbook.md'), 'utf8');
const screen = stripComments(
  readFileSync(fromApp('src', 'features', 'support', 'problem-report-screen.tsx'), 'utf8')
);

describe('дежурный знает, что делать (ТЗ 15.2)', () => {
  it('регламент отвечает на все четыре вопроса ТЗ', () => {
    for (const [what, pattern] of [
      ['что делать при 503', /503/],
      ['где логи', /## 3\. Где логи/],
      ['как перезапустить', /## 4\. Как перезапустить/],
      ['как откатить релиз', /## 5\. Как откатить релиз/]
    ] as const) {
      expect(runbook, `в регламенте нет ответа на «${what}»`).toMatch(pattern);
    }
  });

  it('первое действие — проверка готовности, а не чтение логов', () => {
    /*
     * Логи показывают следствие, проверка готовности — причину. Дежурный, начинающий с логов,
     * тратит первые двадцать минут на симптомы.
     */
    expect(runbook).toMatch(/health\/ready/);
    expect(runbook).toMatch(/## 1\. Первое действие/);
  });

  it('предупреждает не перезапускать всё подряд', () => {
    /* Перезапуск стирает следы, а причина возвращается через десять минут — уже вслепую. */
    expect(runbook).toMatch(/НЕ надо делать первым делом|не перезапускать всё подряд/i);
  });

  it('говорит, что база при откате релиза не откатывается', () => {
    /*
     * Откат базы — это потеря всего, что люди сделали после выкладки. Спутать его с откатом
     * кода в час аварии проще простого, и цена ошибки несопоставима.
     */
    expect(runbook).toMatch(/Базу при откате не откатывают/i);
  });

  it('называет, кто принимает решение о восстановлении из копии', () => {
    expect(runbook).toMatch(/Владелец продукта/);
  });
});

describe('«Сообщить о проблеме» доступно оттуда, где ломается (ТЗ 15.5)', () => {
  it('пункт стоит в меню человека', () => {
    /*
     * Не отдельным разделом: раздел — это место, куда ходят работать, а сюда приходят один раз
     * и в плохую минуту. И не внизу страницы: страница может не открыться — а сообщить о
     * проблеме нужно как раз тогда.
     */
    const labels = userMenuItems(null).map((item) => item.label);
    expect(labels).toContain(PROBLEM_REPORT_LABEL);
  });

  it('пункт доступен любому вошедшему, включая слушателя', () => {
    /*
     * Именно у слушателя чаще всего что-то не открывается, и именно он не дозвонится в центр
     * вечером. Ограничение по праву превратило бы кнопку в украшение для избранных.
     */
    const nav = readFileSync(fromApp('src', 'features', 'navigation', 'model.ts'), 'utf8');
    expect(nav).toMatch(/pattern: '\/support\/problem', meta: \{ public: false \}/);
    expect(nav, 'на обращение навесили право').not.toMatch(
      /'\/support\/problem'[^}]*requiredPermissions/
    );
  });
});

describe('обращение не превращается в канал утечки (ТЗ 15.5)', () => {
  it('из адреса вырезается строка запроса', () => {
    /*
     * В ней живут идентификаторы («?learner=l_8f3a…»), а по правилам продукта идентификатор —
     * не то, что показывают и пересылают.
     */
    expect(safePage('/learners?learner=l_8f3a&tab=docs')).toBe('/learners');
    expect(safePage('/groups/g1#section')).toBe('/groups/g1');
  });

  it('пустой адрес не притворяется страницей', () => {
    expect(safePage(undefined)).toBe('неизвестно');
  });

  it('экран не прикладывает снимок экрана и содержимое полей', () => {
    /*
     * На экранах этой системы почти всегда персональные данные слушателей: ФИО, СНИЛС,
     * паспортные фотографии. «Приложим побольше на всякий случай» превращает обращение в
     * поддержку в канал их утечки.
     */
    expect(screen, 'экран снимает изображение страницы').not.toMatch(
      /html2canvas|toDataURL|getDisplayMedia|screenshot/i
    );
    expect(screen, 'в обращение уходит содержимое полей').not.toMatch(
      /document\.querySelectorAll\('input'\)|FormData\(document/
    );
  });

  it('человеку показано, что именно уходит', () => {
    /*
     * Отправлять что-то «в фоне», не показав что, — верный способ, чтобы кнопкой перестали
     * пользоваться, как только кто-то один заглянет в отправляемое.
     */
    expect(screen).toMatch(/data-testid="problem-context"/);
    expect(screen).toMatch(/Вместе с обращением отправится/);
  });
});

describe('описание обязано быть осмысленным (ТЗ 15.5)', () => {
  it('пустое и слишком короткое не принимается', () => {
    /*
     * «Не работает» без продолжения не даёт дежурному ничего, и обращение всё равно вернётся
     * вопросом «а что именно?» — только через день.
     */
    expect(problemReportError('')).toMatch(/Опишите/);
    expect(problemReportError('ошибка')).toMatch(/подробнее/);
  });

  it('нормальное описание проходит', () => {
    expect(problemReportError('Нажимаю «Выдать документ», ничего не происходит')).toBeNull();
  });

  it('слишком длинное отсекается с подсказкой, куда девать главное', () => {
    const error = problemReportError('а'.repeat(PROBLEM_REPORT_MAX + 1));
    expect(error).toMatch(/самое важное — в начало/);
  });
});
