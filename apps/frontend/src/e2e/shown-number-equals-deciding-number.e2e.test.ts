import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { BACKEND_SRC } from './backend-source';
import { courseCompletionPercent, formatPercent } from '../features/course-viewer/completion';

/**
 * Класс сверки «число, показанное человеку, и число, по которому принимается решение, — одно
 * и то же» (режим ревизии, 2026-09-20; журнал 604).
 *
 * **Что было.** Долю пройденного курса считали в двух местах, и она расходилась дважды.
 *
 * 1. **Курс без материалов.** Сервер считал такой курс пройденным на 100% и ставил статус
 *    «завершён» — по нему выдаются документы. Экран показывал 0%.
 * 2. **Округление.** Сервер хранит два знака после запятой, экран округлял до целого: при
 *    79,6% человек видел «80%» и не понимал, почему его не допускают до экзамена.
 *
 * **Почему сторож смотрит в ИСХОДНИК сервера.** Правило живёт на сервере — по нему
 * принимается решение. Копия на экране законна (ни одно приложение не зависит от общего
 * пакета напрямую, а контракты правятся решением владельца), но копия без сторожа разъедется
 * молча: сегодня поправят порог на сервере, и экран останется показывать старое.
 */

const backendService = readFileSync(join(BACKEND_SRC, 'modules/mvp/mvp.service.ts'), 'utf8');

describe('доля пройденного считается одинаково на сервере и на экране (ТЗ, ревизия)', () => {
  it('курс без материалов — 100%, а не 0', () => {
    /*
     * Сервер по этому же правилу ставит статус «завершён» и выдаёт документы. Показывать
     * ноль значило бы показывать неправду: система считает обучение законченным.
     */
    expect(courseCompletionPercent(0, 0)).toBe(100);
  });

  it('правило сервера для пустого курса не изменилось', () => {
    /*
     * Проверяется КОНСТРУКЦИЯ в исходнике сервера, а не поведение: поведение здесь недоступно
     * — сервер в этот набор не поднимается (RISK-002). Поменяется правило на сервере —
     * сторож потребует поменять и копию.
     */
    expect(
      backendService,
      'на сервере изменилось правило для курса без материалов — поправьте копию на экране'
    ).toContain(
      'totalCount === 0 ? 100 : this.normalizePercent((completedCount / totalCount) * 100)'
    );
  });

  it('округление совпадает: два знака после запятой, а не целое', () => {
    /*
     * 79,6% — это НЕ 80%. Округление до целого показывает человеку ровно пороговое число
     * рядом с отказом, и объяснить это невозможно.
     */
    expect(courseCompletionPercent(199, 250)).toBe(79.6);
    expect(courseCompletionPercent(1, 3)).toBe(33.33);
  });

  it('правило округления на сервере не изменилось', () => {
    const normalize = backendService.slice(backendService.indexOf('private normalizePercent'));
    expect(
      normalize.slice(0, 260),
      'на сервере изменилось округление — поправьте копию на экране'
    ).toContain('Math.min(100, Math.max(0, Math.round(value * 100) / 100))');
  });

  it('рамки 0…100 держатся', () => {
    expect(courseCompletionPercent(5, 3)).toBe(100);
    expect(courseCompletionPercent(-1, 3)).toBe(0);
  });

  it('экран показывает число сервера, а не пересчитывает его сам', () => {
    /*
     * «Построено и не подключено» в миниатюре: правило вынесено, а экран продолжает считать
     * по-своему. Проверяется отсутствие прежней формулы и наличие вызова общего правила.
     */
    const screen = readFileSync(
      join(
        BACKEND_SRC,
        '..',
        '..',
        'frontend',
        'src',
        'features',
        'course-viewer',
        'course-viewer-screen.tsx'
      ),
      'utf8'
    );
    expect(screen).toContain('courseCompletionPercent(completedCount, totalCount)');
    expect(screen, 'экран снова считает долю сам').not.toMatch(
      /Math\.round\(\(completedCount \/ totalCount\) \* 100\)/
    );
  });

  it('подпись не прячет дробную часть и не пишет хвостовых нулей', () => {
    expect(formatPercent(80)).toBe('80%');
    expect(formatPercent(79.6)).toBe('79.6%');
    expect(formatPercent(33.33)).toBe('33.33%');
  });
});
