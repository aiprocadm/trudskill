import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { fromApp } from './app-root';
import { stripComments } from './backend-source';

/**
 * Форма не рисуется человеку, у которого она заведомо не отправится (ТЗ 2.4 / Б6).
 *
 * **Как было.** Слушателю без связи с карточкой показывали живую форму: выбери селфи, выбери
 * фото паспорта, поставь две галочки, нажми «Отправить на проверку» — и только тогда узнай,
 * что учётная запись не связана с личным делом. Галочки согласий при этом тоже не работали:
 * каждая давала свой отказ, и человек получал их россыпью.
 *
 * **Почему это не ловилось раньше.** Экран решал, показывать ли форму, по ответу ручки «мои
 * проверки»: `record === null` → «заявки ещё нет, покажем форму». Но та же ручка отвечает `null`
 * и когда карточки слушателя НЕТ ВООБЩЕ (`getMyIdentityVerification`: нет привязанных
 * `learnerIds` → `null`). Два разных состояния слиты в один ответ, и по нему отличить их нельзя.
 *
 * Сигнал на экране был всё это время: `/consents/me` честно отвечает `learner_not_linked`, потому
 * что согласия дают ЗА карточку слушателя. Его просто никто не читал.
 *
 * Здесь закреплено: решение о показе формы принимается по признаку связи, ДО формы, и признак
 * берётся не из «мои проверки».
 */

const SCREEN = fromApp('src', 'features', 'identity-verification', 'screens.tsx');
const SERVICE = fromApp('..', 'backend', 'src', 'modules', 'mvp', 'mvp.service.ts');

const screenCode = (): string => stripComments(readFileSync(SCREEN, 'utf8'));

describe('нет карточки слушателя — нет формы (ТЗ 2.4)', () => {
  it('экран спрашивает про связь и выходит РАНЬШЕ, чем доходит до формы', () => {
    const code = screenCode();

    /*
     * Признак обязан стоять УСЛОВИЕМ ветки, а не просто встречаться в файле.
     *
     * Первая версия этой проверки искала имя `isLearnerNotLinked` где угодно — и пропустила
     * подсаженную поломку `const notLinked = isLearnerNotLinked(...); if (false) {`: все слова
     * на месте, порядок верный, поведения нет. Текстовый сторож обязан смотреть на то, что
     * РЕШАЕТ, а не на то, что упомянуто.
     */
    const condition = /if\s*\(\s*isLearnerNotLinked\s*\(/.exec(code);
    expect(
      condition,
      'признак связи обязан быть условием ветки — иначе он ничего не решает'
    ).not.toBeNull();
    const checkAt = condition!.index;

    /*
     * Форма узнаётся по РАЗМЕТКЕ выбора файлов, а не по имени: `FilePicker` стоит ещё и в
     * списке импортов в начале файла — по имени «форма» оказалась бы раньше любой проверки.
     * (Ровно этот промах тест и поймал у меня самого при первом прогоне.)
     */
    const formAt = code.indexOf('<FilePicker');
    expect(
      formAt,
      'форма загрузки на экране обязана быть — иначе тест проверяет пустоту'
    ).toBeGreaterThan(-1);
    expect(
      checkAt < formAt,
      'проверка связи обязана стоять ДО формы: иначе человек снова выберет два файла и узнает ' +
        'правду только после нажатия «Отправить на проверку»'
    ).toBe(true);

    /* Выход, а не «спрячем кнопку»: галочки согласий тоже не работают без карточки. */
    const afterCheck = code.slice(checkAt, formAt);
    expect(
      /return\s*\(/.test(afterCheck),
      'из ветки «связи нет» экран обязан ВЫЙТИ: иначе ниже останутся нерабочие галочки согласий'
    ).toBe(true);
  });

  it('человеку дают следующий шаг, а не только отказ', () => {
    const code = screenCode();
    const checkAt = /if\s*\(\s*isLearnerNotLinked\s*\(/.exec(code)!.index;
    const branch = code.slice(checkAt, checkAt + 900);

    expect(
      /SystemMessage/.test(branch),
      'сообщение собирается общим компонентом — он держит шаблон «что случилось → что делать → ' +
        'к кому идти» (ТЗ 2.1)'
    ).toBe(true);
    expect(
      /href="\/chat"/.test(branch),
      'ТЗ требует кнопку «Написать в учебный центр» — без неё человеку некуда пойти'
    ).toBe(true);
  });

  it('признак связи НЕ берётся из ручки «мои проверки» — она про это не знает', () => {
    /*
     * Прямая проверка причины, а не следствия: `getMyIdentityVerification` возвращает `null`
     * и при отсутствии заявки, и при отсутствии карточки. Пока это так, решать по ней нельзя.
     * Если однажды ручка начнёт различать случаи, этот тест придётся осознанно переписать —
     * и это правильно: решение изменится.
     */
    const service = stripComments(readFileSync(SERVICE, 'utf8'));
    const start = service.indexOf('getMyIdentityVerification(');
    expect(start, 'ручка «мои проверки» обязана существовать').toBeGreaterThan(-1);
    const body = service.slice(start, start + 600);

    expect(
      /learnerIds\.size === 0\)\s*return null/.test(body),
      'пока «нет карточки» и «нет заявки» отвечают одинаковым null, отличать их по этой ручке ' +
        'нельзя — признак берётся из согласий'
    ).toBe(true);
  });
});
