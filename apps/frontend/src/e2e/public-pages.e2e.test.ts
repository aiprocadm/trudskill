import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { fromApp } from './app-root';
import { stripComments } from './backend-source';
import {
  PLANNED_MAINTENANCE_NOTE,
  serviceStateOf,
  serviceStatusView
} from '../features/status/service-status';

/**
 * Две публичные страницы-витрины (ТЗ «Стабилизация, UX и развитие», 18.2 и 18.3).
 *
 * **Кто их видит.** Проверку документа — работодатели и инспекторы, попавшие сюда со скана
 * QR-кода: про систему они не знают ничего. Состояние сервиса — администратор центра в тот
 * момент, когда «ничего не открывается».
 *
 * **Что было (журналы 586, 587).** Страницы состояния не было вовсе: при сбое центр звонил и
 * спрашивал, а ответ «мы уже чиним» приходилось повторять каждому. Страница проверки документа
 * существовала и была опрятной, но обрывалась на одном слове: «Аннулирован» — и всё. Работодатель
 * не знает, значит ли это подделку, ошибку центра или отзыв по существу; «Документ не найден» —
 * не знает, плохо считался код или перед ним подделка.
 */

const verify = stripComments(
  readFileSync(fromApp('src', 'features', 'verify', 'verify-page.tsx'), 'utf8')
);
const status = stripComments(
  readFileSync(fromApp('src', 'features', 'status', 'status-screen.tsx'), 'utf8')
);
const nav = readFileSync(fromApp('src', 'features', 'navigation', 'model.ts'), 'utf8');

describe('проверка документа объясняет результат (ТЗ 18.2)', () => {
  it('говорит, откуда сведения', () => {
    /* Человек со скана QR-кода не знает ни системы, ни того, кто подтверждает подлинность. */
    expect(verify).toMatch(/по данным учебного центра/i);
  });

  it('«не найден» называет обе причины, начиная с частой', () => {
    /*
     * Их две, и они противоположны: плохо считался код или подделка. Человек должен сначала
     * исключить первую — иначе честного слушателя обвинят в подлоге из-за бликов на бумаге.
     */
    /*
     * Требуем и ПРИЧИНУ, и ДЕЙСТВИЕ по каждой из двух версий. Проверка одного лишь действия
     * («отсканируйте ещё раз») проходила, когда объяснение причины вырезано, — а без причины
     * человек не понимает, зачем сканировать снова, и сразу думает о подделке.
     */
    expect(verify, 'не названа первая, частая причина').toMatch(/код считался не полностью/i);
    expect(verify, 'не сказано, что делать с первой причиной').toMatch(/отсканировать ещё раз/i);
    expect(verify, 'не сказано, куда идти со второй').toMatch(/обратитесь в учебный центр/i);
  });

  it('«аннулирован» объясняет, что это значит и куда идти', () => {
    /* Одно слово «Аннулирован» работодателю не говорит ничего. */
    expect(verify).toMatch(/больше не подтверждает обучение/i);
    expect(verify).toMatch(/За причиной обратитесь/i);
  });

  it('страница проверки по-прежнему публичная', () => {
    /* Её открывают с телефона, отсканировав бумажный документ, — входа тут быть не может. */
    expect(nav).toMatch(/pattern: '\/verify', meta: \{ public: true \}/);
  });
});

describe('состояние системы: три слова и ни одной подробности (ТЗ 18.3)', () => {
  it('служба не ответила — «недоступна»', () => {
    expect(serviceStateOf({ reachable: false })).toBe('down');
  });

  it('ответила и здорова — «работает»', () => {
    expect(serviceStateOf({ reachable: true, allHealthy: true })).toBe('ok');
  });

  it('непонятный ответ считается неполадкой, а не нормой', () => {
    /*
     * Человек, которому сказали «всё хорошо», начнёт искать причину у себя — в своём интернете,
     * браузере, руках. Честнее сказать «возможны перебои».
     */
    expect(serviceStateOf({ reachable: true })).toBe('degraded');
    expect(serviceStateOf({ reachable: true, allHealthy: false })).toBe('degraded');
  });

  it('каждое состояние говорит, что делать', () => {
    /* Даже «работает»: иначе человек, у которого не открывается, продолжит гадать. */
    for (const state of ['ok', 'degraded', 'down'] as const) {
      const view = serviceStatusView(state);
      expect(view.title.length, `${state}: нет заголовка`).toBeGreaterThan(0);
      expect(view.what.length, `${state}: не сказано, что это значит`).toBeGreaterThan(0);
      expect(view.next.length, `${state}: не сказано, что делать`).toBeGreaterThan(0);
    }
  });

  it('человека на экзамене успокаивают отдельно', () => {
    /*
     * Попытка бывает одна, и сбой посреди экзамена — самый страшный для слушателя случай.
     * Молчание об этом на странице состояния стоит дороже всего остального текста.
     */
    expect(serviceStatusView('degraded').next).toMatch(/экзамен/i);
    expect(serviceStatusView('down').next).toMatch(/не сгорают|сохранится/i);
  });

  it('наружу не уходит ни одной внутренней подробности', () => {
    /*
     * Публичная страница состояния — подсказка и посетителю, и тому, кто ищет, за что дёрнуть.
     * «Очередь задач переполнена» сообщает атакующему, что система под нагрузкой и чем её
     * добить.
     */
    const texts = (['ok', 'degraded', 'down'] as const)
      .map((state) => Object.values(serviceStatusView(state)).join(' '))
      .join(' ');
    expect(texts).not.toMatch(/база|redis|очеред|миграц|хранилищ|версия|сервер\b/i);
    expect(status, 'экран разбирает и показывает подробности проверки').not.toMatch(
      /response\.json\(\)/
    );
  });

  it('страница публичная и обновляется сама', () => {
    /*
     * Смотреть сюда приходят, когда войти не получается: страница состояния, требующая входа,
     * бесполезна ровно в тот момент, ради которого заведена. А человек оставляет вкладку
     * открытой и ждёт, когда починят.
     */
    expect(nav).toMatch(/pattern: '\/status', meta: \{ public: true \}/);
    expect(status).toMatch(/setInterval/);
  });

  it('про плановые работы сказано без конкретных дат', () => {
    /*
     * Конкретные даты объявляет владелец; хранить их в коде значило бы выкладывать релиз ради
     * каждой ночи работ.
     */
    expect(PLANNED_MAINTENANCE_NOTE).toMatch(/заранее объявляются/i);
    expect(PLANNED_MAINTENANCE_NOTE).not.toMatch(/\d{2}\.\d{2}\.\d{4}/);
  });
});
