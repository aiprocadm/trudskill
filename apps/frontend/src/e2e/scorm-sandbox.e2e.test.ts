import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

/**
 * Рамка SCORM-курса не ослабляется дальше.
 *
 * Журнал 127. Учебный курс — чужой код: пакет загружает администратор центра, но пишет
 * его сторонний производитель. Сейчас курс исполняется на том же источнике, что и
 * приложение, потому что мост «курс ↔ система» идёт через `window.API` родительского
 * окна: убрать `allow-same-origin` — сломать все курсы разом.
 *
 * **Решение (срез 54):** мост не переписываем. Перевод на обмен сообщениями и отдельный
 * источник — работа с инфраструктурой (свой поддомен, сертификат) и с риском поломать
 * уже загруженные курсы; менять это ради теоретического улучшения там, где на кону
 * работающие курсы центров, — плохой размен. Риск смягчён политикой ответов
 * (ФТ-G7: курсу разрешены свои скрипты и стили, запрещены отправка данных наружу,
 * подмена базового адреса и плагины).
 *
 * Но у решения есть цена: рамка обязана остаться **ровно такой**, какая есть. Одно
 * добавленное разрешение — и чужой код получит то, чего ему не давали. Этот тест держит
 * список разрешений неизменным: расширение требует осознанного решения, а не правки
 * «чтобы курс заработал».
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const PLAYER = join(HERE, '..', 'features', 'scorm', 'scorm-player.tsx');

/**
 * Разрешения рамки. Каждое — с ответом, зачем оно курсу.
 *
 * Чего здесь нет намеренно: `allow-top-navigation` (курс не должен уводить человека с
 * экрана экзамена), `allow-modals` (диалоги чужого кода поверх системы), `allow-downloads`
 * (файл от стороннего производителя мимо проверки).
 */
const ALLOWED = {
  'allow-scripts': 'курс это программа: без своих скриптов он не проигрывается',
  'allow-same-origin':
    'мост «курс ↔ система» идёт через window.API родительского окна; без этого не работает ни один курс',
  'allow-forms': 'внутри курса встречаются формы ответов',
  'allow-popups': 'часть курсов открывает справочные материалы отдельным окном'
};

describe('SCORM · рамка чужого кода не ослабляется', () => {
  const source = readFileSync(PLAYER, 'utf8');

  it('атрибут sandbox у рамки задан явно', () => {
    expect(source).toMatch(/sandbox="[^"]+"/);
  });

  it('набор разрешений ровно тот, что объяснён — ни одним больше', () => {
    const declared = (source.match(/sandbox="([^"]+)"/)?.[1] ?? '').split(/\s+/).filter(Boolean);
    const extra = declared.filter((token) => !(token in ALLOWED));
    const missing = Object.keys(ALLOWED).filter((token) => !declared.includes(token));

    expect(
      extra,
      `рамке добавили разрешения без объяснения:\n${extra.join('\n')}\n` +
        'Курс пишет сторонний производитель. Каждое разрешение — это то, что чужой код ' +
        'сможет сделать с экраном человека: объясните в ALLOWED, зачем оно.'
    ).toEqual([]);
    expect(
      missing,
      `разрешения пропали — курсы перестанут работать:\n${missing.join('\n')}`
    ).toEqual([]);
  });

  it('опасные разрешения не появились', () => {
    // Перечислены отдельно: их отсутствие — не побочный эффект списка, а само правило.
    for (const forbidden of ['allow-top-navigation', 'allow-modals', 'allow-downloads']) {
      expect(source, `рамке добавили ${forbidden}`).not.toContain(forbidden);
    }
  });
});
