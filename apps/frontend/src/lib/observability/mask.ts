/**
 * Маскирование персональных данных перед отправкой события о сбое (ТЗ 15.1, решение Р15).
 *
 * Р15 называет причину прямо: «в трассировки неизбежно попадают адреса страниц с
 * идентификаторами слушателей и фрагменты данных, то есть персональные данные». Свой сервер
 * сбора этого риска не снимает — он снимает только вопрос «куда».
 *
 * **Устройство защиты в два рубежа, и первый важнее.**
 *
 * Первый рубеж — НЕ ОТПРАВЛЯТЬ. Наружу уходит текст ошибки, стек, ШАБЛОН адреса и номер
 * запроса. Значения полей, тела запросов и ответов не отправляются вовсе: то, чего нет в
 * событии, невозможно раскрыть. Так закрыт вопрос ФИО — надёжно опознать русское имя в
 * свободном тексте нельзя («Иванов» и «Иванов день» неразличимы), а список фамилий был бы
 * решетом.
 *
 * Второй рубеж — вычистить то, что всё же попало в текст ошибки: СНИЛС, почта, телефон, токен.
 * Здесь работают узоры, а узор ошибается в обе стороны, поэтому на него и не возлагается
 * главная работа.
 */

/** СНИЛС: 11 цифр, с разделителями или без. */
const SNILS = /\b\d{3}[- ]?\d{3}[- ]?\d{3}[- ]?\d{2}\b/g;

/** Почта: имя прячем, домен оставляем — он говорит, чей это центр, и не является ПДн. */
const EMAIL = /\b[\w.+-]+@([\w-]+\.[\w.-]+)\b/g;

/** Телефон в любом привычном виде. */
const PHONE = /\+?\d[\d\s()-]{9,}\d/g;

/** Токен доступа: три части через точку (JWT) — с приставкой `Bearer` или без. */
const TOKEN = /\b(?:Bearer\s+)?[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{3,}\b/g;

/** Убирает из текста то, что не должно покидать периметр. */
export const maskSensitive = (text: string): string =>
  text
    .replace(TOKEN, '«токен скрыт»')
    .replace(EMAIL, (_match, domain: string) => `«почта скрыта»@${domain}`)
    .replace(SNILS, '«СНИЛС скрыт»')
    .replace(PHONE, '«телефон скрыт»');

/**
 * Похож ли участок адреса на код записи.
 *
 * Считаем кодом: приставку с подчёркиванием (`lrn_8f3k2m1p`), UUID, длинную мешанину букв и
 * цифр. Осмысленные участки (`gov-export`, `learners`) остаются: без имени раздела событие
 * бесполезно — непонятно, где именно сломалось.
 */
const looksLikeId = (segment: string): boolean => {
  if (/^[a-z][a-z-]*_[\w-]+$/i.test(segment)) return true;
  if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(segment)) return true;
  if (/^\d+$/.test(segment)) return true;
  return segment.length >= 12 && /\d/.test(segment) && /[a-z]/i.test(segment);
};

/** Адрес страницы → шаблон: коды записей заменяются, строка запроса отбрасывается целиком. */
export const maskRoute = (route: string): string => {
  const path = route.split('?')[0] ?? '';
  return (
    '/' +
    path
      .split('/')
      .filter(Boolean)
      .map((segment) => (looksLikeId(segment) ? '{id}' : segment))
      .join('/')
  );
};
