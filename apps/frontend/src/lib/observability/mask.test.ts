import { describe, expect, it } from 'vitest';

import { maskRoute, maskSensitive } from './mask';

/**
 * Маскирование персональных данных до отправки события (ТЗ «Стабилизация, UX и развитие», 15.1).
 *
 * Решение Р15 объясняет, почему это обязательно: «в трассировки неизбежно попадают адреса
 * страниц с идентификаторами слушателей и фрагменты данных, то есть персональные данные».
 * Отправлять их наружу — риск по 152-ФЗ, и он не снимается тем, что сервер сбора свой.
 *
 * **Главное решение здесь — не маскировать ФИО, а не отправлять то, где ФИО может оказаться.**
 * Надёжно опознать русское имя в свободном тексте нельзя: «Иванов» и «Иванов день» не
 * различить, а маскирование по списку фамилий превратится в решето. Поэтому наружу уходит
 * только то, что нужно для поиска причины: текст ошибки, стек, ШАБЛОН адреса и номер запроса.
 * Значения из данных не отправляются вовсе — маскировать нечего.
 *
 * То, что всё же может просочиться в текст ошибки, вычищается здесь: СНИЛС, почта, телефон,
 * токены. Это второй рубеж, а не первый.
 */

describe('маскирование перед отправкой', () => {
  it('СНИЛС не уходит наружу', () => {
    expect(maskSensitive('не найден слушатель со СНИЛС 112-233-445 95')).not.toContain('112-233');
    expect(maskSensitive('СНИЛС 11223344595 занят')).not.toContain('11223344595');
  });

  it('почта заменяется, но домен остаётся — по нему видно, чей это центр', () => {
    const masked = maskSensitive('письмо ivanov@uc-primer.ru не доставлено');
    expect(masked).not.toContain('ivanov');
    expect(masked, 'домен помогает понять, о каком центре речь, и не является ПДн').toContain(
      'uc-primer.ru'
    );
  });

  it('телефон не уходит наружу', () => {
    expect(maskSensitive('звонок на +7 916 123-45-67 не прошёл')).not.toContain('916');
  });

  it('токен доступа вырезается целиком', () => {
    const masked = maskSensitive(
      'отказ: Bearer eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiIxIn0.abc'
    );
    expect(masked).not.toContain('eyJhbGciOi');
  });

  it('обычный текст ошибки не портится', () => {
    const text = 'Не удалось загрузить список групп: сервер ответил 500';
    expect(maskSensitive(text)).toBe(text);
  });

  it('адрес превращается в шаблон: коды записей заменяются', () => {
    expect(maskRoute('/learners/lrn_8f3k2m1p/documents')).toBe('/learners/{id}/documents');
    expect(maskRoute('/courses/course_abc123')).toBe('/courses/{id}');
  });

  it('шаблон сохраняет осмысленные части адреса', () => {
    expect(
      maskRoute('/admin/gov-export'),
      'без имени раздела событие бесполезно — непонятно, где сломалось'
    ).toBe('/admin/gov-export');
  });

  it('строка запроса из адреса убирается целиком', () => {
    expect(maskRoute('/learners?q=Иванов&page=2')).toBe('/learners');
  });

  it('длинный код записи в адресе не выживает даже без приставки', () => {
    expect(maskRoute('/groups/7b3e4f1a-9c22-4d7e-8a11-0f2b3c4d5e6f')).toBe('/groups/{id}');
  });
});
