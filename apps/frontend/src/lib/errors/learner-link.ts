/**
 * «К этой учётной записи не привязана карточка слушателя» (ТЗ «Стабилизация, UX и развитие», 2.4).
 *
 * Отдельный признак, потому что это не ошибка в обычном смысле, а **состояние человека**: он
 * вошёл, всё работает, но учебный центр ещё не связал его учётную запись с карточкой слушателя.
 * Пока связи нет, ни согласия, ни подтверждение личности физически невозможны — и экран обязан
 * сказать это ОДИН раз вместо того, чтобы показывать форму, которая заведомо не отправится.
 *
 * Проверка вынесена сюда, потому что она уже жила в ДВУХ местах слово в слово (согласия и
 * подтверждение личности) — сравнением текста сообщения. Текст сообщения меняется, код отказа
 * нет; поэтому сначала смотрим код, а текст остаётся запасным путём для старых веток.
 */

const NOT_LINKED_CODE = 'learner_not_linked';

/** Код отказа, как его назвал сервер. */
const codeOf = (error: unknown): string => {
  const normalized = (error as { normalized?: { code?: unknown } } | null)?.normalized;
  return typeof normalized?.code === 'string' ? normalized.code : '';
};

export const isLearnerNotLinked = (error: unknown): boolean => {
  if (codeOf(error) === NOT_LINKED_CODE) return true;
  const message = error instanceof Error ? error.message : '';
  return message.includes(NOT_LINKED_CODE) || message.includes('No learner profile');
};

