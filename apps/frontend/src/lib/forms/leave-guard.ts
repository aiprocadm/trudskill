/**
 * Защита от потери несохранённых данных при уходе со страницы (ТЗ «Стабилизация, UX и
 * развитие», задача 10.3).
 *
 * **Что было.** В админских формах можно было набрать данные и уйти со страницы кликом по
 * меню — без единого вопроса. Боковые панели спрашивали (`CMP-010`, сторож
 * `drawer-unsaved-changes`), а страницы — нет: механизма для них не существовало вовсе.
 *
 * **Почему правила вынесены сюда отдельными функциями.** Перехват клика живёт в браузере, а
 * в проекте нет средства монтировать компоненты (`RISK-002`). Если правило «этот клик уводит
 * со страницы» останется внутри обработчика, проверить его будет нечем — а ошибка здесь
 * стоит дорого в обе стороны: пропустишь уход — человек потеряет работу; спросишь лишний раз
 * — человек привыкнет отмахиваться от вопроса и потеряет работу всё равно, но уже сам.
 */

/** Вопрос при уходе. Называет результат, а не действие (`TXT-002`). */
export const LEAVE_CONFIRM_TITLE = 'Уйти без сохранения?';

/**
 * Пояснение. Говорит, что именно потеряется и что можно сделать вместо ухода, — «вы уверены?»
 * не сообщает человеку ничего, чего он не знает (`TXT-004`).
 */
export const LEAVE_CONFIRM_MESSAGE =
  'Введённое на этой странице не сохранено. Если уйти сейчас, оно пропадёт. ' +
  'Можно остаться и нажать «Сохранить».';

export const LEAVE_CONFIRM_OK = 'Уйти без сохранения';
export const LEAVE_CONFIRM_CANCEL = 'Остаться на странице';

export interface LinkClick {
  /** Значение атрибута `href` у ссылки, по которой кликнули. */
  href: string;
  /** Адрес текущей страницы, без параметров запроса. */
  currentPath: string;
  /** Атрибут `target`: `_blank` открывает новую вкладку, а форма остаётся на месте. */
  target?: string | null;
  /** Ссылка со скачиванием файла страницу не покидает. */
  hasDownload?: boolean;
  /** Нажаты Ctrl / Cmd / Shift / средняя кнопка — браузер откроет новую вкладку. */
  opensNewTab?: boolean;
}

/**
 * Приведение адреса к сравнимому виду: параметры запроса и якорь отбрасываются, хвостовой
 * слеш не считается. Смена страницы — это смена адреса раздела, а не порядка сортировки:
 * спросить «уйти без сохранения?» при нажатии на заголовок колонки было бы издевательством.
 */
const normalizePath = (value: string): string => {
  const withoutHash = value.split('#')[0] ?? '';
  const withoutQuery = withoutHash.split('?')[0] ?? '';
  return withoutQuery.length > 1 ? withoutQuery.replace(/\/+$/, '') : withoutQuery;
};

/**
 * Уводит ли этот клик со страницы так, что набранное пропадёт.
 *
 * **Чего здесь намеренно нет: внешних адресов.** Уход на чужой сайт — это полная перезагрузка,
 * и её перехватывает сам браузер через `beforeunload`. Спросить ещё и здесь означало бы два
 * вопроса подряд на одно действие; человек ответит не читая, и вопрос перестанет работать
 * там, где он действительно нужен.
 */
export const leadsAwayFromForm = (click: LinkClick): boolean => {
  const { href, currentPath } = click;
  if (!href) return false;
  if (click.hasDownload === true) return false;
  if (click.opensNewTab === true) return false;
  if (click.target !== undefined && click.target !== null && click.target !== '_self') return false;

  /*
   * Наш переход — только внутренний адрес приложения, начинающийся со «/».
   *
   * Одним этим правилом отсекаются сразу три случая, и отдельных проверок им не нужно:
   * якорь на этой же странице (`#modules`), внешний сайт (`https://…`) и особые схемы
   * (`mailto:`, `tel:`). Проверки на них здесь стояли и были МЁРТВЫМИ — подсаженная поломка
   * их удаление не замечала, потому что поведение не менялось. Строка, которую нельзя
   * сломать, создаёт ложное чувство защиты, поэтому её тут нет.
   */
  if (!href.startsWith('/')) return false;

  /*
   * А вот это правило живое: `//example.ru` со слэша НАЧИНАЕТСЯ, но ведёт на чужой сайт.
   * Без него мы бы перехватили клик и сами отправили человека наружу.
   */
  if (href.startsWith('//')) return false;

  return normalizePath(href) !== normalizePath(currentPath);
};

/**
 * Надо ли сейчас удерживать человека.
 *
 * **Во время сохранения — нет.** Иначе вопрос выскакивает на самом сохранении: форма ещё
 * считается несохранённой, а переход после успеха уже начался. Человек видит «уйти без
 * сохранения?» ровно тогда, когда он нажал «Сохранить», — и перестаёт верить вопросу.
 */
export const shouldGuardLeave = (state: { dirty: boolean; saving?: boolean }): boolean =>
  state.dirty && state.saving !== true;
