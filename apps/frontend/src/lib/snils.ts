/**
 * СНИЛС: нормализация и проверка контрольной суммы по алгоритму ПФР (ФТ-C4.1).
 *
 * Общее место фронта. Раньше эти две функции жили внутри массового зачисления
 * (`features/bulk-enrollments/validators.ts`) — там, где их написали первыми. Форма
 * карточки слушателя до них не дотягивалась и потому не проверяла ничего: опечатка
 * уезжала в базу и всплывала только на выгрузке в госреестр, месяцы спустя.
 *
 * Зеркало серверной `apps/backend/src/modules/mvp/snils.util.ts`: решение всё равно
 * принимает сервер, здесь — мгновенная подсказка человеку, пока он смотрит на карточку.
 */

/** Только цифры: «112-233-445 95» и «11223344595» дают одно значение. */
export function normalizeSnils(input: string): string {
  return input.replace(/\D/g, '');
}

/**
 * Контрольная сумма СНИЛС (последние две цифры).
 *
 * Первые 9 цифр умножаются на позиции 9..1; сумма < 100 — она и есть контрольное число;
 * 100 или 101 — ноль; больше — остаток от деления на 101 (100 и 101 снова дают ноль).
 *
 * @param digits — нормализованные 11 цифр (см. `normalizeSnils`).
 */
export function isValidSnilsChecksum(digits: string): boolean {
  if (digits.length !== 11 || !/^\d{11}$/.test(digits)) return false;
  let sum = 0;
  for (let i = 0; i < 9; i++) {
    sum += Number(digits[i]) * (9 - i);
  }
  let computed: number;
  if (sum < 100) {
    computed = sum;
  } else if (sum === 100 || sum === 101) {
    computed = 0;
  } else {
    const mod = sum % 101;
    computed = mod === 100 || mod === 101 ? 0 : mod;
  }
  return computed === Number(digits.slice(9, 11));
}

/**
 * Подсказка под полем ввода: `null` — всё в порядке (в том числе когда поле пустое).
 *
 * Пустое значение молчит намеренно: СНИЛС обязателен для ВЫГРУЗКИ в реестр, а не для
 * карточки, и заводить слушателя без него разрешено. Ругаться на пустое поле в момент,
 * когда номера просто нет под рукой, — значит мешать работе без причины.
 *
 * Незаконченный ввод тоже молчит: пока человек печатает, красная надпись под полем
 * появлялась бы на первой же цифре и гасла на последней.
 */
export function snilsInputHint(value: string): string | null {
  const digits = normalizeSnils(value);
  if (digits.length === 0) return null;
  if (digits.length < 11) return null;
  if (digits.length > 11) return 'В СНИЛС 11 цифр — сейчас больше.';
  return isValidSnilsChecksum(digits)
    ? null
    : 'Номер не сходится по контрольной сумме — вероятна опечатка. Проверьте цифры по зелёной карточке.';
}
